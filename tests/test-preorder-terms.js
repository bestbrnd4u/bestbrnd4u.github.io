// Умови «під замовлення» — там, де людина ухвалює рішення.
//
// ПРО ЩО ЦЕ
// ----------
// Двадцять дев'ять товарів зі ста трьох — під замовлення. Це не
// виняток, а майже третина каталогу, і в кожного з них дві умови,
// яких немає у звичайного товару:
//
//   • чекати 10–14 робочих днів замість 1–3;
//   • заплатити наперед — 50% або 100%, поле preOrderPrepayment.
//
// Сторінка товару каже обидві чесно. Далі покупець іде вглиб і на
// кожному кроці бачить менше, ніж на попередньому, — а рішення
// ухвалює саме на останньому.
//
// ДВА МІСЦЯ, ДЕ УМОВА ЗНИКАЛА
// ----------------------------
// 1. ЗАКРІПЛЕНА СМУГА ВНИЗУ НА ТЕЛЕФОНІ. Основна кнопка каже
//    «Замовити», під нею — рамка з умовами. Але варто прокрутити на
//    екран нижче, і замість неї знизу з'являється смуга з написом
//    «Додати в кошик» — зашитим у розмітку. Саме її на телефоні й
//    натискають: основної на екрані вже немає.
//    Причина була в одному слові: refreshAvailability() шукала
//    кнопку через querySelector, тобто ПЕРШУ. Сама перевірка — у
//    test-stock.js [7], де вже стоїть jsdom для цієї функції.
//
// 2. СТОРІНКА ОФОРМЛЕННЯ. Кошик про довший термін попереджає, а
//    оформлення — ні. І там людина спокійно обирала «Готівкою при
//    отриманні на пошті», бо ніщо не підказувало, що з цим товаром
//    так не буде. Дізнавалась від менеджера — після того, як
//    магазин уже викупив річ за кордоном.
//
// ЧОГО ЦЕЙ НАБІР НЕ ВИМАГАЄ
// --------------------------
// Щоб спосіб оплати вимикався. Замовлення приймаємо будь-яке, умови
// менеджер узгодить — вимога лише одна: покажіть їх ДО вибору.
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (name, ok, extra) => {
    if (ok) console.log("  ✓", name);
    else { console.log("  ✗", name, extra !== undefined ? "→ " + extra : ""); failures++; }
};

const read = file => fs.readFileSync(path.join(ROOT, file), "utf8");

// Коментарі геть — інакше набір ловить сам себе.
//
// Вище в цьому ж файлі написано і «Додати в кошик», і «Готівкою при
// отриманні»: пояснення без слів, про які воно, не прочитаєш. У
// перевірених файлах те саме — я щойно дописав туди довгі коментарі.
// Тож шукаємо в коді, а не в розповіді про код.
const code = file => read(file)
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");

console.log("\n[1] Сторінка оформлення знає про передоплату");
{
    const html = code("checkout.html");
    const js = code("assets/js/checkout.js");

    check("у блоці оплати є місце під умову",
        /id="checkoutPreorderNote"/.test(html));

    // Саме в блоці оплати, а не десь у підсумку збоку: умова має
    // стояти там, де стоїть вибір, інакше її прочитають після.
    const paymentBlock = (html.match(/<h2>Оплата<\/h2>[\s\S]*?<\/div>\s*<\/div>/) || [""])[0];

    check("і воно саме в блоці «Оплата», поруч із вибором",
        /id="checkoutPreorderNote"/.test(paymentBlock));

    check("порожнє й сховане, поки товарів під замовлення немає",
        /<p class="preorder-banner" id="checkoutPreorderNote" hidden><\/p>/.test(html));

    check("оформлення заповнює його разом із підсумком",
        /showPreorderNote\(lines\);/.test(js));

    check("і робить це з того самого переліку, що й суму",
        js.indexOf("showPreorderNote(lines);") > js.indexOf("const lines = getCartLines();"));

    // Поле з відсотком сюди не доїжджає, і це не випадковість:
    // test-catalog-payload.js [2] стежить, щоб списки не читали
    // полів зі сторінки товару. Наступний, хто захоче написати
    // точну суму, має спершу прочитати чому.
    check("у коді пояснено, звідки береться відсутність відсотка",
        /PRODUCT_PAGE_ONLY/.test(read("assets/js/checkout.js")));
}

console.log("\n[2] Текст умови — на справжньому DOM");
{
    const js = read("assets/js/checkout.js");

    const fn = js.match(/function showPreorderNote[\s\S]*?\n}\n/);

    check("функція знайшлась", Boolean(fn));

    const dom = new JSDOM(
        `<!doctype html><body><p id="checkoutPreorderNote" hidden></p></body>`,
        { runScripts: "outside-only" });

    const { window } = dom;

    window.eval(fn[0]);
    window.eval("window.__note = showPreorderNote;");

    const note = () => window.document.getElementById("checkoutPreorderNote");

    const line = preOrder => ({ product: { preOrder }, qty: 1 });

    // Звичайний кошик — жодного слова зайвого.
    window.__note([line(false), line(false)]);

    check("без товарів під замовлення рядка немає", note().hidden === true);
    check("і текст не лишився від минулого разу", note().textContent === "");

    // Один такий товар серед звичайних — рядок з'являється.
    window.__note([line(true), line(false)]);

    check("з'явився, щойно такий товар у кошику", note().hidden === false);
    check("однина, бо товар один",
        /є товар під замовлення/.test(note().textContent), note().textContent);
    check("сказано про передоплату",
        /потрібна передоплата/.test(note().textContent), note().textContent);

    // ГОЛОВНЕ СЛОВО в цьому рядку. Поруч стоїть перемикач «Готівкою
    // при отриманні на пошті», і без прямої згадки про нього рядок
    // читається як загальна примітка, а не як відповідь на питання,
    // яке людина саме зараз вирішує.
    check("сказано прямо, що оплата при отриманні не підійде",
        /оплата при отриманні не підійде/.test(note().textContent), note().textContent);

    check("названо, хто узгодить суму",
        /менеджер/.test(note().textContent) && /суму/.test(note().textContent));

    // Відсотка тут бути НЕ МОЖЕ: поле preOrderPrepayment лишається
    // на сторінці товару (PRODUCT_PAGE_ONLY), у catalog.json його
    // немає. Написане число було б узяте зі стелі.
    check("жодного відсотка не вигадано",
        !/%/.test(note().textContent), note().textContent);

    // Двоє — множина. Дрібниця, але рядок читають у момент, коли
    // вирішують платити; «є товар» замість «є товари» тут помітно.
    window.__note([line(true), line(true)]);

    check("множина, бо товарів двоє",
        /є товари під замовлення/.test(note().textContent), note().textContent);

    // Повернення до звичайного кошика ховає рядок назад: покупець
    // міг прибрати товар під замовлення просто на цій сторінці.
    window.__note([line(false)]);

    check("прибрали товар — рядок зник", note().hidden === true);
    check("і текст стерто, а не лишено під hidden", note().textContent === "");
}

console.log("\n[3] Жоден спосіб оплати не вимкнено");
{
    const js = code("assets/js/checkout.js");

    const fn = (js.match(/function showPreorderNote[\s\S]*?\n}\n/) || [""])[0];

    // Найпростіший спосіб «полагодити» це місце — заборонити
    // готівку. Тоді частина людей просто піде: спосіб оплати зник
    // без пояснення, а телефону менеджера на сторінці немає.
    check("умова нічого не вимикає",
        !/disabled/.test(fn) && !/\.checked\s*=/.test(fn), fn.slice(0, 120));

    check("і не чіпає перемикачі оплати",
        !/paymentMethod/.test(fn));
}

console.log(failures === 0
    ? "\n✓ усі перевірки пройдено"
    : `\n✗ провалено перевірок: ${failures}`);

process.exit(failures === 0 ? 0 : 1);
