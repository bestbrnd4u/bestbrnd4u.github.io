// Сайт не має обіцяти оплату, якої на ньому немає.
//
// ЗНАЙДЕНО 25.09.2026, сторінка «Оплата і доставка»
// -------------------------------------------------
// «Visa або Mastercard — оплата проходить ОДРАЗУ ПРИ ОФОРМЛЕННІ
// ЗАМОВЛЕННЯ НА САЙТІ, безпечно та без комісії.»
//
// Платіжного шлюзу на сайті немає жодного: ні LiqPay, ні Fondy, ні
// WayForPay, ні monobank. Сторінка оформлення лише ЗАПИСУЄ обраний
// спосіб, а далі сторінка подяки каже: «менеджер зв'яжеться з вами,
// щоб підтвердити замовлення». Телеграм-бот узагалі пропонує саму
// лише оплату при отриманні.
//
// Тобто покупець, який обрав картку (а вона стоїть ПЕРШОЮ і вибрана
// за замовчуванням), чекав форму оплати — і не отримував нічого.
// Найгірша мить для несподіванки.
//
// ЩО ВИПРАВЛЕНО, А ЩО НІ. Прибрано лише МЕХАНІЗМ («одразу при
// оформленні на сайті»), бо саме він неправда. Сам спосіб лишився:
// заплатити карткою онлайн можна — просто не в цю мить. Так
// формулювання лишається правдивим і в тому разі, якщо менеджер
// надсилає посилання на оплату.
//
// ЧОМУ ТЕСТ САМЕ ТАКИЙ
// --------------------
// Перевірити «чи справді все написане правда» автоматом не можна.
// Але можна перевірити ФОРМУ цієї конкретної неправди: речення, у
// якому одночасно є оплата, миттєвість і «на сайті / при оформленні».
// Поки шлюзу немає, такого речення бути не може.
//
// Якщо шлюз колись з'явиться — розділ [1] почервоніє й попросить
// переглянути цей набір. Це навмисно: тест не має тихо дозволяти
// обіцянку, ставши непотрібним.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const PAGES = fs.readdirSync(ROOT).filter(f => f.endsWith(".html"));

const текст = html => html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ");

console.log("\n[1] Платіжного шлюзу на сайті немає");
{
    // Премиса всього набору. З'явиться шлюз — цей розділ почервоніє,
    // і той, хто його додав, перечитає решту перевірок.
    const ШЛЮЗИ = /liqpay|fondy|wayforpay|portmone|ipay\.ua|stripe|paypal|checkout\.monobank|acquiring/i;

    const код = [];

    const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).forEach(entry => {
        if (["node_modules", ".git", "tests", "docs"].includes(entry.name)) return;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else if (/\.(js|ts|html)$/.test(entry.name) && !full.includes(path.join(ROOT, "p"))) код.push(full);
    });

    walk(ROOT);

    const знайдено = код.filter(f => ШЛЮЗИ.test(fs.readFileSync(f, "utf8")))
        .map(f => path.relative(ROOT, f));

    check(`шлюзу немає (перевірено ${код.length} файлів)`,
        знайдено.length === 0,
        знайдено.slice(0, 3).join(", ") + " — шлюз з'явився, перечитайте цей набір");
}

console.log("\n[2] Жодна сторінка не обіцяє оплату в мить оформлення");
{
    // Форма неправди: оплата + миттєвість + «на сайті / при оформленні»
    // в ОДНОМУ реченні.
    // Початок слова, а не будь-де всередині: інакше «без прихованих
    // ДОПЛАТ» на сторінці байєр-сервісу читається як «оплата» — і
    // цілком правдиве речення потрапляє в винні. Перша версія цієї
    // перевірки саме так і спіткнулась.
    const ОПЛАТА = /(?<!\p{L})(оплат|сплат|платіж)/iu;
    const МИТТЄВІСТЬ = /одраз|негайн|миттєв|тут же|прямо зараз/i;
    const НА_САЙТІ = /на сайті|при оформленні|під час оформлення|у кошику/i;

    const винні = [];

    PAGES.forEach(rel => {

        текст(fs.readFileSync(path.join(ROOT, rel), "utf8"))
            .split(/(?<=[.!?])\s+/)
            .forEach(речення => {
                if (ОПЛАТА.test(речення) && МИТТЄВІСТЬ.test(речення) && НА_САЙТІ.test(речення)) {
                    винні.push(`${rel}: «${речення.trim().slice(0, 90)}»`);
                }
            });

    });

    check("такого речення немає на жодній сторінці",
        винні.length === 0, винні.slice(0, 3).join("; "));
}

console.log("\n[3] Відповідь про оплату всюди одна");
{
    // Питання «чи можна оплатити карткою онлайн» лежить у двох місцях
    // на одній сторінці: у розмітці для Google і у видимому тексті.
    // Я правив саме його — і був за крок від того, щоб змінити одну
    // копію й забути другу.
    //
    // Що вони збігаються ЗАГАЛОМ, стежить tests/test-faq-schema.js.
    // Тут — окремо про оплату, бо саме тут ціна розходження найвища:
    // Google показав би в видачі те, чого сторінка не обіцяє.
    const html = fs.readFileSync(path.join(ROOT, "delivery-payment.html"), "utf8");

    const схема = [...html.matchAll(/"acceptedAnswer": \{ "@type": "Answer", "text": "([^"]*картк[^"]*)"/g)]
        .map(m => m[1]);

    check("відповідь про картку є в розмітці", схема.length > 0);

    схема.forEach(відповідь => {
        check("вона ж є у видимому тексті",
            текст(html).includes(відповідь.replace(/\\"/g, '"')),
            відповідь.slice(0, 70));
    });
}

console.log(failures ? `\n✗ Провалено: ${failures}` : "\n✓ Усе зелено");
process.exit(failures ? 1 : 0);
