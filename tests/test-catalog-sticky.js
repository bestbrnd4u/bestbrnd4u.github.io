// На каталозі липкі ОБИДВА блоки: панель фільтрів і дерево категорій.
// Панель прилипає на 82px (під шапкою), колонка — на 170px.
//
// 170 це «82 шапка + 88 панель»: число з часів, коли панель містилась
// в один рядок. Фільтрів побільшало, вони переносяться у два рядки, і
// панель стала 146px. Прилипла, вона займає 82…228 — а колонка
// ставала на 170. Перші 58 пікселів колонки опинялись ПІД панеллю.
//
// «Всі товари» — перший пункт, 35px. Його не було видно взагалі.
// Заміряно на проді: накрито 35 з 35, elementFromPoint у тій точці
// повертав саму панель.
//
// ЧОМУ ПЕРЕВІРКА САМЕ ТАКА
// -------------------------
// Не «чи дорівнює top якомусь числу» — число й було причиною. Будь-яке
// зашите значення правильне рівно для однієї ширини й одного набору
// фільтрів: панель це flex-wrap, і кількість рядків у неї різна.
//
// Тому питаємо ЗВʼЯЗОК: верх колонки мусить рахуватись від справжньої
// висоти панелі, а висоту ту мусить хтось вимірювати й публікувати.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;

const check = (name, condition, extra) => {
    if (condition) console.log("  ✓", name);
    else { console.log("  ✗", name, extra !== undefined ? "→ " + extra : ""); failures++; }
};

const read = file => fs.readFileSync(path.join(ROOT, file), "utf8");

const CSS = read("assets/css/style.css").replace(/\/\*[\s\S]*?\*\//g, " ");
const JS = read("assets/js/catalog.js");

// Назва змінної в одному місці: якщо її колись перейменують, перевірка
// має впасти вся, а не тихо наполовину.
const ЗМІННА = "--catalog-filters-h";


console.log("\n[1] Висоту панелі хтось справді вимірює");
{
    check("скрипт публікує змінну",
        new RegExp(`setProperty\\("${ЗМІННА}"`).test(JS), ЗМІННА);

    // offsetHeight, а не getBoundingClientRect().top: положення
    // залежить від прокрутки, а нам потрібна власна висота.
    check("береться власна висота, не положення",
        /bar\.offsetHeight/.test(JS));

    // Панель міняє висоту не лише від розміру вікна: у розділі з
    // іншим набором фільтрів рядків може бути більше, а приїжджає той
    // набір уже після завантаження сторінки.
    check("перевимірюється при зміні панелі",
        /ResizeObserver/.test(JS));

    check("є запасний шлях без ResizeObserver",
        /addEventListener\("resize", publish/.test(JS));

    // Нуль буває, поки панель ще не намальована: записати його
    // означало б підняти колонку під шапку.
    check("нульову висоту не публікуємо", /if \(!h\) return;/.test(JS));
}


console.log("\n[2] Колонка рахує свій верх від тієї висоти");
{
    const правило = (CSS.match(/\.catalog-sidebar\{([^}]*)\}/g) || [])
        .map(r => r)
        .find(r => /position\s*:\s*sticky/.test(r)) || "";

    check("липке правило колонки знайдено", !!правило, правило.slice(0, 80));

    check("верх залежить від змінної",
        new RegExp(`top\\s*:\\s*calc\\([^;]*var\\(${ЗМІННА}`).test(правило),
        правило.replace(/\s+/g, " "));

    // ЦЕ Й БУЛА ПОМИЛКА: одне число замість розрахунку.
    check("верх НЕ зашитий числом",
        !/top\s*:\s*\d+px\s*;/.test(правило),
        (правило.match(/top\s*:[^;]*/) || [""])[0]);

    // Висота теж: колонка прокручується сама, і її стеля мусить
    // рахуватись від того самого, інакше низ поїде за екран.
    check("максимальна висота теж від змінної",
        new RegExp(`max-height\\s*:\\s*calc\\([^;]*var\\(${ЗМІННА}`).test(правило),
        (правило.match(/max-height\s*:[^;]*/) || [""])[0]);
}


console.log("\n[3] Арифметика: колонка нижча за низ панелі");
{
    // Рахуємо те саме, що порахує браузер, і звіряємо з тим, що
    // заміряно на живій сторінці.
    const правило = (CSS.match(/\.catalog-sidebar\{[^}]*position\s*:\s*sticky[^}]*\}/) || [""])[0];

    const top = (правило.match(/top\s*:\s*calc\(([^;]*)\)/) || [])[1] || "";

    // Висота шапки — вона ж у top самої панелі.
    const панель = (CSS.match(/\.catalog-filters-bar\{[^}]*\}/) || [""])[0];
    const верхПанелі = Number((панель.match(/top\s*:\s*(\d+)px/) || [])[1]);

    check("верх панелі прочитано", верхПанелі > 0, String(верхПанелі));

    // У виразі колонки мусить бути та сама висота шапки: інакше при
    // зміні шапки роз'їдеться одне з двох.
    check("у розрахунку врахована висота шапки",
        top.includes(`${верхПанелі}px`), top.trim());

    // Запасне значення змінної має збігатися з тим, що реально має
    // панель: саме воно діє ту секунду, поки не відпрацював скрипт.
    const запас = Number((top.match(new RegExp(`var\\(${ЗМІННА},\\s*(\\d+)px\\)`)) || [])[1]);

    check("у змінної є запасне значення", запас > 0, String(запас));

    // 146px — заміряно на проді 01.10.2026 на всіх десктопних
    // ширинах. Якщо панель колись стане вищою, запас теж треба
    // підняти: та секунда до скрипта буде зламаною.
    check("запас не менший за те, що панель має зараз",
        запас >= 146, `${запас} проти 146`);

    // І останнє: між панеллю й колонкою мусить лишитись проміжок,
    // інакше вони злипнуться.
    const проміжок = top.replace(/.*\+\s*/, "").trim();

    check("між панеллю й колонкою є відступ",
        /^\d+px$/.test(проміжок) && Number(проміжок.replace("px", "")) > 0,
        проміжок);
}


console.log(failures === 0 ? "\n✅ Усі перевірки пройдено" : `\n❌ Провалено: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
