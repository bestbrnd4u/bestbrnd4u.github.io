// ЛИПКА ПАНЕЛЬ ФІЛЬТРІВ І ЛІВА КОЛОНКА: НЕ НАКРИВАТИ Й НЕ ЛИШАТИ ДІРУ
//
// ЩО БУЛО НЕ ТАК (ПЕРШИЙ РАЗ)
// ----------------------------
// На каталозі липкі ОБИДВА блоки: панель фільтрів і дерево категорій.
// Панель прилипає на 82px (під шапкою), колонка — на 170px.
//
// 170 це «82 шапка + 88 панель»: число з часів, коли панель містилась
// в один рядок. Фільтрів побільшало, вони переносяться у два рядки, і
// панель стала 146px. Прилипла, вона займає 82…228 — а колонка
// ставала на 170. Перші 58 пікселів колонки опинялись ПІД панеллю.
//
// «Всі товари» — перший пункт, 35px. Його не було видно взагалі.
// Заміряно на проді: накрито 35 з 35, elementFromPoint у тій точці
// повертав саму панель.
//
// ЩО БУЛО НЕ ТАК (ДРУГИЙ РАЗ, І ЦЕ ІНША ПОМИЛКА)
// -----------------------------------------------
// Колонку опустили під панель — і забули, що панель там не завжди.
// При прокрутці вниз вона їде вгору (translateY(-140%) на .is-hidden)
// і місця більше не займає, а колонка далі тримала під неї всі 146px.
//
// Власник побачив це так: «Всі товари» висить посеред екрана, а над
// ним порожньо. Заміряно 02.10.2026: 162px порожнечі під шапкою, і
// колонка рівно на стільки ж коротша, ніж могла бути.
//
// ЧОМУ ПЕРЕВІРКА САМЕ ТАКА
// -------------------------
// Не «чи дорівнює top якомусь числу» — число й було причиною першого
// разу. Будь-яке зашите значення правильне рівно для однієї ширини й
// одного набору фільтрів: панель це flex-wrap, і кількість рядків у
// неї різна.
//
// Тому питаємо ЗВʼЯЗОК, і тепер два: верх колонки мусить рахуватись
// від справжньої висоти панелі (її хтось вимірює й публікує) — і від
// того, чи панель ЗАРАЗ на місці.
//
// І ще одне, вистраждане: top у колонки має бути рівно ОДИН. Там, де
// на один край елемента претендує кілька правил, виграє не те, що
// нижче у файлі, а те, чий селектор важчий — на цьому в проєкті вже
// двічі згоріло. Стан мусить міняти ЧИСЛО, а не правило.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;

const check = (name, condition, extra) => {
    if (condition) console.log("  ✓", name);
    else { console.log("  ✗", name, extra !== undefined ? "→ " + extra : ""); failures++; }
};

const read = file => fs.readFileSync(path.join(ROOT, file), "utf8");

const CSS = read("assets/css/style.css").replace(/\/\*[\s\S]*?\*\//g, " ");
const JS = read("assets/js/catalog.js");

// Назви в одному місці: якщо їх колись перейменують, перевірка має
// впасти вся, а не тихо наполовину.
const ВИСОТА = "--catalog-filters-h";    // скільки панель заввишки
const ВІДСТУП = "--catalog-filters-lift"; // скільки місця вона займає ЗАРАЗ
const ХОВАЄТЬСЯ = "is-hidden";            // клас, яким її прибирають


console.log("\n[1] Висоту панелі хтось справді вимірює");
{
    check("скрипт публікує змінну",
        new RegExp(`setProperty\\("${ВИСОТА}"`).test(JS), ВИСОТА);

    // offsetHeight, а не getBoundingClientRect().top: положення
    // залежить від прокрутки, а нам потрібна власна висота.
    check("береться власна висота, не положення",
        /bar\.offsetHeight/.test(JS));

    // Панель міняє висоту не лише від розміру вікна: у розділі з
    // іншим набором фільтрів рядків може бути більше, а приїжджає той
    // набір уже після завантаження сторінки.
    check("перевимірюється при зміні панелі",
        /ResizeObserver/.test(JS));

    check("є запасний шлях без ResizeObserver",
        /addEventListener\("resize", publish/.test(JS));

    // Нуль буває, поки панель ще не намальована: записати його
    // означало б підняти колонку під шапку.
    check("нульову висоту не публікуємо", /if \(!h\) return;/.test(JS));
}


console.log("\n[2] Колонка рахує свій верх від місця, яке панель займає");
{
    const правило = (CSS.match(/\.catalog-sidebar\s*\{[^}]*\}/g) || [])
        .find(r => /position\s*:\s*sticky/.test(r)) || "";

    check("липке правило колонки знайдено", !!правило, правило.slice(0, 80));

    check("верх залежить від відступу",
        new RegExp(`top\\s*:\\s*calc\\([^;]*var\\(${ВІДСТУП}`).test(правило),
        правило.replace(/\s+/g, " "));

    // ЦЕ Й БУЛА ПОМИЛКА ПЕРШОГО РАЗУ: одне число замість розрахунку.
    check("верх НЕ зашитий числом",
        !/top\s*:\s*\d+px\s*;/.test(правило),
        (правило.match(/top\s*:[^;]*/) || [""])[0]);

    // Висота теж: колонка прокручується сама, і її стеля мусить
    // рахуватись від того самого, інакше низ поїде за екран.
    check("максимальна висота теж від відступу",
        new RegExp(`max-height\\s*:\\s*calc\\([^;]*var\\(${ВІДСТУП}`).test(правило),
        (правило.match(/max-height\s*:[^;]*/) || [""])[0]);

    // Ланцюг до справжнього заміру не має обриватись: відступ мусить
    // братися з виміряної висоти, а не бути ще одним числом.
    const основа = (CSS.match(new RegExp(`${ВІДСТУП}\\s*:\\s*var\\(${ВИСОТА}[^;]*;`)) || [""])[0];

    check("відступ рахується з виміряної висоти", !!основа, основа || "немає");
}


console.log("\n[3] Арифметика: колонка нижча за низ панелі");
{
    // Рахуємо те саме, що порахує браузер, і звіряємо з тим, що
    // заміряно на живій сторінці.
    const правило = (CSS.match(/\.catalog-sidebar\s*\{[^}]*position\s*:\s*sticky[^}]*\}/) || [""])[0];

    const top = (правило.match(/top\s*:\s*calc\(([^;]*)\)/) || [])[1] || "";

    // Висота шапки — вона ж у top самої панелі.
    const панель = (CSS.match(/\.catalog-filters-bar\{[^}]*\}/) || [""])[0];
    const верхПанелі = Number((панель.match(/top\s*:\s*(\d+)px/) || [])[1]);

    check("верх панелі прочитано", верхПанелі > 0, String(верхПанелі));

    // У виразі колонки мусить бути та сама висота шапки: інакше при
    // зміні шапки роз'їдеться одне з двох.
    check("у розрахунку врахована висота шапки",
        top.includes(`${верхПанелі}px`), top.trim());

    // Запасне значення діє ту секунду, поки не відпрацював скрипт.
    // Воно переїхало з виразу колонки у визначення відступу — але
    // зникнути не мало права, тому шукаємо його там.
    const запас = Number(
        (CSS.match(new RegExp(`${ВІДСТУП}\\s*:\\s*var\\(${ВИСОТА},\\s*(\\d+)px\\)`)) || [])[1]);

    check("у змінної є запасне значення", запас > 0, String(запас));

    // 146px — заміряно на проді 01.10.2026 на всіх десктопних
    // ширинах. Якщо панель колись стане вищою, запас теж треба
    // підняти: та секунда до скрипта буде зламаною.
    check("запас не менший за те, що панель має зараз",
        запас >= 146, `${запас} проти 146`);

    // Те саме число стоїть і в самої колонки — як захист від того,
    // що оголошення вище колись зникне (var() без запасу зробив би
    // НЕДІЙСНИМ увесь рядок, і колонка перестала б липнути).
    // Два однакових числа в різних місцях рано чи пізно розходяться,
    // тому тримаємо їх разом саме тут.
    const запасНаМісці = Number(
        (top.match(new RegExp(`var\\(${ВІДСТУП},\\s*(\\d+)px\\)`)) || [])[1]);

    check("у колонки теж є запас, і той самий",
        запасНаМісці === запас, `${запасНаМісці} проти ${запас}`);

    // І останнє: між панеллю й колонкою мусить лишитись проміжок,
    // інакше вони злипнуться.
    const проміжок = top.replace(/.*\+\s*/, "").trim();

    check("між панеллю й колонкою є відступ",
        /^\d+px$/.test(проміжок) && Number(проміжок.replace("px", "")) > 0,
        проміжок);
}


console.log("\n[4] Панель поїхала — колонка йде за нею");
{
    // Коли панель ховається, місця вона не займає, і відступ мусить
    // стати нулем. Інакше під шапкою лишається діра на всю її висоту.
    const обнулення = (CSS.match(
        new RegExp(`body:has\\(\\.catalog-filters-bar\\.${ХОВАЄТЬСЯ}\\)\\{[^}]*\\}`)) || [""])[0];

    check("є правило на сховану панель", !!обнулення, обнулення || "немає");

    check("воно обнуляє саме відступ",
        new RegExp(`${ВІДСТУП}\\s*:\\s*0`).test(обнулення),
        обнулення.replace(/\s+/g, " "));

    // Клас у стилях і клас, яким його ставить скрипт, — одне й те саме
    // слово. Перейменують в одному місці — правило вище стане мертвим,
    // а виглядатиме живим.
    check("цим самим класом скрипт і ховає панель",
        new RegExp(`classList\\.toggle\\("${ХОВАЄТЬСЯ}"`).test(JS), ХОВАЄТЬСЯ);

    // ГОЛОВНЕ. Претендент на верх колонки мусить бути один.
    //
    // Спокуса зробити інакше дуже велика: дописати окреме правило
    // «коли панель сховано — top такий» виглядає природно й навіть
    // працює, доки хтось не додасть стан із важчим селектором. Тоді
    // виграє він, мовчки, і знайти це можна лише лінійкою.
    //
    // Тому рахуємо не «чи є потрібне правило», а СКІЛЬКИ разів узагалі
    // задано top. Має бути один.
    const блоки = CSS.match(/\.catalog-sidebar\s*\{[^}]*\}/g) || [];
    const скількиTop = блоки
        .reduce((n, b) => n + (b.match(/(?:^|[{;\s])top\s*:/g) || []).length, 0);

    check("top у колонки заданий рівно один раз",
        скількиTop === 1, `${скількиTop} разів у ${блоки.length} правилах`);

    // Те саме для стелі: вона рахується з того ж відступу, тож двох
    // джерел у неї бути так само не може.
    const скількиМакс = блоки
        .reduce((n, b) => n + (b.match(/max-height\s*:/g) || []).length, 0);

    check("max-height у колонки заданий рівно один раз",
        скількиМакс === 1, `${скількиМакс} разів`);

    // Рухаються вони разом, тож і тривалість одна: інакше колонка
    // відстає від панелі й це видно.
    const панель = (CSS.match(/\.catalog-filters-bar\{[^}]*\}/) || [""])[0];
    const тривалістьПанелі = (панель.match(/transition\s*:[^;]*?([\d.]+)s/) || [])[1];
    const правило = блоки.find(r => /position\s*:\s*sticky/.test(r)) || "";
    const тривалістьКолонки = (правило.match(/transition\s*:[^;]*?([\d.]+)s/) || [])[1];

    check("колонка рухається стільки ж, скільки панель",
        тривалістьПанелі !== undefined && тривалістьПанелі === тривалістьКолонки,
        `панель ${тривалістьПанелі}s, колонка ${тривалістьКолонки}s`);
}


console.log(failures === 0 ? "\n✅ Усі перевірки пройдено" : `\n❌ Провалено: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
