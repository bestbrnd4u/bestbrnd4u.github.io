// Згода на дані: банер, блокування вбудованого відео, чесність тексту.
//
// ГОЛОВНА ВИМОГА
// ---------------
// Банер має відповідати тому, що сайт РОБИТЬ НАСПРАВДІ. Чотири галочки
// «аналітика / реклама / персоналізація», яких на сайті немає, гірші
// за відсутність банера: вони обіцяють контроль над неіснуючим і при
// цьому мовчать про справжнє.
//
// Перевірки нижче стережуть дві речі: що згода не декоративна (відео
// справді не вантажиться до неї) і що текст не розходиться з кодом.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const read = rel => fs.readFileSync(path.join(ROOT, rel), "utf8");
const strip = t => t.replace(/\/\/[^\n]*/g, "").replace(/\/\*[\s\S]*?\*\//g, "");

const consent = read("assets/js/consent.js");
const consentCode = strip(consent);
const product = strip(read("assets/js/product.js"));
const policy = read("privacy-policy.html");
const checkout = read("checkout.html");
const css = read("assets/css/style.css").replace(/\/\*[\s\S]*?\*\//g, "");

console.log("\n[1] Згода — дія, а не бездіяльність");
{
    check("без відповіді згоди немає",
        /return !!\(saved && saved\[category\]\)/.test(consentCode));

    // Обов'язкове (кошик, обране, вхід) згоди не потребує: це пам'ять
    // самої сторінки, а не стеження.
    check("необхідне не питається", /OPTIONAL\.indexOf\(category\) === -1/.test(consentCode));

    // Додасться категорія — банер спитає знову, а не застосує старий
    // вибір до того, чого людина не бачила.
    check("версія згоди враховується", /saved\.version !== VERSION/.test(consentCode));

    check("банер показується лише раз", /if \(!answered\(\)\) render\(\)/.test(consentCode));

    // Згоду треба вміти відкликати так само легко, як дати.
    check("є спосіб змінити рішення", /reopen: function/.test(consentCode));
    check("посилання є в підвалі", /data-consent-reopen/.test(read("index.html")));

    // ПОСИЛАННЯ МУСИТЬ ЩОСЬ РОБИТИ.
    //
    // Тут була мертва кнопка: render() виходив, якщо банер уже на
    // екрані, — тобто клік по «Налаштування даних» у людини, яка ще не
    // відповіла, не робив нічого видимого. Гірше: reopen() при цьому
    // стирав збережений вибір, тобто мовчки вимикав статистику,
    // рекламу й відео.
    check("банер перемальовується, а не мовчить",
        /function render\(mode\)[\s\S]{0,900}close\(\);/.test(consentCode)
        && !/if \(document\.getElementById\("consentBanner"\)\) return;/.test(consentCode));

    check("сам клік нічого не змінює",
        !/reopen: function[\s\S]{0,300}removeItem/.test(consentCode));

    // «Налаштування» мусять бути налаштуваннями: вимкнути саму лише
    // рекламу, не втрачаючи відео й статистики.
    check("є перемикачі по категоріях", /data-consent-option/.test(consentCode));

    check("перемикачі показують поточний вибір",
        /saved && saved\[name\] \? " checked" : ""/.test(consentCode));

    check("вибір зберігається кнопкою", /action === "save"/.test(consentCode));

    check("людина бачить, що вибір збережено", /showToast/.test(consentCode));

    // Видимість банера не має залежати від того, чи встигла
    // програтись анімація: у присплений вкладці вона не починається
    // взагалі, і банер лишався б за межами екрана.
    const css = read("assets/css/style.css");

    check("анімація не ховає банер за екран",
        /@keyframes consentUp\{ from\{transform:translateY\(1?\dpx\)\}/.test(css),
        (css.match(/@keyframes consentUp[^}]*\}[^}]*\}/) || [""])[0]);

    // Приватний режим: чесніше питати щоразу, ніж мовчки вважати
    // згоду отриманою.
    check("збій сховища не дає мовчазної згоди",
        /catch \(error\) \{[\s\S]{0,200}\n\s*\}/.test(consentCode));
}

console.log("\n[2] Згода не декоративна: відео справді чекає");
{
    // Якби iframe вставлявся одразу, YouTube дізнавався б IP ще до
    // того, як людина щось натиснула, — і питання втрачало б сенс.
    check("iframe вставляється лише після згоди",
        /const allowed = !window\.Consent \|\| window\.Consent\.has\("embeds"\)/.test(product));
    check("до згоди — заглушка", /video-consent/.test(product));

    check("у заглушці сказано, що станеться",
        /Сервіс отримає вашу IP-адресу/.test(product));
    check("названо конкретний сервіс", /Vimeo" : "YouTube"/.test(product));

    // Клац по заглушці вмикає ЦЕ відео, а не змінює загальну згоду:
    // людина погодилась подивитись ролик, а не дозволити все назавжди.
    check("клац по заглушці не змінює загальну згоду",
        /video-consent-btn/.test(product) && !/Consent\.reopen|localStorage\.setItem/.test(product));

    check("після згоди заглушки самі стають плеєрами",
        /consent:change/.test(product) && /consent:change/.test(consentCode));

    check("є стилі заглушки", /\.video-consent\{/.test(css));
}

console.log("\n[3] Текст банера відповідає дійсності");
{
    // Категорій три, і кожна — окрема мета: відео, статистика
    // (Google Analytics) і реклама (піксель Meta).
    //
    // ЧОМУ РЕКЛАМА ОКРЕМО ВІД СТАТИСТИКИ. Це різні цілі, і згода на
    // одну не є згодою на іншу: статистика відповідає магазину, чого
    // бракує в каталозі, а піксель віддає дії рекламній компанії, щоб
    // та наздогнала людину оголошенням в іншому місці. Заховати друге
    // під галочкою першого — саме той випадок, коли згода формально є,
    // а насправді її не питали.
    check("категорії — відео, статистика й реклама",
        /var OPTIONAL = \["embeds", "analytics", "ads"\]/.test(consentCode));

    // Додалась категорія — стара відповідь більше не діє. Людина, яка
    // натиснула «Прийняти», коли пікселя на сайті не було, відповідала
    // на ІНШЕ питання; застосувати ту відповідь до нового означало б
    // вирішити за неї.
    check("версію згоди піднято", /var VERSION = 3/.test(consentCode));

    // Вибір мусить зберігатись і повідомлятись по ВСІХ трьох
    // категоріях: забути одну — і піксель або не вмикається ніколи,
    // або вмикається без згоди.
    check("реклама зберігається у виборі", /ads: !!choice\.ads/.test(consentCode));
    check("реклама є в події consent:change", /ads: has\("ads"\)/.test(consentCode));
    check("кнопка «Прийняти» вмикає всі три",
        /decide\(\{ embeds: yes, analytics: yes, ads: yes \}\)/.test(consentCode));

    // БАНЕР СТАВ КОРОТКИМ, І ЦЕ НАВМИСНО
    // -----------------------------------
    // Тут стояло шість стрічок: що зберігаємо, навіщо, які сервіси
    // отримають IP, чого не робимо. Усе правда, але на телефоні банер
    // займав півекрана — і люди тиснули «Прийняти», не читаючи.
    // Довгий текст не зробив вибір усвідомленим, лише відтіснив
    // магазин.
    //
    // Тепер одна стрічка й посилання. Вимога «банер каже правду»
    // лишається, але перевіряємо її по СУТІ: названо, для чого cookie,
    // і є куди піти по деталі.
    check("банер називає, для чого cookie",
        /для роботи магазину/.test(consent) && /статистики/.test(consent)
        && /реклам/.test(consent));
    check("є посилання на політику", /href="privacy-policy"/.test(consent));

    // Банер ПЕРШОГО показу мусить лишатись коротким: це і є суть
    // правки. Текст лежить окремою константою саме для цього — раніше
    // тут вишкрібалися всі рядки з innerHTML, і перевірка почала
    // рахувати заразом текст режиму «Налаштування», тобто вимірювала
    // не те.
    const askText = (consent.match(/var ASK_TEXT = ([\s\S]*?);\n/) || ["", ""])[1]
        .match(/"[^"]*"/g)
        .map(x => x.slice(1, -1))
        .join("")
        .replace(/\s+/g, " ")
        .trim();

    check(`текст банера — ${askText.length} символів`,
        askText.length > 0 && askText.length < 200, askText.length);

    // А повний опис мусить бути в політиці — там, куди веде посилання.
    check("статистика описана в політиці", /Google Analytics/.test(policy));
    check("реклама описана в політиці", /піксель\s*\n?\s*Meta/.test(policy));
    check("є посилання на політику", /href="privacy-policy"/.test(consent));

    // Кнопка «лише необхідне» мусить бути так само доступною, як
    // «дозволити»: інакше вибір формальний.
    check("відмова так само доступна, як згода",
        /data-consent="necessary"/.test(consentCode) && /data-consent="all"/.test(consentCode));
}

console.log("\n[4] Політика описує те, що є в коді");
{
    // Перелік у політиці має збігатися з тим, що код справді пише
    // у сховище. Розходження тут — не дрібниця: це заява, яка не
    // відповідає дійсності.
    // Скануємо ВСІ скрипти сайту: ключі розкидані по файлах
    // (bestbrnd4uLastOrder, наприклад, живе в checkout.js), і вузький
    // список давав хибне «немає в коді».
    const allScripts = fs.readdirSync(path.join(ROOT, "assets/js"))
        .filter(f => f.endsWith(".js"))
        .map(f => read(`assets/js/${f}`))
        .join("\n");

    ["cart", "favorites", "catalogView", "bestbrnd4uLastOrder", "consent", "catalogReturnTo"]
        .forEach(key => {

            const inCode = new RegExp(`["']${key}["']`).test(allScripts);

            check(`${key}: є в коді і названий у політиці`,
                inCode && policy.includes(key), inCode ? "немає в політиці" : "немає в коді");

        });

    // Сервіси, які бачать IP відвідувача, мають бути названі.
    ["Google Fonts", "EmailJS", "MailerLite", "YouTube", "Vimeo", "Supabase"]
        .forEach(name => check(`${name} названий у політиці`, policy.includes(name)));

    // Політика мусить описувати те, що є НАСПРАВДІ, і це вже двічі
    // ловилось саме тут: спершу в ній було «на сайті немає Google
    // Analytics», потім — «немає пікселя Facebook». Підключити річ і
    // лишити фразу про її відсутність означає лишити на сайті неправду.
    check("політика називає Google Analytics", /Google Analytics/.test(policy));
    check("сказано, що він лише після згоди",
        /ЛИШЕ після вашої\s*\n?\s*згоди/.test(policy));
    check("сказано, що персональних даних туди не йде",
        /Персональних даних ми туди не\s*\n?\s*передаємо/.test(policy));

    // Піксель Meta — те саме, але для рекламної половини.
    check("політика називає піксель Meta", /піксель\s*\n?\s*Meta/.test(policy));
    check("сказано, що згода на нього ОКРЕМА",
        /окремою галочкою «реклама»/.test(policy));
    check("сказано, що без згоди він не вантажиться",
        /не\s*\n?\s*завантажується взагалі, жодного запиту до Facebook/.test(policy));
    check("сказано, що персональних даних у піксель не йде",
        /Персональних даних ми в піксель не передаємо/.test(policy));

    // І фраза «чого не робимо» мусить лишитись правдивою: рекламних
    // мереж, КРІМ Meta, на сайті немає.
    check("сказано, чого не робимо й далі",
        /Рекламних мереж, крім\s*\n?\s*Meta, на сайті немає/.test(policy)
        && /не продаємо ваші дані/.test(policy));
}

console.log("\n[5] Оформлення: коротка стрічка, деталі — у політиці");
{
    // РІШЕННЯ ЗМІНИЛОСЬ, І ЦЕ НАВМИСНО
    // ----------------------------------
    // Спершу тут стояв розкривний блок на чотири абзаци: що збираємо,
    // навіщо, кому передаємо, чого не робимо. Логіка була така:
    // питання виникає саме тоді, коли телефон і адресу вже введено,
    // тож відповідь мусить бути під рукою.
    //
    // На практиці вийшло інакше. Блок стояв ПІД кнопкою «Оформити
    // замовлення» і радше пугав: людина хотіла купити сумку, а бачила
    // абзаци про передачу даних службі доставки. Текст не робив вибір
    // усвідомленим — він відтісняв покупку.
    //
    // Тому деталі переїхали в політику, у розділ із якорем, а тут
    // лишилась одна стрічка з посиланням. Обіцянка «сказано, які дані
    // збираємо» в силі — змінилось лише де саме.
    check("є коротка стрічка", /class="order-data-link"/.test(checkout));
    check("розкривного блока більше немає",
        !/class="order-data-note"/.test(checkout));

    // Посилання мусить вести САМЕ в розділ, а не на початок політики:
    // інакше людина опиниться перед довгим документом і шукатиме
    // потрібне сама.
    check("посилання веде в розділ про замовлення",
        /href="privacy-policy#order-data"/.test(checkout));

    // А сам текст мусить існувати — просто в іншому місці.
    check("розділ у політиці є", /id="order-data"/.test(policy));

    check("у політиці названо «Що саме»", /Що саме:<\/b> ім'я та прізвище/.test(policy));
    check("у політиці названо «Навіщо»", /Навіщо:<\/b> зв'язатися щодо замовлення/.test(policy));
    check("у політиці названо «Кому передаються»",
        /Кому передаються:<\/b> службі доставки/.test(policy));
    check("у політиці сказано, чого не робимо",
        /НЕ робимо:<\/b> не передаємо дані рекламним/.test(policy));

    check("сказано, що дані картки не збираються",
        /дані картки нам не\s*\n?\s*потрапляють/.test(policy));
    check("сказано, куди звертатись по видалення",
        /видалити свої дані[\s\S]{0,80}contacts/.test(policy));
}


console.log(failures === 0 ? "\n✅ Усі перевірки пройдено" : `\n❌ Провалено: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
