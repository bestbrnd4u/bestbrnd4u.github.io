// Темні банери: прозора кнопка й кільце фокуса знають про кожен.
//
// ЧОМУ ЦЕ ОКРЕМИЙ НАБІР
// ----------------------
// На сайті три темні банери: головна (.hero), сторінки байєр-сервісу
// (.bayer-hero-banner) і сторінка акції (.promo-hero-banner). Усі
// три роблять те саме — кладуть білий текст поверх притемненого фото.
//
// І обидва правила, які це підтримують, живуть переліками селекторів:
//   • світлий варіант .btn-outline — бо свій color темне чорнило, і
//     білизну банера він НЕ успадковує;
//   • біле кільце :focus-visible — бо синє на темному тоне.
//
// Перелік легко недописати, і тоді банер виглядає цілим, поки не
// дійдеш саме до нього. Так і сталось: банер акції був відсутній в
// ОБОХ переліках. Заміряно 20.10.2026 на справжніх пікселях фото
// /promo/bilshe-styliu-dlia-yaskravoho-lita/ з накладкою
// rgba(17,24,39,.55):
//
//   напис «Поділитися» темним чорнилом   1.81  (норма 4.5)
//   те саме білим                        6.32
//   кільце фокуса синім                  1.27  (норма 3)
//   те саме білим                        6.58
//
// Набір не звіряє кольори — їх уже звірив замір. Він стежить за тим,
// через що помилка стала можливою: за розходженням двох переліків.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const raw = fs.readFileSync(path.join(ROOT, "assets/css/style.css"), "utf8");
// Коментарі геть: нижче самі описи цих правил, і вони ловились би
// замість самих правил.
const css = raw.replace(/\/\*[\s\S]*?\*\//g, "");

// Правила з переліком селекторів: беремо {селектор, тіло}.
const правила = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
    .map(m => ({ сел: m[1].trim(), тіло: m[2] }));

const банериЗ = сел => [...сел.matchAll(/\.([a-z0-9-]+)\s+(?:\.btn-outline|a|button)\b/g)]
    .map(m => m[1]);

console.log("\n[1] Світлий варіант прозорої кнопки — один, а не копія на банер");
{
    // ОДНА КОПІЯ, А НЕ ТРИ.
    //
    // Правило було продубльоване: окреме для .hero, окреме для
    // банерів байєр-сервісу, з тими самими чотирма оголошеннями. Саме
    // тому третій банер і випав — додати ще одну копію ніхто не
    // здогадався. Поки копія одна, забути неможливо: перелік на очах.
    const світлі = правила.filter(п =>
        /\.btn-outline(?!:)/.test(п.сел)
        && /border-color:rgba\(255,255,255,\.55\)/.test(п.тіло));

    check("таке правило в стилях рівно одне", світлі.length === 1, `знайдено ${світлі.length}`);

    if (світлі.length !== 1) {
        console.log(failures === 0 ? "" : `\n❌ Проблем: ${failures}\n`);
        process.exit(1);
    }

    const банери = банериЗ(світлі[0].сел);

    check("у ньому перелічено щонайменше три банери",
        банери.length >= 3, банери.join(", ") || "жодного");

    check("і серед них банер акції",
        банери.includes("promo-hero-banner"), банери.join(", "));

    check("текст у ньому білий", /color:#fff/.test(світлі[0].тіло));

    // Наведення мусить покривати ті самі банери: інакше на одному з
    // них кнопка при наведенні лишиться прозорою з білим написом, а
    // на решті стане білою з темним.
    const наведення = правила.filter(п =>
        /\.btn-outline:hover/.test(п.сел) && /border-color:#fff/.test(п.тіло));

    check("для наведення теж одне правило", наведення.length === 1, `знайдено ${наведення.length}`);

    if (наведення.length === 1) {
        const банериН = банериЗ(наведення[0].сел);
        const різниця = банери.filter(б => !банериН.includes(б))
            .concat(банериН.filter(б => !банери.includes(б)));
        check("і той самий перелік банерів", різниця.length === 0, різниця.join(", "));
    }

    module.exports = банери;
}

console.log("\n[1b] Оформлення з адмінки не повертає напис у темне");
{
    // promo.js вішає has-style на сам банер акції, щойно в ній задано
    // хоч один колір. Правило .has-style .btn-outline має ту саму вагу,
    // що й світлий варіант, і стоїть нижче по файлу — отже вигравало б
    // воно, і «Поділитися» ставало б темним знову. Запасний колір на
    // темному банері мусить бути білим; заданий власником — діяти далі.
    const правило = правила.find(п =>
        /\.promo-hero-banner\.has-style \.btn-outline/.test(п.сел));

    check("для банера акції з оформленням є своє правило", Boolean(правило));

    if (правило) {

        const колір = (правило.тіло.match(/color:var\(--blk-btn-bg,\s*([^)]+)\)/) || [])[1];

        check("колір власника лишається в силі",
            /color:var\(--blk-btn-bg/.test(правило.тіло), правило.тіло.trim().slice(0, 60));

        check("а запасний — білий, не темне чорнило",
            колір !== undefined && /#fff|white|255,\s*255,\s*255/.test(колір), колір);

        // Вага мусить бути більша, а не рівна: інакше все знову
        // вирішуватиме порядок рядків у файлі.
        const класів = (правило.сел.match(/\./g) || []).length;
        check(`вага більша за .has-style .btn-outline (${класів} класи проти 2)`,
            класів >= 3, класів);

        // А ОСЬ ІЗ НАВЕДЕННЯМ ВАГА РІВНА — І ТОДІ ВИРІШУЄ ПОРЯДОК.
        //
        // .promo-hero-banner .btn-outline:hover — теж (0,3,0). Якщо
        // правило запасного кольору опиниться НИЖЧЕ за нього, на
        // наведенні переможе воно: тло стане білим (з правила
        // наведення), а напис лишиться білим — кнопка зникне.
        const деЗапасне = css.indexOf(".promo-hero-banner.has-style .btn-outline");
        const деНаведення = css.indexOf(".promo-hero-banner .btn-outline:hover");

        check("обидва правила знайдено",
            деЗапасне !== -1 && деНаведення !== -1,
            `запасне ${деЗапасне}, наведення ${деНаведення}`);

        check("запасний колір оголошено ПЕРЕД наведенням",
            деЗапасне !== -1 && деНаведення !== -1 && деЗапасне < деНаведення,
            `запасне на ${деЗапасне}, наведення на ${деНаведення} — при рівній вазі виграє нижче`);

    }
}

console.log("\n[2] Біле кільце фокуса знає ті самі банери");
{
    const світлі = правила.filter(п =>
        /\.btn-outline(?!:)/.test(п.сел)
        && /border-color:rgba\(255,255,255,\.55\)/.test(п.тіло));
    const банери = банериЗ(світлі[0].сел);

    const кільце = правила.filter(п =>
        /:focus-visible/.test(п.сел) && /outline-color:#fff/.test(п.тіло));

    check("правило білого кільця існує", кільце.length >= 1, `знайдено ${кільце.length}`);

    const зКільцем = кільце.flatMap(п => банериЗ(п.сел));

    // ОСЬ ЦЕ Й БУЛО ЧЕРВОНИМ.
    //
    // Банер можна додати у світлу кнопку й забути про кільце: напис
    // стане видно одразу, а пропажу кільця видно лише тому, хто ходить
    // сайтом з клавіатури. Тому перевіряє машина.
    const безКільця = банери.filter(б => !зКільцем.includes(б));

    check("кожен темний банер зі списку кнопки має й біле кільце",
        безКільця.length === 0, безКільця.join(", "));
}

console.log("\n[3] Банери справді темні — інакше білий текст був би помилкою");
{
    // Перелік має сенс, лише поки в ньому саме ТЕМНІ банери. Якщо в
    // нього колись потрапить світлий, обидва правила зроблять його
    // текст білим на світлому — тобто невидимим.
    //
    // Темряву перелічуємо НЕ банерами, а способами, якими її взагалі
    // роблять на цьому сайті. Інакше набір довелось би правити на
    // кожен новий банер — тобто рівно там, де вже один раз забули.
    //
    // Способів три, і всі вони зводяться до одного: під білим текстом
    // гарантовано темна поверхня, хай навіть фото під нею світле.
    const ОЗНАКИ = [
        [/rgb\(var\(--hero-tint-rgb\)\)/, "сезонний відтінок героя"],
        [/background-color:#111827/, "суцільне темне тло"],
        [/linear-gradient\(\s*rgba\(17,\s*24,\s*39,\s*\.\d+\)/, "притемнювальна накладка над фото"]
    ];

    const світлі = правила.filter(п =>
        /\.btn-outline(?!:)/.test(п.сел)
        && /border-color:rgba\(255,255,255,\.55\)/.test(п.тіло));
    const банери = банериЗ(світлі[0].сел);

    for (const б of банери) {
        const свій = правила.filter(п => new RegExp("\\." + б + "(?![\\w-])").test(п.сел));
        const знайдено = ОЗНАКИ.filter(([re]) => свій.some(п => re.test(п.тіло)));
        check(`.${б} справді темний — ${знайдено.map(([, н]) => н).join(", ") || "?"}`,
            знайдено.length > 0,
            "ні темного тла, ні накладки: білий текст на ньому був би невидимий");
    }
}

console.log(failures === 0
    ? "\n✅ Темні банери: світла кнопка й біле кільце знають про кожен\n"
    : `\n❌ Проблем: ${failures}\n`);

process.exit(failures === 0 ? 0 : 1);
