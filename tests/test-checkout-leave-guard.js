// Попередження про вихід зі сторінки замовлення — лише коли є що втрачати.
//
// ЩО БУЛО НЕ ТАК
// ---------------
// Сторінка оформлення тримає сторожа: клік по будь-якому внутрішньому
// посиланню перехоплюється й показує поп-ап «Ви дійсно бажаєте
// залишити сторінку замовлення? Вся інформація про замовлення буде
// втрачена», а «назад», перезавантаження й закриття вкладки дають
// нативне вікно браузера.
//
// Сторож стояв на чергуванні З ЗАВАНТАЖЕННЯ СТОРІНКИ:
// `let leaveGuardActive = true`.
//
// ЗАМІРЯНО 02.11.2026 (Playwright, справжній Chromium): відкрити
// оформлення, не чіпати жодного поля, натиснути лого — поп-ап
// з'являється, перехід заблоковано, заповнених полів НУЛЬ.
//
// Тобто людина, яка зайшла на оформлення, передумала й хоче
// повернутись у каталог, упирається в стіну — а повідомлення каже
// неправду. Кошик теж не аргумент: він у localStorage і переживає
// будь-який відхід. Втратити можна рівно те, що вписали руками.
//
// ЩО ЦЕ ЗАКРІПЛЮЄ
// ----------------
// 1. Поки в полях замовлення нічого не вводили — сторож мовчить.
// 2. Перше справжнє введення (чи вибір радіокнопки) його будить.
// 3. Обидва виходи — поп-ап на посиланнях і нативне beforeunload —
//    питають у того самого прапорця.

const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const code = fs.readFileSync(path.join(ROOT, "assets/js/checkout.js"), "utf8");

// ВИКОНУЄМО СПРАВЖНІЙ ШМАТОК, А НЕ ЙОГО ОПИС.
//
// Поруч у наборах є стенди, де логіку переписують руками, — і саме
// так колись проїхала підміна src у лайтбоксі: тест містив копію й
// був зелений. Тому шматок виймається з checkout.js і виконується як
// є, а формою йому підсовується справжній вузол JSDOM.
//
// МЕЖА ВИБІРКИ — ДО openLeaveModal, а не до останнього слухача.
// Перша версія різала «до addEventListener("change")» — і коли
// ламач прибирав саме цей рядок, вибірка ставала порожньою, а набір
// не червонів, а ОБРИВАВСЯ винятком. Обрив ховає причину.
const ШМАТОК = (code.match(/let leaveGuardActive[\s\S]*?(?=function openLeaveModal)/) || [])[0] || "";

// Стенд: форма з одним полем. Події на ній же й слухають.
function стенд(розмітка) {

    const dom = new JSDOM(`<form id="checkoutForm">${розмітка}</form>`);
    const форма = dom.window.document.getElementById("checkoutForm");

    const зібрати = new Function("checkoutForm", "document",
        ШМАТОК + "\nreturn { стан: () => leaveGuardActive };");

    return { форма, вікно: dom.window,
             стан: зібрати(форма, dom.window.document).стан };

}

console.log("\n[1] Сторожа будить саме введення");
{
    check("шматок зі сторожем вийнято з checkout.js", Boolean(ШМАТОК));

    if (ШМАТОК) {

        const s = стенд("<input id=\"firstName\">");

        check("на свіжій сторінці сторож спить", s.стан() === false,
            "сторож чергує ще до введення");

        s.форма.querySelector("#firstName").dispatchEvent(
            new s.вікно.Event("input", { bubbles: true }));

        check("введення в поле будить сторожа", s.стан() === true);

    }
}

console.log("\n[2] Вибір радіокнопки теж будить");
{
    if (ШМАТОК) {

        const s = стенд("<input type=\"radio\" name=\"deliveryMethod\">");

        check("до вибору — спить", s.стан() === false);

        // Радіокнопки способу доставки, оплати й каналу зв'язку дають
        // `change`; без окремого слухача вибір способу доставки
        // сторожа не розбудив би.
        s.форма.querySelector("input[type=radio]").dispatchEvent(
            new s.вікно.Event("change", { bubbles: true }));

        check("вибір способу доставки будить сторожа", s.стан() === true);

    }
}

console.log("\n[2b] Поля, що з'являються пізніше, теж будять");
{
    if (ШМАТОК) {

        // ЗАРАДИ ЦЬОГО СЛУХАЄМО ФОРМУ, А НЕ ОКРЕМІ ПОЛЯ.
        //
        // Номер відділення, адреса кур'єра й «інший перевізник»
        // показуються аж після вибору способу доставки. Якби слухачі
        // висіли на конкретних полях, введення в них сторожа не
        // розбудило б — а це саме ті поля, які найдовше заповнюють.
        const s = стенд("<input id=\"firstName\">");

        check("до введення — спить", s.стан() === false);

        const пізнє = s.вікно.document.createElement("input");
        пізнє.id = "branchNumber";
        s.форма.appendChild(пізнє);

        пізнє.dispatchEvent(new s.вікно.Event("input", { bubbles: true }));

        check("введення в поле, доданого після слухачів, будить сторожа",
            s.стан() === true, "слухач висить на полі, а не на формі");

    }
}

console.log("\n[3] Обидва виходи питають у того самого прапорця");
{
    // Поп-ап на внутрішніх посиланнях.
    check("клік по посиланню дивиться на прапорець",
        /addEventListener\("click"[\s\S]{0,200}if \(!leaveGuardActive\) return;/.test(code));

    // Нативне вікно на «назад» і закритті вкладки.
    check("beforeunload дивиться на той самий прапорець",
        /addEventListener\("beforeunload"[\s\S]{0,200}if \(!leaveGuardActive\) return;/.test(code));

    // Порожній кошик і вже оформлене замовлення мовчать і без цього —
    // перевірка на схований шар лишилась на місці.
    check("порожній кошик сторожа не турбує",
        /if \(!checkoutLayoutEl \|\| checkoutLayoutEl\.hidden\) return;/.test(code));

    // Після вдалого оформлення сторож мусить замовкнути, інакше перехід
    // на сторінку подяки сам питав би дозволу.
    check("оформлення знімає сторожа", /leaveGuardActive = false;/.test(code));

    // А при невдачі — повернутись: дані в полях ще потрібні.
    check("невдале оформлення повертає сторожа",
        /leaveGuardActive = true;[\s\S]{0,300}submitOrderBtn\.disabled = false/.test(code));
}

console.log(failures === 0
    ? "\n✅ Сторож замовлення: мовчить на порожньому, стереже заповнене\n"
    : `\n❌ Проблем: ${failures}\n`);

process.exit(failures === 0 ? 0 : 1);
