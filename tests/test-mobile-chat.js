console.log("\n[4] Клавіатура більше не накриває панель");
{
    // На iOS клавіатура НЕ зменшує layout viewport — зменшується лише
    // visualViewport. Його й питаємо.
    check("висоту клавіатури вимірюємо", /visualViewport/.test(JS));

    check("рахуємо як різницю вікна й visualViewport",
        /window\.innerHeight - vv\.height - vv\.offsetTop/.test(JS));

    // offsetTop потрібен: під час прокрутки з відкритою клавіатурою
    // Safari зсуває visualViewport угору.
    check("враховано зсув при прокрутці", /vv\.offsetTop/.test(JS));

    check("слухаємо і resize, і scroll",
        /vv\.addEventListener\("resize"/.test(JS) && /vv\.addEventListener\("scroll"/.test(JS));

    // Адресний рядок, що ховається, теж міняє visualViewport на
    // кілька десятків пікселів. Якби ми рахували це за клавіатуру,
    // панель смикалась би при звичайній прокрутці.
    check("дрібні коливання не рахуються за клавіатуру",
        /if \(зїдено < 120\) зїдено = 0;/.test(JS));

    check("віддаємо змінною", /setProperty\("--keyboard-h"/.test(JS));

    // --- а тепер розкладка ---
    //
    // ТУТ Я ВЖЕ ПОМИЛИВСЯ ОДИН РАЗ.
    //
    // Спершу клавіатурні правила стояли окремим блоком у кінці файлу,
    // а перевірка питала «чи стоїть останнім». Позиція не має ваги:
    // «body:has(.consent-banner) .contact-dock» важчий за просто
    // «.contact-dock», тож при відкритій клавіатурі перемагало старе
    // правило, і док не рухався. Заміряно в браузері: панель
    // піднялась на 336, док на нуль.
    //
    // Та сама пастка, на якій я вже спіткнувся з липкою колонкою
    // каталогу.
    //
    // Тепер у дока й панелі РІВНО ОДИН bottom, а стани міняють лише
    // --dock-lift. Саме це й перевіряємо.
    const правилаЗBottom = сел => [...CSS.matchAll(/([^{}]+)\{([^}]*)\}/g)]
        .filter(([, с, т]) => new RegExp(сел + "(?![\\w-])").test(с) && /bottom\s*:/.test(т));

    // Чи веде вираз до потрібної змінної — хоч напряму, хоч через
    // інші змінні. Беремо ВСІ оголошення кожної (їх кілька: базове й
    // по станах) — досить, щоб хоч одне вело далі.
    function ланцюжокВедеДо(вираз, ціль, глибина) {

        if ((глибина || 0) > 5) return false;
        if (вираз.includes(ціль)) return true;

        return (вираз.match(/var\((--[\w-]+)/g) || []).some(знайдене => {

            const імʼя = знайдене.slice(4);
            const оголошення = [...CSS.matchAll(
                new RegExp(імʼя.replace(/-/g, "\\-") + "\\s*:([^;}]*)", "g"))].map(m => m[1]);

            return оголошення.some(о => ланцюжокВедеДо(о, ціль, (глибина || 0) + 1));

        });

    }

    [".contact-dock", ".dock-panel"].forEach(сел => {

        const правила = правилаЗBottom(сел.replace(".", "\\."));

        check(`${сел}: bottom задано рівно один раз`,
            правила.length === 1,
            правила.map(([, с]) => с.trim().replace(/\s+/g, " ")).join(" | "));

        // Клавіатура доходить сюди не напряму, а ланцюжком змінних
        // (--dock-bottom → --panel-bottom). Тому питаємо не текст
        // правила, а чи веде ланцюжок до --keyboard-h: інакше
        // перевірка ламалась би від кожного перейменування, нічого
        // при цьому не стережучи.
        check(`${сел}: той єдиний bottom доходить до клавіатури`,
            правила.length === 1 && ланцюжокВедеДо(правила[0][2], "--keyboard-h"),
            правила.length === 1 ? правила[0][2].replace(/\s+/g, " ") : "");

    });

    // Стани міняють лише змінну — і саме тому не можуть перебити
    // клавіатуру вагою селектора.
    check("стани міняють --dock-lift, а не bottom",
        /body:has\(\.consent-banner\)\{[^}]*--dock-lift/.test(CSS)
        && /body:has\(\.mobile-sticky-cart\.show\)\{[^}]*--dock-lift/.test(CSS));

    check("спільний випадок «банер + кошик» теж через змінну",
        /body:has\(\.consent-banner\):has\(\.mobile-sticky-cart\.show\)\{[^}]*--dock-lift/.test(CSS));

    // Запасне значення обовʼязкове: поки скрипт не відпрацював або
    // клавіатури немає, має бути як було.
    const голих = (CSS.match(/var\(--keyboard-h\)/g) || []).length;

    check("у змінної скрізь є запасне значення 0", голих === 0, String(голих));
}


console.log("\n[5] Панель не вилазить за картку і не ховається під шапку");
{
    // ЩО БУЛО НЕ ТАК. Власник прислав три скріни з iPhone 11: у чаті
    // поле вводу й підписи висять ПОВЕРХ товарів, біля картки, а не в
    // ній; у панелі дзвінка не видно ні заголовка, ні хрестика.
    //
    // Заміряно в Playwright на 414×896 з клавіатурою 300:
    //   чат     — коробка 310px, вміст 342, overflow:visible → 32px
    //             домальовувались нижче картки, вже без білого тла;
    //   дзвінок — стеля не задана взагалі, top:-2 при низі шапки 82,
    //             тобто заголовок під шапкою.
    //
    // Третя причина, найнеочевидніша: клавіатура ДОДАВАЛАСЬ до
    // підйому. А все, що приліплене до низу (банер згоди, кнопка
    // «Купити», сам док), клавіатура просто накриває — обходити їх
    // більше не треба. Через те додавання док спливав на півтори
    // сотні пікселів вище за клавіатуру.

    const правило = (CSS.match(/\.dock-panel\{[^}]*\}/) || [""])[0];

    check("панель має стелю", /max-height\s*:/.test(правило),
        правило.slice(0, 60));

    // ВИСОТУ БЕРЕМО ВИМІРЯНУ, А НЕ З ОДИНИЦЬ CSS.
    //
    // Айфони поводяться по-різному: одні кладуть клавіатуру ЗВЕРХУ й
    // сторінка лишається тієї ж висоти, інші зменшують саму сторінку.
    // А 100dvh про клавіатуру не знає В ОБОХ випадках — і в другому
    // режимі стеля виходила більшою за екран рівно на її висоту: верх
    // панелі із заголовком та хрестиком їхав за край. Власник прислав
    // такий скрін: поле вводу й канали над клавіатурою, а шапки немає.
    //
    // visualViewport.height — єдине число, яке в обох режимах означає
    // те саме: скільки видно.
    check("стеля міряється з виміряної висоти",
        /max-height[^;]*var\(--viewport-h/.test(правило),
        (правило.match(/max-height\s*:[^;]*/) || [""])[0].replace(/\s+/g, " "));

    check("скрипт її публікує",
        /setProperty\("--viewport-h", Math\.round\(vv\.height\)/.test(JS));

    // 100dvh лишається ЗАПАСОМ — до першого заміру змінної ще немає.
    // А 100vh не підходить і поготів: на iOS це весь екран.
    check("у запасі dvh, а не vh",
        /var\(--viewport-h, 100dvh\)/.test(правило) && !/max-height[^;]*100vh/.test(правило));

    // --panel-bottom міряється від низу СТОРІНКИ, --viewport-h від
    // низу ВИДИМОГО. Коли клавіатура лежить зверху, між ними рівно її
    // висота — доданок повертає різницю.
    check("різниця між низом сторінки й низом видимого врахована",
        /max-height[^;]*\+\s*var\(--keyboard-h, 0px\)/.test(правило),
        (правило.match(/max-height\s*:[^;]*/) || [""])[0].replace(/\s+/g, " "));

    // І МІСЦЕ ЗГОРИ — ТЕЖ ВИМІРЯНЕ, А НЕ ЗАШИТЕ.
    //
    // Було «- 82px - 16px»: панель лишала місце під шапку завжди. А
    // шапку не завжди видно — вона приліплена до СТОРІНКИ, і коли з
    // піднятою клавіатурою iOS прокручує видиму область усередині
    // сторінки, шапка виїжджає за верхній край.
    //
    // Власник прислав саме такий скрін: нагорі картка товару, шапки
    // сайту немає, а панель однаково тримає під неї сто пікселів
    // порожнечі. Заміряно: на тих самих даних стеля 300 проти 390,
    // стрічка 64 проти 154.
    check("місце під шапку береться зі змінної, а не числом",
        /max-height[^;]*var\(--panel-top-gap/.test(правило)
        && !/max-height[^;]*82px/.test(правило),
        (правило.match(/max-height\s*:[^;]*/) || [""])[0].replace(/\s+/g, " "));

    check("скрипт міряє, скільки шапки ВИДНО",
        /висотаШапки - Math\.round\(vv\.offsetTop\)/.test(JS));

    check("і публікує це разом із повітрям",
        /setProperty\(\s*"--panel-top-gap"/.test(JS));

    // Коли шапки не видно зовсім, панель усе одно не має впиратись у
    // самий край екрана.
    check("без шапки лишається хоч трохи повітря",
        /видноШапки \? видноШапки \+ 16 : 8/.test(JS));

    // Запас на ту мить, поки скрипт ще не відпрацював: та сама сума
    // 82 + 16, що була зашита раніше.
    check("у змінної є запас 98px", /var\(--panel-top-gap, 98px\)/.test(правило));

    // Той самий вираз, що й у bottom: два списки доданків розійшлись
    // би, і стеля перестала б відповідати тому, де насправді низ.
    check("стеля порахована з того самого виразу, що й низ",
        /max-height[^;]*var\(--panel-bottom/.test(правило) && /bottom\s*:\s*var\(--panel-bottom/.test(правило));

    check("стеля одна", (правило.match(/max-height\s*:/g) || []).length === 1);

    // ГОЛОВНЕ З ТОГО, ЩО БАЧИВ ВЛАСНИК: стеля обмежує лише КОРОБКУ.
    // Діти, які в неї не влізли, спокійно домальовуються нижче — вже
    // без білого тла, поверх товарів.
    check("за межі картки нічого не малюється",
        /overflow(-y)?\s*:\s*auto/.test(правило),
        (правило.match(/overflow[^;]*/) || ["немає"])[0]);

    // auto, а не hidden: обрізати — означає сховати кнопку
    // «Передзвоніть мені» без жодного натяку, що вона є.
    check("вміст не обрізається мовчки",
        !/overflow(-y)?\s*:\s*hidden/.test(правило));

    // КЛАВІАТУРА ЗАМІЩУЄ ПІДЙОМ, А НЕ ДОДАЄТЬСЯ ДО НЬОГО.
    const низДока = (CSS.match(/--dock-bottom\s*:([^;]*)/) || [])[1] || "";

    check("низ дока бере більше з двох, а не суму",
        /max\(/.test(низДока) && низДока.includes("--keyboard-h"),
        низДока.trim());

    check("підйом і клавіатура не складаються",
        !/--dock-bottom\s*:\s*calc\([^;]*--dock-lift[^;]*\+[^;]*--keyboard-h/.test(CSS));

    // СТИСКАЄТЬСЯ ЛИШЕ СТРІЧКА. Інакше місце забирають у всіх
    // пропорційно, і заголовок із полем вводу їдуть за край разом з
    // нею — а без них панеллю не скористаєшся.
    const стрічка = (CSS.match(/\.chat-log\{[^}]*\}/) || [""])[0];

    check("стрічка вміє стискатись", /min-height\s*:\s*0/.test(стрічка),
        (стрічка.match(/min-height[^;]*/) || ["немає"])[0]);

    // І РОСТЕ ЗА РОЗМОВОЮ.
    //
    // Тут стояло flex:1 1 120px — я мав на увазі «бажана висота». У
    // колонці, яка сама заввишки з вміст, рости нема з чого: вільного
    // місця немає, і 120 стали СТЕЛЕЮ. Заміряно: розмова на десять
    // повідомлень показувала те саме віконце, що й на два, хоч панель
    // могла бути на 130px вищою. Власник це й побачив.
    //
    // basis:auto — «заввишки як вміст»; разом із max-height панелі це
    // й дає потрібне: мало повідомлень — панель за вмістом, багато —
    // упирається в стелю, а стискається стрічка.
    check("стрічка росте за розмовою, а не прибита до числа",
        /flex\s*:\s*1\s+1\s+auto/.test(стрічка),
        (стрічка.match(/flex\s*:[^;]*/) || ["немає"])[0]);

    check("висота не зашита числом",
        !/flex\s*:\s*1\s+1\s+\d+px/.test(стрічка) && !/\bheight\s*:\s*\d+px/.test(стрічка));

    check("решта дітей панелі не стискається",
        /\.dock-panel-chat\s*>\s*\*:not\(\.chat-log\)\{[^}]*flex-shrink\s*:\s*0/.test(CSS));

    // На телефоні панель і так на всю ширину й стоїть поверх дока:
    // 120px під нього — це рівно те місце, якого бракувало стрічці.
    check("поки панель відкрита, док на телефоні ховається",
        /body:has\(\.dock-btn\[aria-expanded="true"\]\)\s*\.contact-dock\{[^}]*opacity\s*:\s*0/.test(CSS));

    // aria-expanded, а не [hidden]: hidden знімається через 200мс
    // заради анімації — на цьому вже двічі обпікались.
    check("ознака — aria-expanded, а не hidden",
        !/body:has\(\.dock-panel:not\(\[hidden\]\)\)/.test(CSS));

    // І останнє: на найменших екранах панель усе одно не влізе.
    // Прокрутити її можна, але з початку видно заголовок і поле, а
    // кнопку — ні. Заміряно на 375×667: треба прокрутити 73px.
    check("коли не влазить, скрипт підкручує до кнопки дії",
        /\.dock-submit, \.chat-send/.test(JS) && /scrollIntoView/.test(JS));

    check("підкручує лише коли справді не влазить",
        /scrollHeight <= .*clientHeight\) return;/.test(JS));
}


console.log("\n[6] Поки піднята клавіатура — у панелі лишається головне");
{
    // ЩО БУЛО НЕ ТАК. Стрічку я навчив стискатись (без цього вміст
    // вилазив за картку) — і вона стиснулась надто охоче.
    //
    // Заміряно на 390×750 з клавіатурою 340: панелі лишається 300px, а
    // заголовок, поле вводу й відступи забирають 235. Стрічці
    // діставалось 65 — півтора рядки. Прокрутка в ній була (488px
    // схованого тексту), але читати ніде; власник так і написав:
    // «пропав скрол».
    //
    // Підпис «Зазвичай відповідаємо…» і рядок каналів коштують разом
    // 75 пікселів, стоять НИЖЧЕ поля вводу й обидва довідкові. Поки
    // людина друкує, вона їх уже прочитала. Без них стрічка — 120, як
    // і без клавіатури.
    check("довідкові рядки ховаються",
        /body\.keyboard-up \.chat-note,\s*body\.keyboard-up \.chat-channels\{[^}]*display:none/.test(CSS),
        (CSS.match(/body\.keyboard-up[^{]*\{[^}]*\}/) || ["немає"])[0].replace(/\s+/g, " "));

    // Ховаємо саме те, що нижче поля вводу. Заголовок і саме поле —
    // те, без чого панеллю не скористаєшся.
    check("заголовок і поле вводу не чіпаємо",
        !/body\.keyboard-up[^{]*\.(dock-panel-head|chat-form|chat-input)[^{]*\{/.test(CSS));

    // CSS не вміє питати, чи більша змінна за нуль, — тому клас.
    check("клас ставить скрипт за виміряною висотою",
        /classList\.toggle\("keyboard-up", зїдено > 0\)/.test(JS));

    // Клас на body, бо саме так його шукає правило вище. Розійдуться —
    // правило стане мертвим, і ніхто цього не помітить.
    check("клас саме на body, як і в правилі",
        /document\.body\.classList\.toggle\("keyboard-up"/.test(JS));

    // Поза медіазапитом навмисно: клас зʼявляється рівно тоді, коли
    // піднята екранна клавіатура, і на планшеті це так само правда.
    //
    // Питаємо парсером, а не зрізом тексту: медіазапитів у файлі
    // кілька десятків, і «усе до першого з них» — не те саме, що
    // «поза медіазапитами». Першу версію цієї перевірки я написав
    // саме так, і вона була хибно червоною.
    const csstree = require("css-tree");

    let поза = false;

    csstree.walk(csstree.parse(CSS), {
        visit: "Rule",
        enter(node, item, list) {
            const sel = csstree.generate(node.prelude);
            if (!sel.includes("body.keyboard-up")) return;
            // atrule у стеку означає, що правило всередині @media
            поза = poza(this.atrule) || поза;
        }
    });

    function poza(atrule) { return !atrule; }

    check("правило діє не лише на вузьких екранах", поза);
}


console.log("\n[7] Поки друкують — сторінка під панеллю не їздить");
{
    // ЩО БАЧИВ ВЛАСНИК: «скрол на мобілці стоїть на сторінці, а не на
    // чаті — коли скролю, скролиться сторінка, а не текст у чаті». І
    // окремо: з прихованою клавіатурою стрічка гортається нормально.
    //
    // Панель приліплена (position:fixed), а сторінка під нею лишається
    // прокрутною. Поки піднята клавіатура, iOS ще й сам возить
    // сторінку, щоб тримати поле в полі зору, — і дотик усередині
    // невеликої вкладеної стрічки дістається сторінці.
    //
    // overscroll-behavior тут не рятує: він про те, що буде, коли
    // ДОЇХАЛИ до краю, а не про те, кому дістанеться жест спочатку.
    const правило = (CSS.match(/body\.keyboard-up[^{]*\{[^}]*overflow\s*:\s*hidden[^}]*\}/) || [""])[0];

    check("сторінка завмирає, поки піднята клавіатура", !!правило,
        правило.replace(/\s+/g, " ") || "немає");

    // НАЙВАЖЛИВІШЕ В ЦЬОМУ ПРАВИЛІ — УМОВА.
    //
    // Клас keyboard-up ставить сам факт піднятої клавіатури, байдуже
    // де людина друкує. Без умови про відкритий чат сторінка завмирала
    // б і при вводі адреси в оформленні замовлення — там прокрутка
    // якраз потрібна.
    check("і лише коли відкритий саме чат",
        /#dockChat\[aria-expanded="true"\]/.test(правило),
        правило.replace(/\s+/g, " ") || "немає");

    // Прямо кажемо браузеру, кому належить вертикальне протягування.
    const стрічка = (CSS.match(/\.chat-log\{[^}]*\}/) || [""])[0];

    check("стрічка заявляє вертикальне протягування своїм",
        /touch-action\s*:\s*pan-y/.test(стрічка),
        (стрічка.match(/touch-action[^;]*/) || ["немає"])[0]);

    check("і не дає переповненню чіплятись за сторінку",
        /overscroll-behavior\s*:\s*contain/.test(стрічка));
}


