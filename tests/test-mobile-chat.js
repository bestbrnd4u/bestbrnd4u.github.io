// ЧОТИРИ ДЕФЕКТИ, ЯКІ ВИДНО ЛИШЕ НА IPHONE
//
// Усі чотири прислав власник зі свого телефона. Жоден не видно ні в
// тестах на jsdom, ні в емуляції розміру екрана: вони про те, як
// поводиться САМЕ Safari на iOS.
//
//   1. Тап у поле — екран наближається. Safari сам робить зум, щойно
//      фокус потрапляє в поле зі шрифтом меншим за 16px.
//
//   2. Закрив чат — на круглій кнопці лишився синій КВАДРАТ. Базове
//      правило фокуса містило border-radius:inherit, а inherit бере
//      значення в БАТЬКА: у круглої кнопки батько без скруглення,
//      тож кнопка на час фокуса ставала квадратною разом із рамкою.
//
//   3. Клавіатура накрила панель. На iOS вона НЕ зменшує сторінку —
//      просто лягає зверху, і кнопка «Передзвоніть мені» опиняється
//      під нею.
//
//   4. Те саме при прокрутці з відкритою клавіатурою.
//
// ЧОМУ ПЕРЕВІРКИ ТАКІ, ЯК Є
//
// Safari тут немає й не буде. Тому перевіряємо те, від чого ці
// дефекти залежать напряму: розмір шрифту в полях, відсутність
// згубного inherit, наявність заміру клавіатури й те, що розкладка
// його враховує.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;

const check = (name, condition, extra) => {
    if (condition) console.log("  ✓", name);
    else { console.log("  ✗", name, extra !== undefined ? "→ " + extra : ""); failures++; }
};

const read = file => fs.readFileSync(path.join(ROOT, file), "utf8");

const RAW = read("assets/css/style.css");
const CSS = RAW.replace(/\/\*[\s\S]*?\*\//g, " ");
const JS = read("assets/js/contact-buttons.js");

// Правило за селектором, із коментарями вже прибраними.
function правило(селектор) {

    const m = CSS.match(new RegExp(
        селектор.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\{([^}]*)\\}"));

    return m ? m[1] : "";

}


console.log("\n[1] Поля не змушують Safari наближати сторінку");
{
    // 16px — межа, нижче якої iOS робить зум при фокусі. Повернути
    // масштаб назад людина мусить сама, двома пальцями.
    const поля = [
        ['.chat-input', "поле чату"],
        ['.dock-form input[type="tel"]', "поле телефону"]
    ];

    поля.forEach(([сел, назва]) => {

        const тіло = правило(сел);

        check(`${назва}: правило знайдено`, !!тіло.trim(), сел);

        const розмір = Number((тіло.match(/font-size\s*:\s*(\d+(?:\.\d+)?)px/) || [])[1]);

        check(`${назва}: шрифт не менший за 16px`, розмір >= 16, `${розмір}px`);

    });

    // І щоб ніхто не «полагодив» це забороною зуму: viewport із
    // user-scalable=no або maximum-scale відбирає в людини
    // можливість наблизити сторінку взагалі. Зум — це доступність,
    // а не примха.
    const сторінки = fs.readdirSync(ROOT).filter(f => f.endsWith(".html"));

    const заборонили = сторінки.filter(f =>
        /user-scalable\s*=\s*no|maximum-scale\s*=\s*1/.test(read(f)));

    check("зум на сторінках не заборонений", заборонили.length === 0, заборонили.join(", "));
}


console.log("\n[2] Фокус не перетворює круглу кнопку на квадрат");
{
    const базове = CSS.match(/a:focus-visible,[\s\S]*?\{([^}]*)\}/);

    check("базове правило фокуса знайдено", !!базове);

    const тіло = базове ? базове[1] : "";

    // ОСЬ ВОНО. inherit бере скруглення В БАТЬКА, а не в елемента.
    // У круглої кнопки батько без скруглення — і кнопка на час
    // фокуса ставала квадратною.
    check("немає border-radius:inherit",
        !/border-radius\s*:\s*inherit/.test(тіло), тіло.replace(/\s+/g, " "));

    // Але сама рамка лишається: прибрати її означало б лишити того,
    // хто ходить клавіатурою, без жодної ознаки, де він.
    check("рамка на місці", /outline\s*:\s*3px solid/.test(тіло));
    check("і не притиснута до краю", /outline-offset/.test(тіло));

    // Кругла кнопка дока має власне скруглення — перевіряємо, що його
    // ніхто не перебиває.
    check("кнопка дока лишається круглою",
        /border-radius\s*:\s*50%/.test(правило(".dock-btn")));
}


console.log("\n[3] Фокус повертається на кнопку лише для клавіатури");
{
    // Фокус потрібен тому, хто ходить Tab-ом. Але на дотику це видно
    // як рамка, що лишилась висіти після закриття чату.
    check("є помічник, який це розрізняє", /function поверниФокус/.test(JS));

    // detail === 0 — клік від Enter чи пробілу, а не від пальця.
    check("розрізняємо за detail", /подія\.detail > 0/.test(JS));

    check("кнопка дока користується ним", /поверниФокус\(пара\.кнопка, e\)/.test(JS));

    // Обробник мусить отримати подію — інакше помічник завжди
    // вважатиме клік клавіатурним.
    check("обробник приймає подію",
        /пара\.кнопка\.addEventListener\("click", function \(e\)/.test(JS));

    // А ось Esc — це завжди клавіатура, там фокус повертаємо прямо.
    check("на Esc фокус повертається без умов",
        /if \(e\.key !== "Escape"\) return;[\s\S]{0,400}пара\.кнопка\.focus\(\);/.test(JS));
}


console.log("\n[4] Клавіатура більше не накриває панель");
{
    // На iOS клавіатура НЕ зменшує layout viewport — зменшується лише
    // visualViewport. Його й питаємо.
    check("висоту клавіатури вимірюємо", /visualViewport/.test(JS));

    check("рахуємо як різницю вікна й visualViewport",
        /window\.innerHeight - vv\.height - vv\.offsetTop/.test(JS));

    // offsetTop потрібен: під час прокрутки з відкритою клавіатурою
    // Safari зсуває visualViewport угору.
    check("враховано зсув при прокрутці", /vv\.offsetTop/.test(JS));

    check("слухаємо і resize, і scroll",
        /vv\.addEventListener\("resize"/.test(JS) && /vv\.addEventListener\("scroll"/.test(JS));

    // Адресний рядок, що ховається, теж міняє visualViewport на
    // кілька десятків пікселів. Якби ми рахували це за клавіатуру,
    // панель смикалась би при звичайній прокрутці.
    check("дрібні коливання не рахуються за клавіатуру",
        /if \(зїдено < 120\) зїдено = 0;/.test(JS));

    check("віддаємо змінною", /setProperty\("--keyboard-h"/.test(JS));

    // --- а тепер розкладка ---
    //
    // ТУТ Я ВЖЕ ПОМИЛИВСЯ ОДИН РАЗ.
    //
    // Спершу клавіатурні правила стояли окремим блоком у кінці файлу,
    // а перевірка питала «чи стоїть останнім». Позиція не має ваги:
    // «body:has(.consent-banner) .contact-dock» важчий за просто
    // «.contact-dock», тож при відкритій клавіатурі перемагало старе
    // правило, і док не рухався. Заміряно в браузері: панель
    // піднялась на 336, док на нуль.
    //
    // Та сама пастка, на якій я вже спіткнувся з липкою колонкою
    // каталогу.
    //
    // Тепер у дока й панелі РІВНО ОДИН bottom, а стани міняють лише
    // --dock-lift. Саме це й перевіряємо.
    const правилаЗBottom = сел => [...CSS.matchAll(/([^{}]+)\{([^}]*)\}/g)]
        .filter(([, с, т]) => new RegExp(сел + "(?![\\w-])").test(с) && /bottom\s*:/.test(т));

    [".contact-dock", ".dock-panel"].forEach(сел => {

        const правила = правилаЗBottom(сел.replace(".", "\\."));

        check(`${сел}: bottom задано рівно один раз`,
            правила.length === 1,
            правила.map(([, с]) => с.trim().replace(/\s+/g, " ")).join(" | "));

        check(`${сел}: той єдиний bottom додає клавіатуру`,
            правила.length === 1 && /var\(--keyboard-h, 0px\)/.test(правила[0][2]),
            правила.length === 1 ? правила[0][2].replace(/\s+/g, " ") : "");

    });

    // Стани міняють лише змінну — і саме тому не можуть перебити
    // клавіатуру вагою селектора.
    check("стани міняють --dock-lift, а не bottom",
        /body:has\(\.consent-banner\)\{[^}]*--dock-lift/.test(CSS)
        && /body:has\(\.mobile-sticky-cart\.show\)\{[^}]*--dock-lift/.test(CSS));

    check("спільний випадок «банер + кошик» теж через змінну",
        /body:has\(\.consent-banner\):has\(\.mobile-sticky-cart\.show\)\{[^}]*--dock-lift/.test(CSS));

    // Висота панелі чату теж мусить зважати на клавіатуру, інакше
    // стрічка вилізе за верх екрана й зникне заголовок із хрестиком.
    check("висота панелі чату враховує клавіатуру",
        /\.dock-panel-chat\{[^}]*max-height[^;]*var\(--keyboard-h, 0px\)/.test(CSS));

    // Запасне значення обовʼязкове: поки скрипт не відпрацював або
    // клавіатури немає, має бути як було.
    const голих = (CSS.match(/var\(--keyboard-h\)/g) || []).length;

    check("у змінної скрізь є запасне значення 0", голих === 0, String(голих));
}


console.log(failures === 0 ? "\n✅ Усі перевірки пройдено" : `\n❌ Провалено: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
