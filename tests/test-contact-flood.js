// ЧАТ І ЗВОРОТНИЙ ДЗВІНОК НЕ МАЮТЬ СТАТИ ЗАСОБОМ ФЛУДУ
//
// ЩО БУЛО НЕ ТАК
// ---------------
// Обидві функції користувались лічильником сторінки «Де моє
// замовлення»: 20 звернень на IP за годину, 400 глобально. Для пошуку
// замовлення це правильні числа, для цих двох — ні.
//
//   1. Межа по IP стояла лише на СТВОРЕННІ нитки чату. Далі межа йшла
//      тільки по нитці — 30 на годину. Отже:
//
//          20 ниток × 30 повідомлень = 620 повідомлень у Telegram
//          за годину з однієї адреси.
//
//   2. Лічильник спільний: вичерпавши 400 на годину чатом, зловмисник
//      гасив «Де моє замовлення» й підписку ДЛЯ ВСІХ покупців.
//
//   3. Зворотний дзвінок не дивився на сам номер. Двадцять разів
//      вписати чужий — і власник двадцять разів дзвонить незнайомцю,
//      причому знаряддям виглядає магазин.
//
//   4. Опитування чату не мало межі взагалі.
//
// ЧОМУ ПЕРЕВІРКИ САМЕ ТАКІ
// -------------------------
// Числа тут не головне — їх підніматимуть, коли магазин виросте.
// Головне — ЗВ'ЯЗКИ, які легко загубити при наступній правці:
// окремий лічильник, межа до розгалуження, межа по номеру, стеля на
// опитування, і те, що власник дізнається про напад один раз, а не
// сотню.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;

const check = (name, condition, extra) => {
    if (condition) console.log("  ✓", name);
    else { console.log("  ✗", name, extra !== undefined ? "→ " + extra : ""); failures++; }
};

const read = file => fs.readFileSync(path.join(ROOT, file), "utf8");

const ФУНКЦІЯ = read("supabase/functions/telegram-order-bot/_index.src.ts");
const ЗІБРАНА = read("supabase/functions/telegram-order-bot/index.ts");
const МІГРАЦІЯ = read("supabase/migrations/040-contact-flood.sql");

// Сам SQL, без пояснень. Пояснення в цьому проєкті довгі, і перевірка
// «чи згадується таке слово» ловила б саме їх: lookup_throttle
// названий у коментарі «окремий від lookup_throttle» — і це рівно
// протилежне тому, що перевірка хотіла знайти.
const SQL = МІГРАЦІЯ
    .split("\n")
    .filter(рядок => !/^\s*--/.test(рядок))
    .join("\n")
    .replace(/comment on [\s\S]*?;/gi, " ");
const МОДУЛЬ = read("assets/js/contact-buttons.js");

const блок = (назва) =>
    (ФУНКЦІЯ.match(new RegExp(`async function ${назва}[\\s\\S]*?\\n}\\n`)) || [""])[0];


console.log("\n[1] Лічильник окремий від пошуку замовлення");
{
    // НАЙВАЖЛИВІШЕ. Спільний лічильник означав, що флуд у чаті гасить
    // «Де моє замовлення» справжнім покупцям — тобто напад на одну
    // функцію ламає зовсім іншу.
    check("є власна таблиця лічильника",
        /create table if not exists public\.contact_throttle/.test(МІГРАЦІЯ));

    check("вона не чіпає lookup_throttle",
        !/lookup_throttle/.test(SQL));

    ["handleCallBack", "handleChatSend"].forEach(имʼя => {

        check(`${имʼя}: більше не кличе лічильник пошуку замовлення`,
            !/lookupAllowed/.test(блок(имʼя)));

        check(`${имʼя}: кличе власний`,
            /contactAllowed\(request,/.test(блок(имʼя)));

    });

    // НАЙВАЖЛИВІШЕ В ЧАТІ, І ЦЕ ЛЕГКО ВТРАТИТИ ПРИ ПРАВЦІ.
    //
    // Межа має стояти на ОБОХ шляхах — і на новій нитці, і на
    // повідомленні в наявній. Спершу було лише на новій, і це давало
    // 620 повідомлень у Telegram за годину з однієї адреси.
    //
    // Питаємо не «чи є виклик десь у функції» (він лишиться й тоді,
    // коли його сховають у гілку «якщо нитка нова»), а чи вибирається
    // ВИД звернення тернарником — тобто чи працює межа в обох
    // випадках.
    check("межа чату діє і на новій нитці, і на наявній",
        /contactAllowed\(request, перше \? "chat-new" : "chat-msg"\)/.test(блок("handleChatSend")),
        (блок("handleChatSend").match(/contactAllowed\([^)]*\)/) || ["не знайшов"])[0]);
}


console.log("\n[2] Межі описані в одному місці й не загублені");
{
    const межі = (ФУНКЦІЯ.match(/const CONTACT_LIMITS = \{([\s\S]*?)\};/) || [, ""])[1];

    check("перелік меж знайдено", !!межі.trim());

    ["callback", "chat-new", "chat-msg"].forEach(вид => {

        check(`${вид}: межа задана`,
            new RegExp(`"?${вид}"?:\\s*\\{[^}]*perIp:\\s*\\d+[^}]*global:\\s*\\d+`).test(межі),
            межі.replace(/\s+/g, " "));

    });

    // Людині треба ОДИН дзвінок. Два, якщо помилилась цифрою.
    const дзвінок = (межі.match(/callback:\s*\{\s*perIp:\s*(\d+)/) || [])[1];

    check("дзвінків з адреси не більше пʼяти на годину",
        Number(дзвінок) > 0 && Number(дзвінок) <= 5, дзвінок);

    // Глобальна межа тісна навмисно: Telegram, у якому за годину лягло
    // триста повідомлень, непридатний для роботи — тобто напад досяг
    // мети, навіть якщо формально нічого не зламалось.
    const усіГлобальні = [...межі.matchAll(/global:\s*(\d+)/g)].map(m => Number(m[1]));

    check("жодна глобальна межа не більша за 200",
        усіГлобальні.length === 3 && усіГлобальні.every(n => n <= 200),
        усіГлобальні.join(", "));
}


console.log("\n[3] Магазином не можна цькувати стороннього");
{
    const callback = блок("handleCallBack");

    // Адресу зловмисник змінить, а номер, який цькують, лишається той
    // самий — тому межа саме по номеру, а не лише по IP.
    check("є межа по самому номеру", /rpc\/callback_phone_allowed/.test(callback));

    check("функція межі існує в міграції",
        /create or replace function public\.callback_phone_allowed/.test(МІГРАЦІЯ));

    check("номер зберігається хешем, а не відкрито",
        /digest\(salt \|\| btrim\(p_phone\)/.test(МІГРАЦІЯ)
        && !/insert into public\.callback_throttle \(phone\)/.test(МІГРАЦІЯ));

    // Людина, яка справді чекає дзвінка, має почути «заявка вже є», а
    // не «забагато спроб»: друге звучить як відмова.
    check("повтор номера має власний код", /error: "phone_repeat"/.test(callback));

    check("сайт каже про повтор окремо",
        /error === "phone_repeat"/.test(МОДУЛЬ));

    check("і каже це спокійно, не як помилку",
        /phone_repeat[\s\S]{0,260}"ok"\)/.test(МОДУЛЬ));
}


console.log("\n[4] Опитування чату має стелю");
{
    const poll = блок("handleChatPoll");

    check("опитування перевіряє межу", /rpc\/chat_poll_allowed/.test(poll));

    check("функція межі існує",
        /create or replace function public\.chat_poll_allowed/.test(МІГРАЦІЯ));

    // Сайт питає раз на пʼять секунд і лише поки панель відкрита —
    // 720 на годину. Стеля мусить бути вищою, інакше чесний відвідувач
    // упреться в неї раніше за зловмисника.
    const стеля = (МІГРАЦІЯ.match(/return v_count <= (\d+);/) || [])[1];

    check("стеля вища за те, що робить сам сайт",
        Number(стеля) > 720, `${стеля} проти 720`);

    // Лічильник у рядку нитки, а не окремою таблицею: опитування має
    // лишатись дешевим, інакше захист від навантаження сам стає
    // навантаженням.
    check("лічильник не потребує окремої вставки",
        /update public\.chat_threads[\s\S]{0,400}poll_count/.test(МІГРАЦІЯ));
}


console.log("\n[5] Власник дізнається про напад — один раз, не сто");
{
    check("є окреме повідомлення про флуд",
        /async function warnAboutFlood/.test(ФУНКЦІЯ));

    // Сто повідомлень «вас флудять» — це той самий флуд, тільки від
    // нас. Тому попередження йде лише на ПЕРШЕ відхилення за годину.
    check("шлемо лише на перше відхилення за годину",
        /вердикт === "global-first"/.test(ФУНКЦІЯ));

    check("база вміє відрізнити перше відхилення",
        /'global-first'/.test(SQL) && /when v_denied = 0 then 'global-first'/.test(SQL));

    check("обидва обробники вміють попередити",
        (ФУНКЦІЯ.match(/warnAboutFlood\(/g) || []).length >= 3);

    // Межа по IP — це майже завжди нетерплячий покупець, і будити
    // власника через нього не треба.
    check("через межу по IP власника не будимо",
        !/вердикт === "ip"[\s\S]{0,120}warnAboutFlood/.test(ФУНКЦІЯ));
}


console.log("\n[6] Зламаний лічильник не глушить чат");
{
    // Та сама засада, що в решті запобіжників проєкту: лічильник, який
    // через власну помилку відповідає «ні», перекрив би чат усім
    // покупцям одразу. Мовчазний чат гірший за зайве повідомлення.
    ["contact_allowed", "callback_phone_allowed", "chat_poll_allowed"].forEach(имʼя => {

        const тіло = (МІГРАЦІЯ.match(
            new RegExp(`create or replace function public\\.${имʼя}[\\s\\S]*?\\n\\$\\$;`)) || [""])[0];

        check(`${имʼя}: при збої пропускає`,
            /exception when others then[\s\S]*?return (true|'ok')/.test(тіло), имʼя);

    });

    check("у функції теж: немає відповіді — пропускаємо",
        /if \(!response\.ok\) \{[\s\S]{0,160}return "ok";/.test(ФУНКЦІЯ));
}


console.log("\n[7] Межі не можна покликати з браузера");
{
    ["contact_allowed", "callback_phone_allowed", "chat_poll_allowed"].forEach(имʼя => {

        check(`${имʼя}: права відкликані в anon`,
            new RegExp(`revoke execute on function public\\.${имʼя}\\([^)]*\\)\\s*\\n?\\s*from anon`)
                .test(МІГРАЦІЯ), имʼя);

    });

    check("таблиці лічильників закриті RLS",
        /alter table public\.contact_throttle enable row level security/.test(МІГРАЦІЯ)
        && /alter table public\.callback_throttle enable row level security/.test(МІГРАЦІЯ));

    check("політик RLS немає жодної", !/create policy/i.test(МІГРАЦІЯ));
}


console.log("\n[8] Відхилене повідомлення видно НА НЬОМУ, а не лише внизу");
{
    // Відхилене повідомлення лишалось на екрані такою самою синьою
    // бульбашкою, як доставлене. Людина впевнена, що її почули, і йде
    // чекати відповіді, якої не буде.
    check("бульбашка позначається як ненадіслана",
        /classList\.add\("chat-msg-failed"\)/.test(МОДУЛЬ));

    const css = read("assets/css/style.css");

    check("для неї є окремий вигляд", /\.chat-msg-failed \.chat-msg-body\{/.test(css));

    check("і підпис «не надіслано»", /content:"не надіслано"/.test(css));
}


console.log("\n[9] Зібраний файл функції не відстав");
{
    // Деплоять саме index.ts. Якщо він зібраний зі старих джерел,
    // межі лишаться на папері.
    ["contact_allowed", "callback_phone_allowed", "chat_poll_allowed"].forEach(имʼя => {
        check(`${имʼя} є в зібраному файлі`, ЗІБРАНА.includes(имʼя));
    });

    // Саме слово, а не частина іншого: перевірка на includes лишалась
    // зеленою, коли я навмисно перейменував константу в
    // CONTACT_LIMITS_OLD — вона ж містить потрібний рядок.
    check("CONTACT_LIMITS є в зібраному файлі",
        /\bCONTACT_LIMITS\b(?!_)/.test(ЗІБРАНА));
}


console.log(failures === 0 ? "\n✅ Усі перевірки пройдено" : `\n❌ Провалено: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
