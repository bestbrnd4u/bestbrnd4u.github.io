// Ворота проти відомих вразливостей у залежностях.
//
// ЗВІДКИ ВЗЯЛОСЬ
// ---------------
// 19.10.2026 власник знайшов на сторінці Dependabot дві відкриті
// скарги високого рівня — sharp і source-map-js, обидві висіли
// тижнями. Жодна перевірка про них не знала: тести дивляться на файли
// репозиторію, а про вразливості знає реєстр npm.
//
// Автоматика спрацювала наполовину: на sharp Dependabot підняв PR, і
// той лежав відкритим; на source-map-js PR не з'явився взагалі, бо
// виправлена 1.2.2 вже підходила під `^1.2.1` від css-tree — треба
// було лише перерахувати lock. Тобто сповіщення жило тільки на
// сторінці, куди треба зайти самому.
//
// ЧОМУ ЦЕЙ НАБІР НЕ ХОДИТЬ У МЕРЕЖУ
// ----------------------------------
// Решта 200 наборів працюють офлайн і дають однаковий результат
// сьогодні й через рік. Набір, що питає реєстр, почав би падати від
// чужих релізів — і привчив би ганяти тести з пропуском.
//
// Тому в мережу ходить сама робота в CI (.github/workflows/tests.yml),
// а тут перевіряється РІШЕННЯ воріт: тому самому коду підсовуються
// вигадані звіти й звіряється, що він пропускає й що валить.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const read = rel => fs.readFileSync(path.join(ROOT, rel), "utf8");

const { вердикт } = require("../scripts/audit-gate.js");

// Звіт тієї самої форми, яку віддає `npm audit --json`.
const звіт = пакети => ({
    auditReportVersion: 2,
    vulnerabilities: пакети,
    metadata: { vulnerabilities: { total: Object.keys(пакети).length } }
});

const запис = (severity, fixAvailable, title) => ({
    severity,
    fixAvailable,
    range: "1.0.0 - 1.2.1",
    via: [{ title, url: "https://github.com/advisories/TEST", severity }]
});


console.log("\n[1] Важку вразливість із простим виправленням ворота НЕ пропускають");
{
    // Саме цей випадок і висів тижнями: `npm audit fix` і все.
    const { провали, попередження } = вердикт(звіт({
        "source-map-js": запис("high", true, "event-loop denial of service")
    }));

    check("high із доступним виправленням — провал", провали.length === 1,
        JSON.stringify(провали));

    check("у скарзі названо пакет", провали[0] && провали[0].назва === "source-map-js");

    check("…рівень", провали[0] && провали[0].рівень === "high");

    // Без цього рядка людина мусить сама здогадуватись, що робити.
    check("…і як лікувати", провали[0] && /npm audit fix/.test(провали[0].лікування),
        провали[0] && провали[0].лікування);

    check("заголовок поради доїхав із via",
        провали[0] && провали[0].заголовок === "event-loop denial of service");

    check("у попередження воно не потрапило", попередження.length === 0);

    const critical = вердикт(звіт({ "щось": запис("critical", true, "x") }));

    check("critical так само", critical.провали.length === 1);

    // fixAvailable буває і об'єктом із версією — тоді її варто назвати.
    const зВерсією = вердикт(звіт({
        "sharp": запис("high", { name: "sharp", version: "0.35.5", isSemVerMajor: false }, "CVE")
    }));

    check("коли відома версія виправлення — вона у підказці",
        зВерсією.провали.length === 1
        && /sharp@0\.35\.5/.test(зВерсією.провали[0].лікування),
        зВерсією.провали[0] && зВерсією.провали[0].лікування);
}


console.log("\n[2] А те, з чим нічого не вдієш, — лише попередження");
{
    // ЧОМУ НЕ ВСЕ ПІДРЯД ВАЛИТЬ ЗБІРКУ.
    //
    // Нова скарга з'являється на боці реєстру, без жодної правки в
    // коді. Ворота, що валять геть усе, одного ранку зупинили б усі
    // пуші поспіль — зокрема й той, яким цю скаргу лікують.
    const безВиправлення = вердикт(звіт({
        "щось": запис("high", false, "поки без патча")
    }));

    check("виправлення немає — не провал", безВиправлення.провали.length === 0);

    check("…але попередження є", безВиправлення.попередження.length === 1);

    check("…і сказано чому", безВиправлення.попередження[0]
        && /виправлення ще немає/.test(безВиправлення.попередження[0].чому),
        безВиправлення.попередження[0] && безВиправлення.попередження[0].чому);

    // Мажорна версія збірочного інструмента може вимагати роботи.
    // Блокувати на цей час усі пуші — гірше за саму вразливість.
    const мажор = вердикт(звіт({
        "jsdom": запис("high", { name: "jsdom", version: "40.0.0", isSemVerMajor: true }, "x")
    }));

    check("виправлення лише через мажор — не провал", мажор.провали.length === 0);

    check("…а попередження з номером версії", мажор.попередження.length === 1
        && /jsdom@40\.0\.0/.test(мажор.попередження[0].чому),
        мажор.попередження[0] && мажор.попередження[0].чому);

    // Дрібниці не мають права зупиняти роботу взагалі.
    const дрібне = вердикт(звіт({
        "a": запис("moderate", true, "x"),
        "b": запис("low", true, "x"),
        "c": запис("info", true, "x")
    }));

    check("moderate і нижче — ні провалу, ні попередження",
        дрібне.провали.length === 0 && дрібне.попередження.length === 0,
        JSON.stringify(дрібне));
}


console.log("\n[3] Порожній або зламаний звіт нічого не блокує");
{
    // Мережі може не бути — локально чи у відрізаному контейнері.
    // Перевірка, яка падає без інтернету, привчає ганяти тести з
    // пропуском, і тоді мовчать уже всі 200 наборів.
    // Не просто «нуль провалів», а «не впало»: ворота, що кидають
    // виняток на порожньому звіті, валять роботу в CI з Node-слідом
    // замість зрозумілої скарги — і виглядає це як поломка збірки, а
    // не як відсутність мережі.
    const безПадіння = (назва, вхід) => {

        try {
            check(назва, вердикт(вхід).провали.length === 0);
        } catch (error) {
            check(назва, false, "ворота впали: " + error.message);
        }

    };

    безПадіння("порожній перелік", звіт({}));

    безПадіння("звіт без поля vulnerabilities", {});

    безПадіння("нічого замість звіту", null);

    const джерело = read("scripts/audit-gate.js");

    check("без відповіді npm ворота пропускають і кажуть про це",
        /::warning::npm audit не відповів/.test(джерело));

    // npm виходить із кодом 1, щойно щось знайшов. Якби запуск
    // покладався на код виходу, ворота бачили б «помилку запуску»
    // рівно тоді, коли насправді є що показати, — і мовчали б.
    check("ненульовий код npm розбирається як результат, а не як збій",
        /error && error\.stdout/.test(джерело) && /JSON\.parse\(out\)/.test(джерело));
}


console.log("\n[4] Ворота справді стоять у CI");
{
    const workflow = read(".github/workflows/tests.yml");

    check("робота audit є", /^\s{2}audit:/m.test(workflow));

    check("і запускає саме ці ворота",
        /node scripts\/audit-gate\.js/.test(workflow));

    // npm ci (а не install) — аудит мусить дивитись рівно на те, що
    // зафіксовано в lock, інакше він перевіряє не те, що поїде.
    const робота = workflow.slice(workflow.search(/^\s{2}audit:/m));

    check("перед аудитом ставиться залежності з lock",
        /run: npm ci/.test(робота));

    check("порядок саме такий: спершу ci, потім ворота",
        робота.indexOf("npm ci") < робота.indexOf("audit-gate.js"));

    // Пуші в dev теж мусять перевірятись: робота йде там, а в main
    // усе потрапляє одним перенесенням (Sync branches).
    //
    // Тригерів ДВА — push і pull_request, — і dev потрібен в обох:
    // бракуватиме в одному, і половина випадків лишиться без
    // перевірки, а перевірка «десь у файлі є main, dev» цього не
    // побачить.
    const тригери = (workflow.match(/branches: \[[^\]]*\]/g) || []);

    check(`тригерів із переліком гілок: ${тригери.length}`, тригери.length === 2,
        тригери.join(" | "));

    check("dev є в кожному — і на push, і на pull_request",
        тригери.length === 2 && тригери.every(t => /\bdev\b/.test(t)),
        тригери.join(" | "));

    // ЗАПУСК ОКРЕМОЮ РОБОТОЮ, А НЕ КРОКОМ ПОРУЧ ІЗ ТЕСТАМИ.
    // Крок після тестів не дійшов би до запуску після їх падіння, а
    // крок перед ними ховав би їхній результат.
    const тести = workflow.slice(workflow.search(/^\s{2}test:/m),
        workflow.search(/^\s{2}audit:/m));

    // Шукаємо саме КРОК, а не згадку: пояснення, чому ворота стоять
    // окремо, живе в коментарі — і він якраз у цьому ж відрізку.
    check("у роботі з тестами воріт немає — це окремі галочки",
        !/run: node scripts\/audit-gate\.js/.test(тести));
}


console.log("\n[5] Залежності зараз чисті");
{
    // Офлайн-частина: звіряємо, що встановлені версії не нижчі за ті,
    // якими закрили скарги 19.10.2026. Це не заміна аудиту — це
    // пам'ять про конкретні два випадки, щоб відкат lock не пройшов
    // непоміченим, навіть коли мережі немає.
    const lock = JSON.parse(read("package-lock.json"));

    const версія = шлях => (lock.packages && lock.packages[шлях] || {}).version || "";

    const частини = v => String(v).split(".").map(n => parseInt(n, 10) || 0);

    const не_нижче = (було, треба) => {
        const a = частини(було), b = частини(треба);
        for (let i = 0; i < 3; i++) {
            if ((a[i] || 0) !== (b[i] || 0)) return (a[i] || 0) > (b[i] || 0);
        }
        return true;
    };

    const sharp = версія("node_modules/sharp");
    const smjs = версія("node_modules/source-map-js");

    check(`sharp ${sharp} — не нижче 0.35.5 (CVE-2026-96889)`,
        Boolean(sharp) && не_нижче(sharp, "0.35.5"), sharp);

    check(`source-map-js ${smjs} — не нижче 1.2.2 (GHSA-68fv-2mgg-jv7q)`,
        Boolean(smjs) && не_нижче(smjs, "1.2.2"), smjs);

    // package.json і lock не мають розходитись: інакше npm ci в CI
    // поставить не те, що бачив розробник.
    const пакет = JSON.parse(read("package.json"));

    const розбіжні = Object.entries(пакет.devDependencies || {}).filter(([назва, діапазон]) => {

        const v = версія("node_modules/" + назва);

        if (!v) return true;

        const мінімум = String(діапазон).replace(/^[\^~>=]+/, "");

        return !не_нижче(v, мінімум);

    });

    check("жодна залежність у lock не нижча за діапазон у package.json",
        розбіжні.length === 0, розбіжні.map(([n]) => n).join(", "));
}


console.log(failures === 0
    ? "\n✅ Ворота проти вразливостей: рішення правильні, у CI стоять, залежності чисті\n"
    : `\n❌ Проблем: ${failures}\n`);

process.exit(failures === 0 ? 0 : 1);
