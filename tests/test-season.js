// Сезонне оформлення: один перемикач в адмінці міняє вигляд сайту.
//
// ЯК ЦЕ ВЛАШТОВАНО
// -----------------
// data/season.json → scripts/apply-season.js ставить
// <html data-season="…"> кожній сторінці → у style.css оживає блок
// :root[data-season="…"], який перевизначає кілька змінних кольору.
// «Звичайне» оформлення — це відсутність блока: базові значення на
// :root і є той вигляд, що на сайті зараз.
//
// ЧОМУ ЦЕ ВЗАГАЛІ ПРАЦЮЄ ТАК ДЕШЕВО
// ----------------------------------
// Стилі наскрізь на змінних: --secondary ужито 141 раз, --gray500 —
// 136, --gray900 — 109. Десяток перевизначень доходить до всього
// сайту сам, без другої копії верстки й без жодного запиту.
//
// ЩО ТУТ НАЙВАЖЛИВІШЕ
// --------------------
// 1. КОНТРАСТ. Сезон міняє кольори тексту й тла — тобто може мовчки
//    зробити сайт нечитабельним. Тому набір не звіряє палітру з
//    переліком «правильних» значень, а БЕРЕ значення з самого CSS і
//    рахує співвідношення яскравостей за формулою WCAG. Новий сезон
//    автоматично потрапляє під ту саму перевірку.
// 2. ТРИ МІСЦЯ МУСЯТЬ ЗБІГАТИСЬ: перелік сезонів у скрипті, варіанти
//    в адмінці і блоки в CSS. Розійдуться — власник обере сезон,
//    якого збірка не знає, і сайт лишиться звичайним без жодної
//    скарги.
// 3. АТРИБУТ НА КОЖНІЙ СТОРІНЦІ. Сторінок 254, і вони народжуються з
//    шаблонів — забути частину тут уже виходило тричі (штампи версій).
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

let failures = 0;
const check = (n, c, e) => {
    if (c) console.log("  ✓", n);
    else { console.log("  ✗", n, e !== undefined ? "→ " + e : ""); failures++; }
};

const read = rel => fs.readFileSync(path.join(ROOT, rel), "utf8");

const css = read("assets/css/style.css").replace(/\r\n/g, "\n");

const { readSeason, stamp, SEASONS } = require("../scripts/apply-season.js");


console.log("\n[1] Перемикач є в адмінці і веде у відомий файл");
{
    const { loadYaml } = require("./helpers/yaml");

    const config = loadYaml(".github/../admin/config.yml");

    const pages = (config.collections || []).find(c => c.name === "pages");

    const запис = ((pages || {}).files || []).find(f => f.name === "season");

    check("перемикач у налаштуваннях сайту", Boolean(запис));

    check("пише у data/season.json", запис && запис.file === "data/season.json",
        запис && запис.file);

    const поле = запис && (запис.fields || [])[0];

    check("це список, а не вільний текст", поле && поле.widget === "select", поле && поле.widget);

    check("за замовчуванням — звичайне оформлення",
        поле && поле.default === "standard", поле && поле.default);

    const варіанти = ((поле || {}).options || []).map(o => o.value);

    // ТРИ МІСЦЯ, ЯКІ МУСЯТЬ ЗБІГАТИСЬ. Адмінка пропонує варіанти,
    // скрипт їх приймає, CSS їх малює. Варіант, якого немає у
    // скрипті, тихо перетвориться на «звичайне» — власник обере
    // «Зима», збережеться, дочекається збірки й не побачить нічого.
    check(`варіанти в адмінці: ${варіанти.join(", ")}`,
        варіанти.length === SEASONS.length
        && SEASONS.every(s => варіанти.includes(s)),
        `адмінка: ${варіанти.join(", ")} | скрипт: ${SEASONS.join(", ")}`);

    // І ТРЕТЄ МІСЦЕ: самі блоки в CSS.
    //
    // Доти перевірка звіряла лише адмінку зі скриптом — тобто
    // «обіцяємо те, що приймаємо». Але намалювати сезон має CSS, і
    // блок там можна забути: власник обере «Осінь», збірка чесно
    // проставить data-season="autumn", а сайт лишиться звичайним.
    // Ні помилки, ні сліду — просто нічого не змінилось.
    const уCss = [...css.matchAll(/:root\[data-season="([a-z-]+)"\]/g)]
        .map(m => m[1])
        .filter((v, i, a) => a.indexOf(v) === i);

    const очікувані = SEASONS.filter(s => s !== "standard");

    check(`блоків у стилях: ${уCss.join(", ")}`,
        уCss.length === очікувані.length && очікувані.every(s => уCss.includes(s)),
        `CSS: ${уCss.join(", ")} | скрипт: ${очікувані.join(", ")}`);

    check("файл даних існує", fs.existsSync(path.join(ROOT, "data", "season.json")));

    const дані = JSON.parse(read("data/season.json"));

    check(`у файлі відомий сезон: ${дані.season}`, SEASONS.includes(дані.season), дані.season);
}


