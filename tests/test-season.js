console.log("\n[9] В адмінці є де подивитись, не вмикаючи");
{
    // Перемикач без перегляду означає «увімкни на живому сайті й
    // подивись». Для оформлення це найгірший спосіб: побачать усі, а
    // відкотити можна лише наступною збіркою.
    check("сторінка перегляду існує", fs.existsSync(path.join(ROOT, "admin", "seasons.html")));

    const page = read("admin/seasons.html");

    check("закрита від індексації", /name="robots" content="noindex, nofollow"/.test(page));

    check("є в меню адмінки", /href: "seasons\.html"/.test(read("admin/index.html")));

    // ПОКАЗУЄ СПРАВЖНІЙ САЙТ, А НЕ МАКЕТ.
    //
    // Макет — це друга копія верстки, і вона розходиться з сайтом на
    // першій правці; тоді перегляд показує не те, що побачить
    // покупець, і довіряти йому не можна взагалі.
    check("у рамці відкрито сам сайт", /<iframe[^>]+id="frame"/.test(page));

    check("сезон ставиться тим самим атрибутом, що й у збірці",
        /documentElement\.setAttribute\("data-season", сезон\)/.test(page));

    // ЧЕТВЕРТОЇ КОПІЇ ПЕРЕЛІКУ НЕ БУВАЄ.
    //
    // Перелік уже в трьох місцях (CSS, скрипт, адмінка). Якби сторінка
    // перегляду мала свій, вона розійшлася б першою — додали сезон, а
    // подивитись на нього саме тут і не вийде.
    check("перелік сезонів читається зі стилів",
        /function сезониЗCss/.test(page)
        // Без лапки на кінці: збірка дописує сюди ?v=…, і вираз із
        // закритою лапкою бачив би лише адресу без версії — рівно та
        // пастка, через яку вже падали перевірки посилань.
        && /fetch\("\/assets\/css\/style\.css/.test(page));

    const жорсткий = /var СЕЗОНИ = \[\s*\{\s*ключ:/.test(page);

    check("і не зашитий у сторінку", !жорсткий);

    // Палітра й контраст читаються з документа в рамці — тобто з тих
    // значень, які браузер справді застосував. Переписані сюди кольори
    // були б іще однією копією палітри.
    check("палітра зчитується з рамки, а не переписана",
        /getComputedStyle\(doc\.documentElement\)\.getPropertyValue/.test(page));

    check("контраст рахується на місці", /function контраст/.test(page));

    // Дивитись треба не лише головну й не лише на десктопі.
    check("можна обрати сторінку", /var СТОРІНКИ = \[/.test(page)
        && /catalog/.test(page));

    check("і ширину екрана", /var ЕКРАНИ = \[/.test(page) && /420px/.test(page));

    // Сторінка нічого не зберігає — інакше «подивитись» перетворилось
    // би на «увімкнути».
    check("нічого не записує", !/fetch\([^)]*method:\s*"(POST|PUT)"/.test(page)
        && !/localStorage\.setItem/.test(page));
}


console.log(failures === 0
    ? "\n✅ Сезонне оформлення: перемикається з адмінки, читабельне, знаки на місці\n"
    : `\n❌ Проблем: ${failures}\n`);

process.exit(failures === 0 ? 0 : 1);
