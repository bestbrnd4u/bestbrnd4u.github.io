console.log("\n[5] «Звичайне» — це справді нинішній вигляд");
{
    // Блока :root[data-season="standard"] бути НЕ ПОВИННО: базові
    // значення на :root і є звичайне оформлення. Якби він зʼявився,
    // «повернути як було» означало б «повернути як хтось вирішив»,
    // і сьогоднішній вигляд сайту став би неповоротним.
    check("для звичайного оформлення окремого блока немає",
        !/:root\[data-season="standard"\]/.test(css));

    // Сезонні блоки чіпають ЗМІННІ, а не селектори вмісту. Інакше
    // сезон почав би переставляти верстку, і повернення стало б
    // непередбачуваним.
    const блоки = [...css.matchAll(/:root\[data-season="([^"]+)"\]([^{]*)\{([^}]*)\}/g)];

    check(`сезонних блоків знайдено: ${блоки.length}`, блоки.length > 0);

    const зВмістом = блоки.filter(([, , хвіст, тіло]) =>
        !хвіст.trim() && /^[\s\S]*$/.test(тіло) && /[a-z-]+\s*:/.test(тіло)
        && тіло.split(";").some(d => d.trim() && !d.trim().startsWith("--") && !d.trim().startsWith("/*")));

    check("блоки на :root задають лише змінні",
        зВмістом.length === 0,
        зВмістом.map(b => b[1]).join(", "));
}


console.log("\n[6] Контраст: кожен сезон лишається читабельним");
{
    // ГОЛОВНА ПЕРЕВІРКА НАБОРУ.
    //
    // Значення беруться з САМОГО CSS, а не з копії в тесті: копія
    // розійшлася б із файлом, і перевірка міряла б палітру, якої на
    // сайті немає. Новий сезон потрапляє сюди автоматично.
    const токени = блок => {

        const out = {};

        for (const m of блок.matchAll(/--([a-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g)) {
            out[m[1]] = m[2];
        }

        return out;

    };

    const база = токени((css.match(/^:root\{([\s\S]*?)^\}/m) || ["", ""])[1]);

    check(`базових кольорів знайдено: ${Object.keys(база).length}`,
        Object.keys(база).length >= 10, Object.keys(база).join(", "));

    const палітри = { standard: база };

    for (const m of css.matchAll(/:root\[data-season="([^"]+)"\]\s*\{([\s\S]*?)\}/g)) {
        палітри[m[1]] = { ...база, ...токени(m[2]) };
    }

    check("палітра знайдена для кожного сезону",
        SEASONS.every(s => палітри[s]), Object.keys(палітри).join(", "));

    const hex = h => {
        const s = h.replace("#", "");
        const повний = s.length === 3 ? [...s].map(c => c + c).join("") : s;
        return [0, 2, 4].map(i => parseInt(повний.slice(i, i + 2), 16));
    };

    const яскравість = h => {
        const [r, g, b] = hex(h).map(v => {
            const c = v / 255;
            return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
        });
        return 0.2126 * r + 0.7152 * g + 0.0722 * b;
    };

    const контраст = (a, b) => {
        const [l1, l2] = [яскравість(a), яскравість(b)].sort((x, y) => y - x);
        return (l1 + 0.05) / (l2 + 0.05);
    };

    // Пари, які справді зустрічаються на сайті: основний і
    // другорядний текст на трьох тлах, посилання, білий на кнопці.
    const ПАРИ = [
        ["основний текст на сторінці", "gray900", "gray50"],
        ["основний текст на картці", "gray900", "white"],
        ["другорядний текст на сторінці", "gray500", "gray50"],
        ["другорядний текст на картці", "gray500", "white"],
        ["другорядний на сірій плашці", "gray500", "gray100"],
        ["посилання на сторінці", "secondary", "gray50"],
        ["посилання на картці", "secondary", "white"],
        ["білий на синій кнопці", "white", "secondary"],
        ["білий на темній кнопці", "white", "primary"]
    ];

    const НОРМА = 4.5;

    for (const сезон of SEASONS) {

        const п = палітри[сезон];

        if (!п) continue;

        const погані = ПАРИ
            .filter(([, т, ф]) => п[т] && п[ф])
            .map(([назва, т, ф]) => ({ назва, r: контраст(п[т], п[ф]) }))
            .filter(x => x.r < НОРМА);

        // «Звичайне» оформлення перевіряємо тим самим мірилом, але
        // його провали — не наша сьогоднішня справа: це нинішній
        // вигляд сайту, і міняти фірмові кольори заднім числом тут
        // ніхто не просив. Важливо, щоб СЕЗОН не зробив гірше.
        if (сезон === "standard") {
            console.log(`  ⓘ звичайне: пар нижче ${НОРМА} — ${погані.length}`
                + (погані.length ? ` (${погані.map(x => `${x.назва} ${x.r.toFixed(2)}`).join("; ")})` : ""));
            continue;
        }

        check(`${сезон}: усі пари тексту проходять ${НОРМА}`,
            погані.length === 0,
            погані.map(x => `${x.назва} ${x.r.toFixed(2)}`).join("; "));

        // І ОКРЕМО: СЕЗОН НЕ МАЄ ПРАВА ПОГІРШИТИ ТЕ, ЩО БУЛО.
        //
        // Пара може проходити норму й водночас стати помітно гіршою —
        // так палітра тихо повзе вниз від сезону до сезону.
        const гірші = ПАРИ
            .filter(([, т, ф]) => п[т] && п[ф] && база[т] && база[ф])
            .map(([назва, т, ф]) => ({
                назва,
                було: контраст(база[т], база[ф]),
                стало: контраст(п[т], п[ф])
            }))
            // Поріг у 20%: заголовки при 17:1 можуть просісти до 15:1
            // без жодного наслідку, а от 4,6 → 3,7 — це вже біда.
            .filter(x => x.стало < x.було * 0.8);

        check(`${сезон}: жодна пара не просіла помітно`,
            гірші.length === 0,
            гірші.map(x => `${x.назва}: ${x.було.toFixed(2)} → ${x.стало.toFixed(2)}`).join("; "));

        // СМУГА СЕКЦІЇ МУСИТЬ ЛИШАТИСЬ РОДИЧЕМ ТЛА.
        //
        // Сторінка чергує «біла секція / тиха смуга», і це чергування
        // задає ритм довгої головної. Смуга мусить бути ТРОХИ
        // світлішою за тло — тоді вона читається як підняте поле.
        //
        // ЩО БУЛО НЕ ТАК. Зиму залили на dev, і там тло стало
        // холодним (#e8eff8), а смуги лишились майже білими: колір
        // був зашитий у сімох місцях трьома різними відтінками й сезон
        // до них не доходив. Ритм перевернувся — смуги стали світлішими
        // за білі секції поруч. Контраст тексту при цьому лишався в
        // нормі, тож жодна перевірка не скаржилась.
        //
        // Відстань 20 — рівно той зламаний випадок. Чинні сезони
        // тримаються в 8-13, тож межа 16 розділяє їх упевнено.
        const відстань = (a, b) => {
            const x = hex(a), y = hex(b);
            return Math.round(Math.sqrt(x.reduce((s, v, i) => s + (v - y[i]) ** 2, 0)));
        };

        if (п.gray50 && п["surface-muted"]) {

            const між = відстань(п.gray50, п["surface-muted"]);

            check(`${сезон}: смуга секції тримається тла (${між})`, між <= 16,
                `${п.gray50} проти ${п["surface-muted"]} — відстань ${між}`);

            check(`${сезон}: і лежить між тлом і білим`,
                відстань(п["surface-muted"], "#ffffff") < відстань(п.gray50, "#ffffff"),
                `смуга до білого ${відстань(п["surface-muted"], "#ffffff")}, `
                + `тло до білого ${відстань(п.gray50, "#ffffff")}`);

        }

    }
}


