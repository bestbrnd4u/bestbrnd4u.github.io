// Читання й запис файлу з повтором, коли Windows тримає його зайнятим.
//
// СИМПТОМ
// --------
// Збірка падає посеред дороги на випадковому файлі:
//
//   Error: EBUSY: resource busy or locked, open '…\index.html'
//       at Object.readFileSync (node:fs:441:20)
//       at …\scripts\apply-cache-version.js:157:23
//
// Наступний запуск тієї самої збірки — без єдиної зміни в коді —
// проходить. Заміряно 24.09.2026: один і той самий `npm run build`
// упав на index.html, а за хвилину пройшов повністю.
//
// ПРИЧИНА
// --------
// Це не наша помилка й не пошкоджений файл. На Windows файл можна
// відкрити монопольно (share = None), і поки хтось його так тримає,
// будь-яке інше відкриття падає — навіть на читання. Так поводяться
// антивірус, індексатор пошуку, відкритий редактор, а часом і
// попередній процес, який ще не встиг закритись.
//
// Відтворюється навмисне:
//
//   $s = [System.IO.File]::Open($p, 'Open', 'ReadWrite', 'None')
//   node scripts/apply-cache-version.js   → EBUSY, код виходу 1
//
// Коди бувають різні: EBUSY, EPERM, EACCES, а інколи й UNKNOWN —
// останній видає саме антивірус. Лікування в усіх одне: зачекати
// мить і спробувати ще раз.
//
// ЧОМУ ЦЕ ВАЖИТЬ БІЛЬШЕ ЗА ОДНУ ВПАЛУ ЗБІРКУ
// -------------------------------------------
// Збірники пишуть сотні файлів ПО ЧЕРЗІ. Виняток посеред дороги
// лишає дерево напівзібраним: частина сторінок зі свіжим штампом
// версії, частина зі старим. Тест цього не ловить — він бачить уже
// впалий процес, — а в коміт таке піде мовчки.
//
// Саме так 24.09 у гілці опинилось 227 проштампованих сторінок
// замість 228, і помітив я це випадково, за числом у виводі.
//
// МЕЖІ
// -----
// Повторюємо лише те, що схоже на тимчасовий замок. Немає файлу
// (ENOENT), немає місця (ENOSPC), не той шлях — падаємо одразу, бо
// повтор тут нічого не змінить, лише сховає справжню причину.
//
// Після останньої спроби теж падаємо, і це навмисно: пропустити
// файл — те саме напівзібране дерево, тільки тихіше.
const fs = require("fs");

// Коди, за якими варто зачекати. Решта — справжні помилки.
const TRANSIENT = new Set(["EBUSY", "EPERM", "EACCES", "UNKNOWN"]);

// Разом трохи менше секунди. Замок від антивіруса живе мілісекунди,
// від індексатора — десяті частки; чекати довше означає ховати вже
// не випадковість, а щось, що тримає файл постійно.
const DELAYS = [30, 60, 120, 250, 500];

// Пауза мусить бути синхронною: усі збірники читають і пишуть
// синхронно, і переводити їх на async заради цього — переписати
// половину репозиторію. Atomics.wait на буфері, якого більше ніхто
// не бачить, — єдиний спосіб зачекати синхронно, не крутячи процесор.
function pause(ms) {
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

function withRetry(action, file, what) {

    for (let attempt = 0; ; attempt += 1) {

        try {

            const result = action();

            // Про вдалий повтор кажемо вголос. Мовчазний повтор
            // приховав би, якби замки стали щоденними, — а це вже
            // не випадковість, а привід прибрати того, хто тримає.
            if (attempt > 0) {
                console.warn(`::notice::${what} ${file} вдалося з ${attempt + 1}-ї спроби `
                    + "(файл був зайнятий)");
            }

            return result;

        } catch (error) {

            if (!TRANSIENT.has(error.code) || attempt >= DELAYS.length) throw error;

            pause(DELAYS[attempt]);

        }

    }

}

const readFileSync = (file, options) =>
    withRetry(() => fs.readFileSync(file, options), file, "читання");

const writeFileSync = (file, data, options) =>
    withRetry(() => fs.writeFileSync(file, data, options), file, "запис");

module.exports = { readFileSync, writeFileSync, TRANSIENT, DELAYS };
