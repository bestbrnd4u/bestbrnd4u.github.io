// Кому магазин більше не пише.
//
// НАВІЩО ОКРЕМИЙ ФАЙЛ НА ТРИ РЯДКИ
// ---------------------------------
// Листи покупцям надсилають три різні кроки — нагадування про кошик,
// подяка за покупку й прохання про відгук, — і кожен ходить у базу
// своїм способом. Блокування, розписане в кожному окремо, рано чи
// пізно розійшлося б: додали четвертий лист, забули четверту
// перевірку — і заблокований знову отримує пошту.
//
// ЧОМУ ЦЬОГО НЕ РОБИТЬ ТРИГЕР
// ----------------------------
// Тригер (міграція 035) не дає заблокованому ЗАЛИШИТИ новий слід:
// ні замовлення, ні незавершеного оформлення. Але сліди, залишені
// ДО блокування, нікуди не діваються — і саме за ними ці три кроки й
// пишуть листи. Тобто без цієї перевірки блокований далі отримував
// би пошту за старими замовленнями.
//
// ЩО ПОВЕРТАЄ
// ------------
// Множину адрес у нижньому регістрі. Порожню — якщо таблиці ще
// немає: це означає «міграцію 035 не застосували», а не «блокувати
// нікого». Мовчазна порожня множина тут правильна, бо альтернатива —
// зупинити всю розсилку через те, чого власник ще не ввімкнув.

async function blockedEmails(url, key) {

    if (!url || !key) return new Set();

    try {

        const response = await fetch(`${url}/rest/v1/blocked_emails?select=email&limit=5000`, {
            headers: {
                apikey: key,
                Authorization: `Bearer ${key}`,
            },
        });

        if (!response.ok) {

            console.warn("Список заблокованих недоступний — чи застосована міграція 035?");

            return new Set();

        }

        const rows = await response.json();

        return new Set((Array.isArray(rows) ? rows : [])
            .map(row => String(row?.email ?? "").trim().toLowerCase())
            .filter(Boolean));

    } catch (error) {

        console.warn("Список заблокованих недоступний:", error.message);

        return new Set();

    }

}

// Чи писати цій адресі.
function allowedToWrite(blocked, email) {

    return !blocked.has(String(email ?? "").trim().toLowerCase());

}

module.exports = { blockedEmails, allowedToWrite };
