// Картинка, яку показують месенджери й соцмережі під посиланням.
//
// ЩО БУЛО НЕ ТАК
// ---------------
// В og:image стояв банер головної — hero-bags.jpg, 2400×1080. У
// Telegram посилання на магазин виглядало так: назва, опис і крихітний
// квадратик праворуч, у який потрапив випадковий світлий шматок того
// банера. Тобто на місці, де мав би бути магазин, — сіро-блакитна
// пляма.
//
// Причина не в якості фото. Прев'ю обрізають картинку під СВІЙ формат:
// Telegram бере квадрат, Facebook — 1.91:1, Viber — свій. Широкий
// банер із композицією по центру після квадратного обрізання
// перетворюється на фрагмент.
//
// ЩО ТЕПЕР
// ---------
// Окрема картинка, зроблена саме для прев'ю: логотип магазину на
// суцільному тлі, точно по центру. Її можна різати як завгодно — і
// квадратом, і смугою — логотип лишається на місці й лишається
// впізнаваним. Це та сама «B», що у вкладці браузера й на іконці
// застосунку, тож посилання, вкладка й ярлик виглядають як одне.
//
// РОЗМІР 1200×630 — той, який просять Facebook і Twitter (1.91:1) і
// який приймають усі решта. Дрібніше за 600×315 месенджери показують
// маленьким значком, а не картинкою.
//
// ЗАПУСК: npm run og-cover
//
// Робити це щозбірки не треба: вихідна іконка не змінюється. Файл
// лежить у репозиторії поруч із рештою банерів, а скрипт потрібен
// тоді, коли зміниться сам логотип.
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.join(__dirname, "..");

const SOURCE = path.join(ROOT, "assets/images/favicon-512.png");
const TARGET = path.join(ROOT, "assets/images/og-cover.png");

const WIDTH = 1200;
const HEIGHT = 630;

// Тло темніше за саму іконку (у неї #131c30), щоб її заокруглений
// край було видно як окрему плитку, а не як край картинки.
const BACKGROUND = { r: 14, g: 22, b: 38, alpha: 1 };

// Логотип трохи менший за висоту полотна: поля з усіх боків потрібні,
// бо кожен месенджер обрізає по-своєму, і впритул поставлений край
// першим і зникне.
const LOGO = 440;

async function build() {

    const logo = await sharp(SOURCE)
        .resize(LOGO, LOGO, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .toBuffer();

    await sharp({
        create: {
            width: WIDTH,
            height: HEIGHT,
            channels: 4,
            background: BACKGROUND,
        },
    })
        .composite([{ input: logo, gravity: "centre" }])
        // Кольорів тут лічені одиниці (тло, золото, тінь), тож палітра
        // дає файл у кілька разів менший без жодної видимої різниці.
        .png({ compressionLevel: 9, palette: true })
        .toFile(TARGET);

    const size = fs.statSync(TARGET).size;

    console.log(`Готово: ${WIDTH}×${HEIGHT}, ${(size / 1024).toFixed(0)} КБ → assets/images/og-cover.png`);

}

build().catch(error => {

    console.error("Не вдалося зібрати картинку прев'ю:", error.message);

    process.exit(1);

});
