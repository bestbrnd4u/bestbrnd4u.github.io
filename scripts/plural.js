// Відмінювання після числа для сторінок, які збираються заздалегідь.
//
// ЩО БУЛО НЕ ТАК
// ---------------
// Сторінки-хаби підписували себе так:
//
//     const intro = `${pages.length} ${meta.word} у каталозі BestBrnd4u.`;
//
// де meta.word — зашите слово в родовому відмінку множини. Число
// мінялось, слово ні. На 24.09.2026 з трьох хабів два читались
// неправильно:
//
//     21 брендів у каталозі     → мало бути «21 бренд»
//     3 розділів у каталозі     → мало бути «3 розділи»
//     6 категорій у каталозі    → випадково збіглось
//
// І це не дрібниця в журналі збірки: той самий рядок іде і в видимий
// текст сторінки, і в опис для Google. Тобто помилку бачив кожен, хто
// відкривав /brands/ або знаходив її в пошуку.
//
// ЧОМУ ПРАВИЛО ТУТ, А НЕ ВЗЯТЕ З COMMON.JS
// -----------------------------------------
// Оригінал живе в assets/js/common.js — це браузерний файл, який
// підключається тегом <script> і нічого не експортує. Node його не
// підтягне, а переписувати common.js у модуль означало б зачепити
// кожну сторінку сайту заради трьох рядків.
//
// Тому копія — і це та сама домовленість, що вже діє для строків
// акцій: dealActive() у scripts/promo-deals.js повторює promoTiming()
// з common.js, а розійтись їм не дає тест, який проганяє ОБИДВІ на тих
// самих числах. Тут так само — tests/test-plural.js.
//
// НАЙКРИХКІШЕ — СОТНІ
// --------------------
// Українське правило дивиться на дві останні цифри, і 11-14 — виняток
// із правила про останню. Перевірити mod 10 раніше за mod 100 означає
// отримати «11 товар». Порядок нижче саме тому такий.
function plural(count, one, few, many) {

    const n = Math.abs(Number(count)) || 0;

    const mod10 = n % 10;
    const mod100 = n % 100;

    if (mod100 >= 11 && mod100 <= 14) return many;
    if (mod10 === 1) return one;
    if (mod10 >= 2 && mod10 <= 4) return few;

    return many;

}

// Число разом зі словом: plural() віддає лише слово, а на сторінці
// майже завжди потрібне «21 бренд» цілком.
function withCount(count, one, few, many) {

    return `${count} ${plural(count, one, few, many)}`;

}

module.exports = { plural, withCount };
