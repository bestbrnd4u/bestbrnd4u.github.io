//
// НАВІЩО ЦЕ ОКРЕМИЙ СКРИПТ
// -------------------------
// У згенерованих файлах є значення, які рахуються ВІД ДНЯ ЗБІРКИ, а
// тому псуються самі собою — без жодної правки в даних:
//
//   1. <g:availability_date> у feed.xml — «очікуємо такого-то».
//      Рахується як день збірки плюс строк під замовлення. Google
//      ВИМАГАЄ цю дату для backorder і позначає позицію
//      попередженням, щойно дата опиняється в минулому.
//
//   2. © РІК у підвалі кожної сторінки (scripts/build-legal.js:394).
//      Береться з поточного року на момент збірки.
//
// Коментар у build-feed.js каже про дату: «з кожною перезбіркою вона
// зсувається вперед — це і є "очікуємо через два тижні", а не
// фіксований день у минулому». Намір правильний, але його ніщо не
// тримало: на main НЕМАЄ регулярної перезбірки. build-products.yml
// запускається на push у main і з apply-stock.yml — тобто лише коли
// власник щось правив або прийшло замовлення.
//
// ЗАМІРЯНО 02.11.2026. Останню збірку main зроблено 20.10. У фіді на
// проді всі 39 позицій backorder обіцяли 09.11 — сім днів до того,
// як обіцянка стала б датою в минулому. Тринадцять днів тиші в
// магазині вже минуло, лишалось сім.
//
// ЧОМУ НЕ ПРОСТО «ПЕРЕЗБИРАТИ ЩОДНЯ»
// -----------------------------------
// Дата дорівнює дню збірки плюс строк, тож вона зсувається ЩОДНЯ.
// Безумовна щоденна перезбірка давала б щоденний коміт, щоденну
// виливку і щоденне скидання кешу Cloudflare — і все це заради
// файлу, який насправді ще днів десять правдивий.
//
// Тому вартовий питає спершу тут, а перезбирає лише коли пора:
// виходить приблизно раз на два тижні замість щодня.
//
// ЧОМУ ТУТ НЕМАЄ ЛОГІКИ ЗБІРКИ
// -----------------------------
// Навмисно. Перезбірку вже вміє робити build-products.yml: він
// рахує все з даних, комітить ЛИШЕ те, що змінилось, і сам
// викликає виливку та IndexNow. Вартовий лише натискає ту саму
// кнопку, яку натискає замовлення.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

// ЗА СКІЛЬКИ ДНІВ ДО КІНЦЯ ПОЧИНАЄМО ХВИЛЮВАТИСЬ.
//
// Найкоротший строк під замовлення в даних — «5–10 робочих днів»,
// тобто 14 календарних (10 × 7 / 5). Другий строк, «10-14 робочих
// днів», дає 20. Поріг має бути помітно меншим за 14, інакше
// вартовий викликатиме перезбірку мало не щодня.
//
// П'ять днів означають дві речі одночасно: дата у фіді ніколи не
// ближча за п'ять днів, і п'ять підряд пропущених запусків за
// розкладом нас не зламають (а запускаємось ми щодоби).
const ПОРІГ_ДНІВ = 5;

const ДОБА = 24 * 60 * 60 * 1000;

// Дати очікування з готового feed.xml — саме з ФАЙЛУ, а не з
// перезбірки в пам'яті.
//
// Це головне, чим перевірка відрізняється від tests/test-feed.js
// [9]. Там дата теж перевіряється на «в майбутньому», але береться
// з feed.feedItems(), яку тест викликає сам — тобто завжди свіжа,
// хоч би який старий файл лежав у репозиторії. Той тест стереже
// генератор; цей скрипт стереже те, що вже опубліковано.
function датиОчікування(xml) {

    return [...String(xml || "")
        .matchAll(/<g:availability_date>([^<]+)<\/g:availability_date>/g)]
        .map(m => Date.parse(m[1]))
        .filter(time => Number.isFinite(time));

}

// Рік зі знаку охорони прав. Формат заданий у build-legal.js:
// syncCopyrightYear() пише «© 2026 bestbrnd4u.» і те саме в
// <meta name="copyright">.
function рікУЗнакуПрав(html) {

    const m = String(html || "").match(/©\s*(\d{4})\s+bestbrnd4u\./);

    return m ? Number(m[1]) : null;

}

// Чиста функція — щоб тест міг підсунути їй будь-який день і будь-який
// фід, не чекаючи, поки справжні дати протухнуть.
function чиПора({ xml, html, тепер }) {

    const now = тепер instanceof Date ? тепер : new Date(тепер || Date.now());

    const причини = [];

    const дати = датиОчікування(xml);

    if (дати.length) {

        const найближча = Math.min(...дати);

        // Округлення вниз спрацьовує на нашу користь: воно робить
        // число меншим, тобто вартовий прокидається радше на день
        // раніше, ніж на день пізніше.
        const днів = Math.floor((найближча - now.getTime()) / ДОБА);

        if (днів < ПОРІГ_ДНІВ) {
            причини.push("найближча дата очікування у фіді — "
                + new Date(найближча).toISOString().slice(0, 10)
                + ", це через " + днів + " дн. (поріг " + ПОРІГ_ДНІВ + ")");
        }

    }

    const рік = рікУЗнакуПрав(html);

    if (рік !== null && рік !== now.getUTCFullYear()) {
        причини.push("у знаку охорони прав " + рік
            + ", а рік уже " + now.getUTCFullYear());
    }

    return { пора: причини.length > 0, причини, дат: дати.length, рік };

}

function читай(rel) {

    try {
        return fs.readFileSync(path.join(ROOT, rel), "utf8");
    } catch (error) {
        return null;
    }

}

function main() {

    const xml = читай("feed.xml");
    const html = читай("index.html");

    // Якщо файлів немає — мовчки не перезбираємо.
    //
    // Нема feed.xml — це або зовсім зламане дерево, або гілка, де
    // фіда й не буває. В обох випадках сипати перезбірками гірше,
    // ніж не робити нічого: вартовий має лікувати дати, а не
    // ставати ще одним джерелом запусків.
    if (xml === null) {
        console.warn("::warning::feed.xml не знайдено — перезбірку не викликаємо");
    }

    const { пора, причини, дат, рік } = чиПора({ xml, html, тепер: new Date() });

    console.log("Дат очікування у фіді: " + дат
        + (рік === null ? "" : ", рік у знаку прав: " + рік));

    if (пора) причини.forEach(r => console.log("  → " + r));
    else console.log("  усе свіже — перезбірка не потрібна");

    if (process.env.GITHUB_OUTPUT) {
        fs.appendFileSync(process.env.GITHUB_OUTPUT,
            "due=" + (пора ? "true" : "false") + "\n");
    }

    // Вихід нулем у будь-якому разі: «пора перезбирати» — це не
    // помилка, і червоний запуск за розкладом лише навчив би
    // не дивитись на пошту.
}

module.exports = { чиПора, датиОчікування, рікУЗнакуПрав, ПОРІГ_ДНІВ };

if (require.main === module) main();
