// «Перейти до вмісту» — першим на кожній сторінці.
//
// ЩО БУЛО НЕ ТАК
// ---------------
// Людина з клавіатурою чи читачем екрана мусила пройти всю шапку,
// перш ніж потрапити на сторінку. А шапка тут велика: мегаменю
// розкривається від фокусу, і Tab іде по кожному його пункту.
//
// ЗАМІРЯНО 04.11.2026 на проді, головна, 1280px, людський темп
// (400мс на натискання): до першого посилання вмісту — 34 натискання
// Tab, із них 33 у шапці (Кросівки, Гаманці, Годинники, Окуляри…).
// І так на КОЖНІЙ сторінці.
//
// Посилання пропуску — це вимога WCAG 2.4.1 (Bypass Blocks) рівня A,
// тобто найнижчого. Його не було ніде, а <main>, яким користуються
// читачі екрана, є лише на 22 сторінках із 173.
//
// ЩО РОБИТЬ ЦЕЙ КРОК
// -------------------
// На кожній сторінці з шапкою ставить дві речі:
//
//   одразу після <body …>   посилання, яке видно лише у фокусі
//   одразу після </header>  порожню ціль id="content"
//
// Ціль — окремий порожній елемент, а не id на першому блоці
// сторінки: перші блоки скрізь різні, частина вже має свої id, і
// дописувати атрибути в чужу розмітку регуляркою — найпевніший
// спосіб колись її зламати.
//
// Сторінки без шапки — переадресації зі старих кириличних адрес
// товарів (73 штуки, по 695 байт) — пропускаються: там нема чого
// пропускати.
//
// ІДЕМПОТЕНТНІСТЬ — НЕ ПРИКРАСА
// -----------------------------
// product.html і catalog.html — водночас сторінки й шаблони для 136
// згенерованих. Усе, що крок впише в шаблон, генератор скопіює далі,
// а наступна збірка прожене крок і по копії. Тому крок спершу
// ПРИБИРАЄ свої вставки, а потім ставить їх заново на свої місця:
// будь-яка кількість прогонів дає той самий файл.
//
// ЗАПУСК
//   node scripts/build-skip-link.js           розставити
//   node scripts/build-skip-link.js --check   лише перевірити, не писати
//
// Фокус на ціль переносить загальний обробник якорів у common.js —
// без нього посилання лише прокрутило б сторінку, а наступний Tab
// знову пішов би на лого.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CHECK = process.argv.includes("--check");

const ПОСИЛАННЯ = '<a class="skip-link" href="#content">Перейти до вмісту</a>';
const ЦІЛЬ = '<span id="content" class="skip-target" tabindex="-1"></span>';

// Вставляються з власним переносом рядка — і з ним же прибираються,
// інакше кожен прогін лишав би по порожньому рядку.
const ВСТАВКА_ПОСИЛАННЯ = "\n" + ПОСИЛАННЯ;
const ВСТАВКА_ЦІЛІ = "\n" + ЦІЛЬ;

// Ті самі теки, що й у build-footer-sections.js: supabase — шаблони
// листів, admin — Decap зі своєю розміткою, archive — старе.
const ПРОПУСК = ["node_modules", ".git", ".claude", "archive", "admin",
    ".playwright-mcp", "supabase", "_site"];

function сторінки(dir, список) {

    const усі = список || [];

    fs.readdirSync(dir, { withFileTypes: true }).forEach(запис => {

        if (ПРОПУСК.includes(запис.name)) return;

        const повний = path.join(dir, запис.name);

        if (запис.isDirectory()) сторінки(повний, усі);
        else if (запис.name.endsWith(".html")) усі.push(повний);

    });

    return усі;

}

// Чиста функція: розмітка → розмітка. Окремо від файлів, щоб її
// можна було перевіряти без жодного запису на диск.
function розставити(html) {

    if (!/<header[\s>]/.test(html)) return html;

    let текст = html
        .split(ВСТАВКА_ПОСИЛАННЯ).join("")
        .split(ВСТАВКА_ЦІЛІ).join("")
        // на випадок, якщо вставку колись переносили руками без рядка
        .split(ПОСИЛАННЯ).join("")
        .split(ЦІЛЬ).join("");

    текст = текст.replace(/<body\b[^>]*>/, тег => тег + ВСТАВКА_ПОСИЛАННЯ);
    текст = текст.replace("</header>", "</header>" + ВСТАВКА_ЦІЛІ);

    return текст;

}

function main() {

    let змінено = 0;
    let розставлено = 0;
    const неТак = [];

    сторінки(ROOT).forEach(файл => {

        const було = fs.readFileSync(файл, "utf8");
        const стало = розставити(було);

        if (стало.includes(ПОСИЛАННЯ)) розставлено++;

        if (стало === було) return;

        змінено++;

        if (CHECK) неТак.push(path.relative(ROOT, файл));
        else fs.writeFileSync(файл, стало, "utf8");

    });

    if (CHECK) {

        if (неТак.length) {
            console.error(`::error::Посилання пропуску не на місці на ${неТак.length} сторінках:`);
            неТак.slice(0, 10).forEach(ф => console.error("  " + ф));
            process.exit(1);
        }

        console.log(`Готово: посилання пропуску вже на місці на всіх ${розставлено} сторінках з шапкою`);
        return;

    }

    console.log(змінено
        ? `Готово: посилання пропуску розставлено на ${змінено} сторінках (усього з шапкою ${розставлено})`
        : `Готово: посилання пропуску вже на місці на всіх ${розставлено} сторінках з шапкою`);

}

module.exports = { розставити, ПОСИЛАННЯ, ЦІЛЬ, ПРОПУСК };

if (require.main === module) main();
