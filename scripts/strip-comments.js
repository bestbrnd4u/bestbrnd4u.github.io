// Знімає коментарі зі скриптів у ЗІБРАНІЙ теці, перед виливкою.
//
// ЗАПУСК (із scripts/collect-site.js):
//   node scripts/strip-comments.js _site
//
// НАВІЩО
// -------
// У репозиторії коментарів більше, ніж коду, і це навмисно. Але у
// вазі сторінки вони важать непропорційно багато — рівно з тієї ж
// причини, що й у стилях: код однорідний і жметься добре, українська
// проза в UTF-8 — погано.
//
// ЗАМІРЯНО 20.10.2026 на всіх 41 файлі assets/js:
//
//     сирих   1528 → 558 КБ
//     gzip     455 → 161 КБ   (−294 КБ, 65%)
//
// На самому каталозі (20 файлів зі згаданих) це близько 166 КБ на
// кожен перший показ.
//
// ЧОМУ ОКРЕМИЙ СКРИПТ, А НЕ РЯДОК У collect-site.js
// --------------------------------------------------
// terser.minify() асинхронний, а collect() синхронний і таким
// потрібен тестам. Запускати його 41 раз через execFileSync означало б
// 41 процес; цей скрипт — один процес, усередині якого вже можна
// чекати на обіцянки.
//
// ЧОМУ САМЕ terser, А НЕ ВИРАЗ
// -----------------------------
// У стилях коментарі можна зняти виразом: їх синтаксис не має
// винятків (див. collect-site.js). У JS — ні: «//» буває всередині
// адреси, «/*» — у регулярці й у шаблонному літералі. Тут потрібен
// справжній розбирач, тож terser із ВИМКНЕНИМИ compress і mangle:
// він лише перевидає розібране дерево, не перейменовуючи й не
// переставляючи нічого.
//
// Побічно terser екранує «<» як «\x3c» у рядках — це той самий
// символ і захист від «</script» усередині рядка.
//
// ЯКЩО terser НЕ ВСТАНОВЛЕНО
// ---------------------------
// Виходимо з попередженням, а не з помилкою: краще віддати сайт із
// коментарями, ніж не віддати зовсім. У Actions це видно як
// ::warning::, тобто мовчки не мине.
//
// ПОВІДОМЛЕННЯ НАЗИВАЄ ПРИЧИНУ, А НЕ ЛИШЕ СИМПТОМ.
//
// Доти тут стояло «terser не встановлено — скрипти поїдуть із
// коментарями». Правда, але марна: 02.11.2026 через цей рядок
// пройшли ДВІЧІ, не зрозумівши, що сталось. Обидва рази Sync
// branches падав на тестах зі словами «у зібраних скриптах
// коментарів немає ✗» — а справжня причина була за два кроки до
// того й виглядала як нешкідливе жовте попередження.
//
// Причина обидва рази одна: `npm ci` виконали ДО злиття гілок, тобто
// з package.json гілки-ПРИЙМАЧА, де terser ще немає. У виправленій
// версії воркфлоу цього кроку вже немає на тому місці — але
// workflow_dispatch бере файл із тієї гілки, на якій його запустили,
// тож стара копія лишається робочою, доки виправлення не доїде.
const fs = require("fs");
const path = require("path");

let terser = null;

try {
    terser = require("terser");
} catch (error) {
    console.log("::warning::terser не встановлено — скрипти поїдуть із коментарями,"
        + " і перевірка tests/test-published-tree.js через це почервоніє."
        + " Найчастіша причина: npm ci виконано ДО злиття гілок, тобто з package.json"
        + " гілки-приймача. У Sync branches це означає, що запуск узяв стару копію"
        + " воркфлоу — запустіть його з гілки, де виправлення вже є (Use workflow from).");
    process.exit(0);
}

// compress і mangle ВИМКНЕНІ навмисно.
//
// Нам потрібні лише коментарі. Стиснення переписало б код (злиття
// змінних, інші умови), і тоді виливка возила б не те, що лежить у
// репозиторії, — а налагоджувати прод довелось би по чужому тексту.
// Перейменування імен зламало б іще й звіти про помилки: у них
// лишаються назви функцій.
const ОПЦІЇ = {
    compress: false,
    mangle: false,
    sourceMap: false,
    ecma: 2020,
    format: {
        comments: false,
        // Рядки лишаються рядками: так номер у звіті про помилку все
        // ще приблизно вказує на місце, а різниця з повним
        // стисненням — лише 7 КБ на весь сайт (заміряно).
        beautify: true,
        indent_level: 0,
        quote_style: 3
    }
};

async function обробити(файл) {

    const код = fs.readFileSync(файл, "utf8");

    const res = await terser.minify(код, ОПЦІЇ);

    if (res.error) throw new Error(`${файл}: terser не впорався — ${res.error.message}`);

    const out = res.code;

    // ЗАПОБІЖНИК 1: висновок мусить бути робочим кодом.
    try {
        new (require("vm").Script)(out);
    } catch (error) {
        throw new Error(`${файл}: після зняття коментарів не парситься — ${error.message}`);
    }

    // ЗАПОБІЖНИК 2: розумні межі.
    //
    // Спершу тут стояла п'ята частина — і вона завалила збирання на
    // breadcrumbs.js (13040 → 2448, тобто 18,8%). Виявилось, що це
    // правда: заміряно 20.10.2026 на восьми модулях, які виконуються
    // і в Node, — від 18% (product-offer.js) до 32% (stock.js) від
    // вихідного розміру. Ці файли справді на 70-82% із пояснень.
    //
    // Поведінку всіх восьми звірено окремо: висновки функцій на тих
    // самих входах збіглись 8 із 8 (див. [7] у
    // tests/test-published-tree.js — там та сама звірка в наборі).
    //
    // Лишаємо десяту частину: менше — це вже точно не «зняли
    // коментарі».
    const було = Buffer.byteLength(код), стало = Buffer.byteLength(out);

    if (стало < було * 0.1) throw new Error(`${файл}: схуд у десять разів (${було} → ${стало}) — підозріло`);

    // НЕ СТАЛО МЕНШИМ — ЛИШАЄМО ЯК БУЛО.
    //
    // Доти це була ПОМИЛКА, і вона валила збирання всього сайту.
    //
    // ЗАМІРЯНО 03.11.2026 на supabase-js 2.112.3: у ньому нуль
    // коментарів і одинадцять рядків — він повністю мінімізований.
    // terser із beautify розкладає його назад на рядки й доводить із
    // 207 до 236 КБ. Тобто крок падав на файлі, якому нічого не
    // бракує.
    //
    // Правило тепер просте й не потребує переліку винятків: сенс
    // кроку — прибрати пояснення, яких браузеру не треба. Не схуд —
    // прибирати нічого, лишаємо вихідний файл недоторканим.
    //
    // Це НЕ послаблення: гірший за вихідний файл не їде на сайт ні в
    // тому, ні в іншому разі. Просто замість зупинки всієї збірки
    // крок робить очевидне.
    if (стало >= було) return { було, стало: було, пропущено: true };

    fs.writeFileSync(файл, out, "utf8");

    return { було, стало, пропущено: false };

}

function скрипти(корінь) {

    const знайдені = [];

    (function обійти(каталог) {
        for (const entry of fs.readdirSync(каталог, { withFileTypes: true })) {
            const повний = path.join(каталог, entry.name);
            if (entry.isDirectory()) обійти(повний);
            else if (entry.name.endsWith(".js")) знайдені.push(повний);
        }
    })(корінь);

    return знайдені;

}

async function main() {

    const ціль = process.argv[2];

    if (!ціль || !fs.existsSync(ціль) || !fs.statSync(ціль).isDirectory()) {
        console.error("Вкажіть зібрану теку: node scripts/strip-comments.js _site");
        process.exit(1);
    }

    // ОБХОДИМО ВЕСЬ ЗІБРАНИЙ САЙТ, А НЕ ПЕРЕЛІК ТЕК.
    //
    // Тут стояло ["assets/js", "admin"], відфільтроване через
    // existsSync. Воно працювало: заміряно 02.11.2026 — у зібраному
    // сайті рівно 60 файлів .js, 41 в assets/js і 19 в admin, тобто
    // промаху сьогодні немає.
    //
    // Але перелік зашитий, а фільтр означає, що зникла чи
    // перейменована тека мовчки пропускається. Варто завтра покласти
    // скрипт деінде — і він поїде з коментарями, причому в журналі
    // збирання все буде зелене.
    //
    // У зібраній теці лежить РІВНО те, що віддається браузерам, тож
    // «кожен .js тут треба почистити» — це і є правило, і воно не
    // старіє. scripts/, tests/ і supabase/ сюди не потрапляють
    // (див. ВИНЯТКИ в collect-site.js), тож обходити нема чого
    // боятись.
    const файли = скрипти(ціль);

    // НУЛЬ ФАЙЛІВ — ЦЕ ПОМИЛКА, А НЕ УСПІХ.
    //
    // Доти на теці без скриптів друкувалось «0 файлів» і скрипт
    // виходив нулем, а collect-site.js вважає нульовий код успіхом.
    // Тобто єдиним слідом від виливки, яка повезла коментарі, був би
    // рядок «знято 0 КБ» у журналі, якого ніхто не читає.
    //
    // Сайту без жодного скрипта не буває: каталог, сторінка товару й
    // кошик без JS не працюють узагалі.
    if (!файли.length) {
        throw new Error(`у «${ціль}» не знайдено жодного .js`
            + " — або вказано не ту теку, або збирання зламалось");
    }

    let було = 0, стало = 0;

    let пропущено = 0;

    for (const файл of файли) {
        const r = await обробити(файл);
        було += r.було; стало += r.стало;
        if (r.пропущено) пропущено++;
    }

    // Пропущені називаємо вголос: це майже завжди чужі бібліотеки,
    // які вже мінімізовані, — але якщо колись пропуститься СВІЙ файл,
    // про це треба знати, бо коментарі з нього поїдуть на сайт.
    console.log(`   коментарів зі скриптів знято: ${Math.round((було - стало) / 1024)} КБ`
        + ` (${файли.length} файлів, ${Math.round(було / 1024)} → ${Math.round(стало / 1024)} КБ)`
        + (пропущено ? `, без змін: ${пропущено}` : ""));

}

if (require.main === module) {

    main().catch(error => {
        console.error(error.message);
        process.exit(1);
    });

}

module.exports = { ОПЦІЇ };
