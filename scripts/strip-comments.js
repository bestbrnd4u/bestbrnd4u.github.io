// Знімає коментарі зі скриптів у ЗІБРАНІЙ теці, перед виливкою.
//
// ЗАПУСК (із scripts/collect-site.js):
//   node scripts/strip-comments.js _site
//
// НАВІЩО
// -------
// У репозиторії коментарів більше, ніж коду, і це навмисно. Але у
// вазі сторінки вони важать непропорційно багато — рівно з тієї ж
// причини, що й у стилях: код однорідний і жметься добре, українська
// проза в UTF-8 — погано.
//
// ЗАМІРЯНО 20.10.2026 на всіх 41 файлі assets/js:
//
//     сирих   1528 → 558 КБ
//     gzip     455 → 161 КБ   (−294 КБ, 65%)
//
// На самому каталозі (20 файлів зі згаданих) це близько 166 КБ на
// кожен перший показ.
//
// ЧОМУ ОКРЕМИЙ СКРИПТ, А НЕ РЯДОК У collect-site.js
// --------------------------------------------------
// terser.minify() асинхронний, а collect() синхронний і таким
// потрібен тестам. Запускати його 41 раз через execFileSync означало б
// 41 процес; цей скрипт — один процес, усередині якого вже можна
// чекати на обіцянки.
//
// ЧОМУ САМЕ terser, А НЕ ВИРАЗ
// -----------------------------
// У стилях коментарі можна зняти виразом: їх синтаксис не має
// винятків (див. collect-site.js). У JS — ні: «//» буває всередині
// адреси, «/*» — у регулярці й у шаблонному літералі. Тут потрібен
// справжній розбирач, тож terser із ВИМКНЕНИМИ compress і mangle:
// він лише перевидає розібране дерево, не перейменовуючи й не
// переставляючи нічого.
//
// Побічно terser екранує «<» як «\x3c» у рядках — це той самий
// символ і захист від «</script» усередині рядка.
//
// ЯКЩО terser НЕ ВСТАНОВЛЕНО
// ---------------------------
// Виходимо з попередженням, а не з помилкою: краще віддати сайт із
// коментарями, ніж не віддати зовсім. У Actions це видно як
// ::warning::, тобто мовчки не мине.
const fs = require("fs");
const path = require("path");

let terser = null;

try {
    terser = require("terser");
} catch (error) {
    console.log("::warning::terser не встановлено — скрипти поїдуть із коментарями");
    process.exit(0);
}

// compress і mangle ВИМКНЕНІ навмисно.
//
// Нам потрібні лише коментарі. Стиснення переписало б код (злиття
// змінних, інші умови), і тоді виливка возила б не те, що лежить у
// репозиторії, — а налагоджувати прод довелось би по чужому тексту.
// Перейменування імен зламало б іще й звіти про помилки: у них
// лишаються назви функцій.
const ОПЦІЇ = {
    compress: false,
    mangle: false,
    sourceMap: false,
    ecma: 2020,
    format: {
        comments: false,
        // Рядки лишаються рядками: так номер у звіті про помилку все
        // ще приблизно вказує на місце, а різниця з повним
        // стисненням — лише 7 КБ на весь сайт (заміряно).
        beautify: true,
        indent_level: 0,
        quote_style: 3
    }
};

async function обробити(файл) {

    const код = fs.readFileSync(файл, "utf8");

    const res = await terser.minify(код, ОПЦІЇ);

    if (res.error) throw new Error(`${файл}: terser не впорався — ${res.error.message}`);

    const out = res.code;

    // ЗАПОБІЖНИК 1: висновок мусить бути робочим кодом.
    try {
        new (require("vm").Script)(out);
    } catch (error) {
        throw new Error(`${файл}: після зняття коментарів не парситься — ${error.message}`);
    }

    // ЗАПОБІЖНИК 2: розумні межі.
    //
    // Спершу тут стояла п'ята частина — і вона завалила збирання на
    // breadcrumbs.js (13040 → 2448, тобто 18,8%). Виявилось, що це
    // правда: заміряно 20.10.2026 на восьми модулях, які виконуються
    // і в Node, — від 18% (product-offer.js) до 32% (stock.js) від
    // вихідного розміру. Ці файли справді на 70-82% із пояснень.
    //
    // Поведінку всіх восьми звірено окремо: висновки функцій на тих
    // самих входах збіглись 8 із 8 (див. [7] у
    // tests/test-published-tree.js — там та сама звірка в наборі).
    //
    // Лишаємо десяту частину: менше — це вже точно не «зняли
    // коментарі». Більше за вихідний — теж ознака біди.
    const було = Buffer.byteLength(код), стало = Buffer.byteLength(out);

    if (стало > було) throw new Error(`${файл}: став більшим (${було} → ${стало})`);
    if (стало < було * 0.1) throw new Error(`${файл}: схуд у десять разів (${було} → ${стало}) — підозріло`);

    fs.writeFileSync(файл, out, "utf8");

    return { було, стало };

}

function скрипти(корінь) {

    const знайдені = [];

    (function обійти(каталог) {
        for (const entry of fs.readdirSync(каталог, { withFileTypes: true })) {
            const повний = path.join(каталог, entry.name);
            if (entry.isDirectory()) обійти(повний);
            else if (entry.name.endsWith(".js")) знайдені.push(повний);
        }
    })(корінь);

    return знайдені;

}

async function main() {

    const ціль = process.argv[2];

    if (!ціль || !fs.existsSync(ціль)) {
        console.error("Вкажіть зібрану теку: node scripts/strip-comments.js _site");
        process.exit(1);
    }

    // Лише те, що виконується в браузері. scripts/ і tests/ у зібрану
    // теку й так не потрапляють (див. ВИНЯТКИ в collect-site.js), але
    // покладатись на це не будемо.
    const теки = ["assets/js", "admin"]
        .map(t => path.join(ціль, t))
        .filter(t => fs.existsSync(t));

    let було = 0, стало = 0, файлів = 0;

    for (const тека of теки) {
        for (const файл of скрипти(тека)) {
            const r = await обробити(файл);
            було += r.було; стало += r.стало; файлів++;
        }
    }

    console.log(`   коментарів зі скриптів знято: ${Math.round((було - стало) / 1024)} КБ`
        + ` (${файлів} файлів, ${Math.round(було / 1024)} → ${Math.round(стало / 1024)} КБ)`);

}

if (require.main === module) {

    main().catch(error => {
        console.error(error.message);
        process.exit(1);
    });

}

module.exports = { ОПЦІЇ };
