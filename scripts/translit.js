// Транслітерація кирилиці латиницею для адрес сторінок.
//
// ЩО ЦЕ ВИРІШУЄ
// --------------
// Ім'я файлу товару стає slug-ом, а slug — адресою /p/<slug>/. Поки в
// імені кирилиця, адреса виглядає так:
//
//   /p/%D0%B3%D0%BE%D0%B4%D0%B8%D0%BD%D0%BD%D0%B8%D0%BA-tissot-…/
//
// Кожна літера — девʼять символів. Браузер показує її розшифрованою, а
// от скрізь, де адресу треба СКОПІЮВАТИ, вилазить саме ця борода: в
// адмінці, у постах, у повідомленнях. А коли таку адресу ще й кладуть
// у параметр (t.me/…?text=…), вона кодується вдруге — %25D0%25B3 — і
// стає втричі довшою за сам товар.
//
// ЧОМУ САМЕ ОФІЦІЙНА ТАБЛИЦЯ
// ---------------------------
// Транслітерувати можна по-різному: «х» це h чи kh, «и» це i чи y.
// Вигадана таблиця означала б, що завтра хтось перепише її інакше — і
// всі адреси зміняться вдруге. Тому беремо ту, що вже є: постанова
// КМУ №55 від 27.01.2010, офіційна транслітерація українського
// алфавіту латиницею. Її ж використовують у закордонних паспортах, тож
// написання впізнаване («Kyiv», а не «Kiev»).
//
// Кілька літер у ній залежать від позиції: на початку слова «я» це ya,
// всередині — ia. Тому таблицею одних лише символів не обійтись, і
// нижче йде розбір по буквах із памʼяттю про попередню.

"use strict";

// Літери, що не залежать від позиції.
const PLAIN = {
    а: "a", б: "b", в: "v", г: "h", ґ: "g", д: "d",
    е: "e", ж: "zh", з: "z", и: "y", і: "i", к: "k",
    л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
    с: "s", т: "t", у: "u", ф: "f", х: "kh", ц: "ts",
    ч: "ch", ш: "sh", щ: "shch", ю: "iu", я: "ia",
    є: "ie", ї: "i", й: "i",

    // Мʼякий знак і апостроф не передаються — так у таблиці.
    ь: "", "'": "", "’": "", "ʼ": "",

    // Літери, яких в українському алфавіті немає, але вони трапляються
    // в назвах, скопійованих з російських описів постачальників. Без
    // них такі назви втрачали б букви мовчки.
    ё: "yo", ы: "y", э: "e", ъ: ""
};

// Ті самі літери на ПОЧАТКУ слова пишуться інакше.
const AT_WORD_START = {
    є: "ye", ї: "yi", й: "y", ю: "yu", я: "ya"
};

// Літера — це те, після чого наступний символ уже не «початок слова».
const LETTER_RE = /[\p{L}\p{N}]/u;

// Регістр однієї літери переносимо на все, у що вона перетворилась.
//
// Для slug-а це байдуже — він однаково зводиться до нижнього
// регістру. Але translit() віддають і в інші місця (заголовки, підписи
// до фото), і там «ЩАСТЯ» мусить лишитись «SHCHASTIA», а «Щастя» —
// стати «Shchastia», а не «SHchastia» чи «shchastia».
//
// Розрізняємо їх за наступним символом: велика літера поруч означає
// слово капслоком.
function matchCase(mapped, source, next, prev) {

    if (!mapped) return mapped;

    const isUpper = source !== source.toLowerCase();

    if (!isUpper) return mapped;

    // Слово капслоком упізнаємо по сусідах з обох боків: без
    // погляду назад остання літера «ЩАСТЯ» лишалась би «SHCHASTIa».
    const caps = ch => typeof ch === "string"
        && LETTER_RE.test(ch)
        && ch !== ch.toLowerCase();

    if (caps(next) || caps(prev)) return mapped.toUpperCase();

    return mapped[0].toUpperCase() + mapped.slice(1);

}

/**
 * Кирилиця → латиниця за таблицею КМУ 2010.
 * Латинські літери, цифри й розділові знаки лишаються як є.
 */
function translit(text) {

    const source = String(text == null ? "" : text);

    let out = "";
    let atWordStart = true;

    for (let i = 0; i < source.length; i++) {

        const ch = source[i];
        const lower = ch.toLowerCase();

        // Єдина двобуквена послідовність у таблиці: «зг» → zgh.
        // Потрібна, щоб відрізнити її від «ж» (zh) — інакше «згін» і
        // «жін» дали б однакову латиницю.
        if (lower === "з" && source[i + 1] && source[i + 1].toLowerCase() === "г") {

            // Регістр беремо від «З», а сусіда для «капслок чи ні»
            // дивимось уже ЗА «г» — інакше «Згорани» дало б «ZGHorany».
            out += matchCase("zgh", ch, source[i + 2], source[i - 1]);

            i += 1;
            atWordStart = false;

            continue;

        }

        const mapped = atWordStart && AT_WORD_START[lower] !== undefined
            ? AT_WORD_START[lower]
            : PLAIN[lower];

        if (mapped !== undefined) {

            out += matchCase(mapped, ch, source[i + 1], source[i - 1]);

            // Мʼякий знак не літера й слова не починає, але й не
            // розриває його: після «ь» наступна літера — не початок.
            atWordStart = false;

            continue;

        }

        out += ch;

        atWordStart = !LETTER_RE.test(ch);

    }

    return out;

}

/**
 * Готовий slug: транслітерація + тільки [a-z0-9-].
 *
 * Ідемпотентна: slug, який уже латинський, лишається тим самим. Це не
 * дрібниця — збірка проганяє через неї КОЖНЕ ім'я файлу на кожному
 * запуску, і найменша нестабільність перейменовувала б товари
 * по колу, щоразу міняючи їхні адреси.
 */
function toSlug(text) {

    return translit(String(text == null ? "" : text))
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");

}

/** Чи потребує ім'я перетворення. */
function isLatinSlug(text) {
    return typeof text === "string" && text !== "" && toSlug(text) === text;
}

/**
 * Розкладка «старе ім'я → нове» для цілого набору.
 *
 * Спершу за собою закріплюють імена ті, кого міняти не треба: інакше
 * перейменований запис міг би зайняти чуже місце. Далі — колізії: дві
 * різні назви цілком можуть дати однакову латиницю, і другий отримує
 * «-2».
 *
 * Порожній результат (ім'я без жодної літери й цифри) пропускаємо:
 * адресу з нічого не вигадаєш.
 *
 * @param {string[]} names — імена БЕЗ розширення
 * @returns {Map<string,string>} лише ті, що змінюються
 */
function planLatinRenames(names) {

    const list = Array.isArray(names) ? names : [];

    const taken = new Set(list.filter(isLatinSlug));

    const plan = new Map();

    list.forEach(name => {

        if (isLatinSlug(name)) return;

        const base = toSlug(name);

        if (!base) return;

        let wanted = base;
        let n = 1;

        while (taken.has(wanted)) {
            n += 1;
            wanted = `${base}-${n}`;
        }

        taken.add(wanted);
        plan.set(name, wanted);

    });

    return plan;

}

module.exports = { translit, toSlug, isLatinSlug, planLatinRenames, PLAIN, AT_WORD_START };
