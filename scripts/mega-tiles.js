// Зменшені плитки випадаючого меню: «стать → файл».
//
// НАВІЩО ОКРЕМИЙ ФАЙЛ НА ЧОТИРИ РЯДКИ
// ------------------------------------
// Словник потрібен двом скриптам, і вони з різних світів:
//
//   build-banners.js    МАЛЮЄ ці плитки (sharp, читає products.json),
//                       запускається окремою командою npm run banners;
//   build-home-static.js ПІДСТАВЛЯЄ їх у головну, і крутиться в
//                       кожній звичайній збірці.
//
// Перша спроба була простіша: експортувати словник прямо з
// build-banners.js. Це працює, але тягне за собою require("sharp") —
// а в основному ланцюжку збірки sharp не потрібен ЖОДНОМУ скрипту.
// Тобто складання сайту почало б залежати від нативного модуля, і
// середовище без зібраного sharp валило б усю збірку замість однієї
// необов'язкової команди.
//
// ЧОМУ ЦЕ ВЗАГАЛІ ВАЖЛИВО
// ------------------------
// Плитка в меню — 88×88 px. Доки головна підставляла туди знімки
// категорій із home.json (кожен на пів екрана), вона качала 8,7 МБ
// на чотири картинки — і викидала їх, бо мега-меню за мить
// перемальовує mega-menu.js. Решта сторінок уже брали ці webp по
// 0,2–3,5 КБ. Розійдись словник на дві копії — і головна тихо
// повернеться до мегабайтів.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

const DIR = "assets/images/banners";

const MEGA_MENU_FILES = {
    "Чоловікам": "mega-men.webp",
    "Жінкам": "mega-women.webp",
    "Унісекс": "mega-unisex.webp",
    "Дітям": "mega-kids.webp"
};

// Адреса готової плитки — або порожньо, якщо файлу ще немає.
//
// Порожньо означає «банери ще не збирали»: тоді той, хто питає,
// лишає що було. Важкий знімок гірший за легкий, але незрівнянно
// кращий за порожнє місце в меню.
function megaTile(gender) {

    const file = MEGA_MENU_FILES[gender];

    if (!file) return "";

    const relative = DIR + "/" + file;

    return fs.existsSync(path.join(ROOT, relative)) ? "/" + relative : "";

}

module.exports = { MEGA_MENU_FILES, megaTile, MEGA_DIR: DIR };
