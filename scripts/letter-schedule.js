// Коли саме йдуть два листи навздогін покупцеві — і чому вони не
// мають зіштовхнутись.
//
// НАВІЩО ЦЕ ОКРЕМИМ ФАЙЛОМ
// -------------------------
// Листів два, і обидва вирішують різне:
//
//   прохання про відгук  — «розкажіть, як вам»
//   дякуємо за покупку   — персональний промокод на наступну покупку
//
// Поодинці кожен доречний. Поспіль — ні: знижка, яка приходить
// наступного дня після прохання про відгук, читається як ПЛАТА ЗА
// ВІДГУК. Для магазину, що тримається на довірі, це гірше, ніж не
// слати другий лист узагалі.
//
// ЩО ВЖЕ ЛАМАЛОСЬ. Спершу правило жило у двох місцях: поле в адмінці
// дозволяло від 7 днів, а тест вимагав не менше 14. Власник поставив
// 8 — законне за адмінкою, заборонене тестом — і CI впав (11.09.2026).
// Правило, записане двічі, розходиться; тому воно тут одне.
//
// ЧОМУ ВІДСТАНЬ, А НЕ «ПІЗНІШЕ»
// ------------------------------
// Важлива саме відстань між листами, а не їхній порядок. Знижка за
// день ДО прохання про відгук виглядає так само куплено, як і за день
// після.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

// Тиждень. Менше — листи читаються як одна розсилка; більше — покупець
// уже забув про магазин, і другий лист починає все спочатку.
const MIN_GAP_DAYS = 7;

// Значення за замовчуванням — ті самі, що в адмінці. Потрібні, коли
// файлу налаштувань немає (свіжий клон, перевірка на чистій теці).
const DEFAULTS = { reviewDays: 7, thankYouDays: 30 };

function saved() {

    try {
        return JSON.parse(fs.readFileSync(path.join(ROOT, "data", "notifications.json"), "utf8"));
    } catch (error) {
        return {};
    }

}

function positive(value, fallback) {

    const parsed = Number(value);

    return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;

}

// Обидва строки з адмінки.
function schedule(settings) {

    const data = settings || saved();

    return {
        reviewDays: positive(data.reviewDays, DEFAULTS.reviewDays),
        thankYouDays: positive(data.thankYouDays, DEFAULTS.thankYouDays)
    };

}

// Чи можна слати. Повертає текст проблеми або порожньо.
//
// ЧОМУ ПОСТУПАЄТЬСЯ САМЕ «ДЯКУЄМО». Прохання про відгук нічого не
// продає й не має ціни; лист зі знижкою — має. Якщо вони надто
// близько, зупиняти треба той, через який виникає підозра.
function tooClose(reviewDays, thankYouDays) {

    const gap = Math.abs(Number(thankYouDays) - Number(reviewDays));

    if (gap >= MIN_GAP_DAYS) return "";

    return `Між листами ${gap} дн., а треба щонайменше ${MIN_GAP_DAYS}: `
        + `прохання про відгук на ${reviewDays}-й день, «дякуємо» на ${thankYouDays}-й. `
        + `Знижка поруч із проханням про відгук виглядає як плата за нього. `
        + `Полагодити в адмінці: «Листи покупцеві» → рознести строки.`;

}

module.exports = { MIN_GAP_DAYS, DEFAULTS, schedule, tooClose };
