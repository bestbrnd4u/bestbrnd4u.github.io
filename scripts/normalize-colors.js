// Окремі свотчі, назву яких не врятувати чищенням.
//
// НАВІЩО КЛЮЧ ПО HEX. У межах одного товару два різні відтінки можуть
// називатись однаково: у Coach Tabby 26 і #8c6f63 (приглушений
// сіро-коричневий, у Coach це «Dark Stone»), і #b66813 (насичений
// коричневий) записані як «Коричневий». За назвою вони нерозрізнимі,
// за свотчем — очевидно різні. Тому для таких випадків ключем служить
// сам колір, а не його підпис.
//
// Список свідомо короткий: це не спосіб перейменовувати кольори, а
// латка на конкретні зіткнення. Якщо він починає рости — значить,
// кольори в адмінці заповнюють надто грубо, і лікувати треба там.
const COLOR_BY_HEX = new Map(Object.entries({
    "#8c6f63": "Сіро-коричневий"
}));

// Артикули відтінків, які трапляються всередині назви. Це або код
// постачальника (1R5, 21G, 286), або повний sku (WR953HA) — у назві
// кольору вони не потрібні, бо є в полі sku варіанта.
const ARTICLE_CODE = /\b(?=[a-z0-9-]*\d)[a-z0-9]{1,4}(?:-[a-z0-9]+)*\b/gi;

// Слова про фурнітуру й обробку. Самі по собі кольором речі не є:
// «Brass/Chalk» — золота фурнітура на айворі, а не золотий колір.
const HARDWARE_WORDS = /\b(brass|chalk|nickel|antique|glacier|gold|silver)\b/gi;

function tidySpaces(text) {

    return String(text || "")
        .replace(/\s+/g, " ")
        .replace(/\s*([/,])\s*/g, "$1")
        .trim();

}

// Ключі словника проганяємо через ту саму нормалізацію пробілів, що й
// назву на вході.
//
// ЧОМУ. У даних трапляється «Tan / Chalk / Brass — …» з пробілами
// навколо косих і «Camel — карамельний, світло-коричневий» з комою.
// tidySpaces() стискає такі місця («Tan/Chalk/Brass»), тож ключ,
// записаний тут «як у даних», уже не збігався — і три записи словника
// мовчки не працювали. Помітити це можна було лише за результатом,
// тому нормалізуємо обидві сторони порівняння в одному місці.
const COLOR_DICTIONARY = new Map(
    Object.entries(COLOR_DICTIONARY_SOURCE)
        .map(([key, value]) => [tidySpaces(key).toLowerCase(), value])
);

function capitalize(text) {

    if (!text) return text;

    return text[0].toLocaleUpperCase("uk") + text.slice(1);

}

// Механічне чищення для назв, яких немає у словнику.
function cleanupColorName(name) {

    let text = tidySpaces(name);

    if (!text) return "";

    // «Black чорний» / «Beige — бежевий»: англійська частина дублює
    // українську. Лишаємо українську — сайт український.
    const cyrillic = text.match(/[А-Яа-яЇїІіЄєҐґ][А-Яа-яЇїІіЄєҐґ'\- ]*/g);

    if (cyrillic) {

        const longest = cyrillic
            .map(part => part.trim())
            .filter(part => part.length > 2)
            .sort((a, b) => b.length - a.length)[0];

        if (longest) return capitalize(tidySpaces(longest));

    }

    // Українського варіанта немає — чистимо латинку від службового.
    text = text
        .replace(HARDWARE_WORDS, " ")
        .replace(ARTICLE_CODE, " ")
        .replace(/[—–]/g, " ");

    text = tidySpaces(text);

    return text ? capitalize(text) : capitalize(tidySpaces(name));

}

function normalizeColorName(name, hex) {

    const key = tidySpaces(name).toLowerCase();

    if (!key) return "";

    const byHex = hex && COLOR_BY_HEX.get(String(hex).trim().toLowerCase());

    if (byHex) return byHex;

    if (COLOR_DICTIONARY.has(key)) return COLOR_DICTIONARY.get(key);

    return cleanupColorName(name);

}

// Світлість свотча — щоб на зіткненні назв відрізнити темніший
// відтінок від світлішого словами, а не цифрою в дужках.
function hexLightness(hex) {

    const value = String(hex || "").trim().replace(/^#/, "");

    if (!/^[0-9a-f]{6}$/i.test(value)) return null;

    const r = parseInt(value.slice(0, 2), 16);
    const g = parseInt(value.slice(2, 4), 16);
    const b = parseInt(value.slice(4, 6), 16);

    // сприйнята яскравість, а не середнє: око бачить зелений
    // світлішим за синій тієї самої «математичної» яскравості
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255;

}

// Нормалізація кольорів одного товару.
//
// ВАЖЛИВО: у межах ОДНОГО товару назви кольорів мусять лишатися
// різними — за назвою кольору знаходиться варіант (фото, розміри,
// артикул), і два однакових імені означали б, що другий варіант
// недосяжний. Тому якщо зведення дало збіг, до другого додається
// уточнення з його ж вихідної назви, а не «(2)».
function normalizeProductColors(product) {

    const variants = Array.isArray(product && product.variants) ? product.variants : [];

    const taken = new Set();
    const takenHex = new Map(); // зайнята назва -> її свотч

    const renamed = new Map(); // стара назва -> нова

    variants.forEach(variant => {

        if (!variant || !variant.color) return;

        const before = variant.color;

        let after = normalizeColorName(before, variant.hex);

        if (taken.has(after)) {

            // Зіткнення: два відтінки одного товару звелись до однієї
            // назви. Розводимо їх словами про світлість — «Темно-» чи
            // «Світло-» від того, з чим зіткнулись. Це читається як
            // колір, на відміну від «Коричневий 2».
            const mine = hexLightness(variant.hex);
            const theirs = hexLightness(takenHex.get(after));

            if (mine !== null && theirs !== null && Math.abs(mine - theirs) > 0.02) {

                const prefix = mine < theirs ? "Темно-" : "Світло-";

                const candidate = prefix + after.toLocaleLowerCase("uk");

                if (!taken.has(candidate)) after = candidate;

            }

        }

        if (taken.has(after)) {

            // Ні світлість не допомогла, ні словник — лишаємо вихідну
            // назву. Негарно, зате варіант досяжний: за назвою кольору
            // знаходяться фото, розміри й артикул, і два однакових
            // імені зробили б другий варіант недосяжним.
            after = before;

        }

        taken.add(after);
        takenHex.set(after, variant.hex);

        if (after !== before) renamed.set(before, after);

        variant.color = after;

    });

    // Поле color верхнього рівня — це колір першого варіанта; тримаємо
    // їх узгодженими, інакше картка й сторінка товару показували б
    // різні назви того самого кольору.
    if (product && product.color) {

        product.color = renamed.get(product.color)
            || normalizeColorName(product.color, variants[0] && variants[0].hex);

    }

    return renamed;

}

