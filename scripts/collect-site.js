// Збирає теку, яку виливаємо на GitHub Pages.
//
// Запуск (із .github/workflows/deploy-pages.yml):
//   node scripts/collect-site.js _site
//
// НАВІЩО
// -------
// Виливка робилась із `path: .` — на Pages їхав увесь репозиторій.
// Заміряно 19.10.2026: зі 155 МБ опублікованого сайту 44 МБ не
// потрібні відвідувачу ніяк —
//
//     assets/images/_originals   16 МБ   копії фото до обробки
//     assets/images/_archive     17 МБ   зняті з сайту банери
//     scripts/                  5,4 МБ   код збірки
//     tests/                    4,0 МБ   самі тести
//     supabase/                 1,6 МБ   міграції й код функції
//
// і все це віддавалось публічно: /tests/test-oversell.js та
// /supabase/migrations/011-stock-reservation.sql повертали 200.
//
// Це не охайність. У GitHub Pages ліміт опублікованого сайту — 1 ГБ,
// а кожен товар додає близько 0,75 МБ фотографій. Третина бюджету,
// витрачена на службові файли, — це сотні товарів, яких магазин не
// зможе виставити, поки хтось не розбереться, куди поділось місце.
//
// ЧОМУ ОКРЕМИЙ СКРИПТ, А НЕ РЯДОК RSYNC У YAML
// ---------------------------------------------
// Перелік винятків — класичний спосіб тихо зламати сайт: досить
// додати рядок, і потрібний файл перестає їхати. У репозиторії він на
// місці, git чистий, сторінка відкривається — просто без картинки або
// без скрипта.
//
// Скрипт можна ВИКОНАТИ в тестах і подивитись на результат, а рядок у
// YAML можна хіба що звірити регуляркою. tests/test-published-tree.js
// саме це й робить: збирає сайт у тимчасову теку й перевіряє, що там
// є кожен файл, на який посилається розмітка.
//
// ЧОМУ НЕ ЧИСТИМО РОБОЧУ ТЕКУ
// ----------------------------
// Останній крок виливки запускає scripts/purge-cache.js — тобто
// scripts/ має лишитись на місці. Тому копіюємо в окрему теку, а не
// видаляємо зайве з наявної.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

// Шляхи ВІД КОРЕНЯ репозиторію. Саме від кореня, а не просто назви:
// інакше виняток «archive» вигріб би ще й assets/images/_archive за
// збігом назви, а «docs» — будь-яку теку docs усередині сайту.
const ВИНЯТКИ = [
    ".git",
    ".github",
    ".gitignore",
    ".gitattributes",
    ".claude",
    ".playwright-mcp",
    "node_modules",
    "archive",
    "docs",
    "scripts",
    "tests",
    "supabase",
    "package.json",
    "package-lock.json",
    "assets/images/_originals",
    "assets/images/_archive"
];

// Файли в корені, без яких сайт ламається або втрачає домен. У
// розмітці на них ніхто не посилається, тому їх найлегше випадково
// виключити — і найважче помітити:
//
//   .nojekyll   без нього Pages ховає все, що починається з «_»
//   CNAME       власний домен (лежить лише в гілці main)
//   robots.txt, sitemap.xml, feed.xml, llms.txt — пошук і фід
//   <32 hex>.txt — ключ IndexNow, підтверджує право надсилати адреси
const ОБОВЯЗКОВІ = [".nojekyll", "CNAME", "robots.txt", "sitemap.xml", "feed.xml", "llms.txt"];

// Збіг ТОЧНИЙ, без перевірки «чи лежить усередині».
//
// Цього досить, бо обхід нижче відсікає теку цілком і в неї не
// заходить: до файлів усередині assets/images/_originals справа
// просто не доходить. Перевірка на вкладеність тут була — і виявилась
// недосяжною: жоден злам не зміг її зачепити, бо кожен шлях, який
// сюди потрапляє, лежить рівно на один рівень глибше за вже дозволену
// теку.
//
// Звідси умова до переліку: шляхи від кореня, без кінцевої скісної.
// КОМЕНТАРІ ЗІ СТИЛЮ НА САЙТ НЕ ЇДУТЬ.
//
// У репозиторії вони лишаються — у цьому файлі їх теж повно, і це
// навмисно. Але відвідувачеві вони коштують більше, ніж самі правила.
//
// ЗАМІРЯНО 20.10.2026 на style.css:
//
//     сирий цілий        548 КБ   =  244 КБ коду + 304 КБ коментарів
//     gzip цілий         140 КБ   =   37 КБ коду +  89 КБ коментарів
//
// Тобто коментарі — ДВІ ТРЕТИНИ стиснутого стилю. Причина не в обсязі,
// а в стисливості: правила однорідні до неможливості (`color:var(…)`
// сотні разів) і жмуться 6.5:1, а українська проза в UTF-8 — лише
// 3.4:1. Сирий розмір тут обманює: 56% тексту дають 64% трафіку.
//
// ЧОМУ РЕГУЛЯРКА ТУТ ДОСТАТНЯ. Коментарі в CSS не вкладаються:
// /* … /* … */ закінчується на ПЕРШОМУ */, і не жадібний вираз робить
// рівно те саме, що браузер. Перевірено на цьому файлі: жодного /* чи
// */ немає ні в рядкових літералах (177), ні в url() (7).
//
// Запобіжник нижче важливіший за сам вираз: якщо зникне бодай один
// селектор, збірка впаде тут, а не на сайті.
let знятоКоментарів = 0;

function безКоментарівCss(css, звідки) {

    // КРОК 1. Передумова, за якої зняття коментарів ТОЧНО безпечне.
    //
    // Не жадібний /\/\*[\s\S]*?\*\// розбирає CSS так само, як браузер,
    // рівно доки «/*» і «*/» не трапляються всередині рядкового
    // літерала чи url() — там вони звичайні символи, і вираз вирізав би
    // шматок правила. Тому не віримо на слово, а перевіряємо щоразу:
    // файл міг змінитись після того, як це писалось.
    const літерали = (css.match(/"[^"\n]*"|'[^'\n]*'|url\([^)]*\)/g) || []);
    const небезпечні = літерали.filter(s => s.includes("/*") || s.includes("*/"));

    if (небезпечні.length) {
        throw new Error(
            `${звідки}: «/*» або «*/» усередині ${небезпечні.length} літералів`
            + ` (напр. ${небезпечні[0].slice(0, 40)}) — знімати коментарі виразом не можна`
        );
    }

    const безКоментарів = css.replace(/\/\*[\s\S]*?\*\//g, "");

    // КРОК 2. Прибирання порожніх рядків — і ось його перевіряємо
    //         точно, а не на вигляд.
    //
    // Цей крок МАЄ ПРАВО міняти лише пробільні символи. Отже якщо
    // згорнути всі пробіли в обох версіях, рядки мусять збігтись
    // символ у символ. Це й перевіряємо — інваріант, а не ознака.
    //
    // Перша версія звіряла перелік селекторів, і цього було мало:
    // сценарій, який почав з'їдати крапку з комою в кінці рядка,
    // пройшов зеленим. Селектори на місці, дужки на місці, а
    // оголошення в тілах правил злиплись. Згортання пробілів ловить
    // це одразу й не вимагає нічого знати про синтаксис CSS.
    //
    // З ВИХІДНИМ файлом так порівнювати не можна — там ще є
    // коментарі; тому звіряємо крок 1 із кроком 2.
    const чистий = безКоментарів
        .replace(/\n[ \t]*(?=\n)/g, "")
        .replace(/\n{3,}/g, "\n\n");

    const згорнути = текст => текст.replace(/\s+/g, " ").trim();

    if (згорнути(безКоментарів) !== згорнути(чистий)) {

        const a = згорнути(безКоментарів);
        const b = згорнути(чистий);
        let i = 0;
        while (i < a.length && i < b.length && a[i] === b[i]) i++;

        throw new Error(
            `${звідки}: прибирання порожніх рядків змінило не лише пробіли`
            + ` — розбіжність на символі ${i}: «${a.slice(i - 30, i + 30)}»`
            + ` проти «${b.slice(i - 30, i + 30)}»`
        );

    }

    return чистий;

}

function виключено(відносний, dest) {

    // Сама тека призначення — інакше копіювали б її в себе.
    if (відносний === dest) return true;

    return ВИНЯТКИ.includes(відносний);

}

function collect(dest, { тихо = false } = {}) {

    const ціль = path.isAbsolute(dest) ? dest : path.join(ROOT, dest);

    const маркер = path.relative(ROOT, ціль).split(path.sep).join("/");

    fs.rmSync(ціль, { recursive: true, force: true });
    fs.mkdirSync(ціль, { recursive: true });

    let файлів = 0;
    let байтів = 0;

    // Скидаємо: лічильник на рівні модуля, а collect() кличуть кілька
    // разів за прогін (тести збирають сайт у тимчасову теку). Без
    // цього рядка друге число було б сумою двох збірок — рівно та
    // пастка, що вже траплялась із лічильником через «+=».
    знятоКоментарів = 0;

    (function обійти(каталог) {

        for (const entry of fs.readdirSync(каталог, { withFileTypes: true })) {

            const повний = path.join(каталог, entry.name);

            const відносний = path.relative(ROOT, повний).split(path.sep).join("/");

            if (виключено(відносний, маркер)) continue;

            if (entry.isDirectory()) {

                обійти(повний);

            } else {

                const куди = path.join(ціль, відносний);

                fs.mkdirSync(path.dirname(куди), { recursive: true });

                if (відносний.endsWith(".css")) {
                    fs.writeFileSync(куди, безКоментарівCss(fs.readFileSync(повний, "utf8"), відносний), "utf8");
                    знятоКоментарів += fs.statSync(повний).size - fs.statSync(куди).size;
                } else {
                    fs.copyFileSync(повний, куди);
                }

                файлів++;
                байтів += fs.statSync(повний).size;

            }

        }

    })(ROOT);

    // Обовʼязкові файли перевіряємо ПІСЛЯ копіювання, а не звіряємо з
    // переліком винятків: виняток — не єдиний спосіб їх загубити.
    // Головне питання одне — чи лежить файл у зібраній теці.
    const зниклі = ОБОВЯЗКОВІ
        .filter(f => fs.existsSync(path.join(ROOT, f)))
        .filter(f => !fs.existsSync(path.join(ціль, f)));

    if (зниклі.length) {
        throw new Error("У зібраному сайті немає обовʼязкових файлів: " + зниклі.join(", "));
    }

    // КОМЕНТАРІ ЗІ СКРИПТІВ — ОКРЕМИМ ПРОЦЕСОМ.
    //
    // У стилях їх знімає вираз (вище): синтаксис коментарів у CSS без
    // винятків. У JS так не можна — «//» трапляється в адресах, «/*» у
    // регулярках і шаблонних літералах, — тому там працює terser із
    // вимкненими compress і mangle, тобто просто перевидає розібране
    // дерево. terser.minify() асинхронний, а ця функція синхронна й
    // такою потрібна тестам, тож кличемо скрипт, а не бібліотеку.
    //
    // Якщо terser не встановлено, scripts/strip-comments.js виходить
    // із ::warning:: і кодом 0 — сайт поїде з коментарями, але поїде.
    try {

        const вивід = require("child_process").execFileSync(
            process.execPath,
            [path.join(__dirname, "strip-comments.js"), ціль],
            { encoding: "utf8", stdio: "pipe", timeout: 600000 }
        );

        if (!тихо && вивід.trim()) process.stdout.write(вивід);

    } catch (error) {

        throw new Error(
            "Зняття коментарів зі скриптів не вдалось: "
            + ((error.stdout || "") + (error.stderr || "") || error.message).trim()
        );

    }

    if (!тихо) {
        console.log(`Готово: ${файлів} файлів, ${(байтів / 1048576).toFixed(1)} МБ → ${dest}`);
        if (знятоКоментарів > 0) {
            console.log(`   коментарів зі стилів знято: ${Math.round(знятоКоментарів / 1024)} КБ`);
        }
    }

    return { файлів, байтів, ціль, знятоКоментарів };

}

if (require.main === module) {

    const dest = process.argv[2] || "_site";

    try {
        collect(dest);
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }

}

module.exports = { collect, ВИНЯТКИ, ОБОВЯЗКОВІ };
