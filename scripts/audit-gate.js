// Ворота проти відомих вразливостей у залежностях.
//
// НАВІЩО ЦЕ З'ЯВИЛОСЬ
// --------------------
// 19.10.2026 власник знайшов на сторінці Dependabot дві відкриті
// скарги високого рівня — sharp і source-map-js. Обидві висіли там
// тижнями, і жодна перевірка про них не знала: тести ганяють лише
// файли репозиторію, а про вразливості знає реєстр npm.
//
// Прикметно, що автоматика СПРАЦЮВАЛА наполовину. На sharp Dependabot
// підняв PR — і той просто лежав відкритим. А на source-map-js PR не
// з'явився взагалі: виправлена версія 1.2.2 вже підходила під діапазон
// `^1.2.1`, який просить css-tree, тож піднімати не було чого —
// достатньо було перерахувати package-lock.json. Тобто сповіщення
// було тільки на сторінці, куди треба зайти самому.
//
// Тепер про таке каже той самий прогін, який і так дивляться після
// кожного пуша.
//
// ЧОМУ НЕ ВСЕ ПІДРЯД ВАЛИТЬ ЗБІРКУ
// ---------------------------------
// Нова скарга з'являється на боці реєстру, без жодної правки в коді.
// Якби ворота валили геть усе, одного ранку перестали б проходити всі
// пуші поспіль — зокрема ті, якими цю скарту й лікують.
//
// Тому:
//   • high/critical, і виправлення не ламає сумісність → ПРОВАЛ.
//     Лікується одним `npm audit fix`, тож тримати це відкритим
//     немає причин.
//   • high/critical, але виправлення лише через мажорну версію →
//     попередження. Мажор у збірці може вимагати роботи, і блокувати
//     на цей час усі пуші — гірше за саму вразливість.
//   • виправлення ще немає → попередження. Зробити все одно нічого.
//   • moderate і нижче → рядок у звіті.
//
// ВАЖЛИВО: усе це — залежності збірки й тестів (sharp, jsdom,
// js-yaml, onnxruntime). На сам сайт не їде жоден з цих пакетів:
// у браузер віддається статичний HTML. Тобто це про машину, на якій
// збирається сайт, а не про відвідувача.
const { execFileSync } = require("child_process");

const ВАЖКІ = ["high", "critical"];

// Розбір звіту винесено окремо від запуску: саме його перевіряє
// tests/test-audit-gate.js, підсовуючи вигадані звіти. Інакше
// перевірка воріт залежала б від того, що саме сьогодні в реєстрі.
function вердикт(report) {

    const пакети = (report && report.vulnerabilities) || {};

    const провали = [];
    const попередження = [];

    for (const [назва, запис] of Object.entries(пакети)) {

        if (!ВАЖКІ.includes(запис.severity)) continue;

        // Заголовок самої поради лежить у via — там або рядок (назва
        // пакета, через який прилетіло), або об'єкт із title і url.
        const порада = (запис.via || []).find(v => v && typeof v === "object") || {};

        const рядок = {
            назва,
            рівень: запис.severity,
            діапазон: запис.range || "",
            заголовок: порада.title || "",
            посилання: порада.url || ""
        };

        const fix = запис.fixAvailable;

        if (!fix) {

            попередження.push({ ...рядок, чому: "виправлення ще немає" });

        } else if (fix.isSemVerMajor) {

            попередження.push({
                ...рядок,
                чому: `виправлення лише через мажорну версію (${fix.name}@${fix.version})`
            });

        } else {

            провали.push({
                ...рядок,
                лікування: fix === true
                    ? "npm audit fix"
                    : `npm audit fix (${fix.name}@${fix.version})`
            });

        }

    }

    return { провали, попередження };

}

// Сам запуск. Мережі може не бути (локально в літаку, у відрізаному
// контейнері) — тоді ворота мовчать і пропускають: перевірка, яка
// падає без інтернету, швидко привчає ганяти тести з --ignore.
function звіт() {

    try {

        const out = execFileSync("npm", ["audit", "--json"], {
            encoding: "utf8",
            stdio: ["ignore", "pipe", "pipe"],
            timeout: 60000,
            // npm виходить з кодом 1, коли щось знайшов, — це не
            // помилка запуску, а результат. Тому код ігноруємо, а
            // дивимось на вміст.
            shell: process.platform === "win32"
        });

        return JSON.parse(out);

    } catch (error) {

        // Знайшлись вразливості → ненульовий код, але stdout із JSON.
        const out = error && error.stdout;

        if (out) {
            try { return JSON.parse(out); } catch (e) { /* нижче */ }
        }

        return null;

    }

}

function main() {

    const report = звіт();

    if (!report || !report.vulnerabilities) {

        console.log("::warning::npm audit не відповів — ворота пропускають. "
            + "Перевірте вручну: https://github.com/bestbrnd4u/bestbrnd4u.github.io/security/dependabot");

        return;

    }

    const { провали, попередження } = вердикт(report);

    const всього = (report.metadata && report.metadata.vulnerabilities) || {};

    console.log(`Перевірено залежностей: вразливостей усього ${всього.total || 0}`
        + ` (critical ${всього.critical || 0}, high ${всього.high || 0},`
        + ` moderate ${всього.moderate || 0}, low ${всього.low || 0})`);

    попередження.forEach(п => {
        console.log(`::warning::${п.назва} (${п.рівень}): ${п.заголовок || п.діапазон}`
            + ` — ${п.чому}. ${п.посилання}`);
    });

    if (!провали.length) {

        console.log("Важких вразливостей із простим виправленням немає.");

        return;

    }

    провали.forEach(п => {
        console.log(`::error::${п.назва} (${п.рівень}): ${п.заголовок || п.діапазон}`
            + ` — лікується: ${п.лікування}. ${п.посилання}`);
    });

    console.error(`\nВідомих вразливостей із доступним виправленням: ${провали.length}.`);
    console.error("Полагодити: npm audit fix, далі npm test і коміт разом із package-lock.json.\n");

    process.exit(1);

}

if (require.main === module) main();

module.exports = { вердикт, ВАЖКІ };
