-- ======================================
-- Bagvero — перевірка, чи є email в системі
-- (потрібна для форми "Забули пароль?": показати
-- користувачу зрозуміле повідомлення, а не мовчки
-- прикидатися, що лист надіслано)
--
-- Виконати ОДИН раз у Supabase: Project → SQL Editor → New query,
-- вставити весь цей файл і натиснути Run.
--
-- ВАЖЛИВО про безпеку: за замовчуванням Supabase (і взагалі
-- будь-який нормальний сервіс автентифікації) НІКОЛИ не каже
-- анонімному відвідувачу, чи існує конкретний email в системі —
-- це захист від "email enumeration": зловмисник міг би перебором
-- дізнатися, які адреси зареєстровані на сайті, і потім
-- цілеспрямовано їх атакувати (підбір пароля, фішинг тощо).
--
-- Ця функція свідомо послаблює цей захист заради зручності
-- користувачів невеликого магазину: вона віддає РІВНО true/false
-- і нічого більше (жодних інших даних користувача), що є
-- розумним компромісом, але все одно теоретично дозволяє
-- перебором дізнатися список зареєстрованих email. Якщо це
-- колись стане критичним — просто видаліть цю функцію
-- (GRANT REVOKE нижче) і поверніть попередню поведінку.
-- ======================================

create or replace function public.email_exists(check_email text)
returns boolean
language sql
security definer
set search_path = public, auth
as $$
    select exists (
        select 1
        from auth.users
        where lower(email) = lower(check_email)
    );
$$;

-- дозволяємо викликати цю функцію навіть неавторизованим
-- відвідувачам (форма "Забули пароль?" працює до входу в акаунт)
grant execute on function public.email_exists(text) to anon, authenticated;
