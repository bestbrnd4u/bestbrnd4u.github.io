-- --------------------------------------
-- НАВІЩО
--
-- Google і Facebook Supabase вміє сам. Telegram — ні, а саме він тут
-- найпоширеніший: бот магазину вже приймає замовлення, і людина в
-- ньому вже є.
--
-- ЧОМУ ЧЕРЕЗ БОТА, А НЕ ЧЕРЕЗ ВІДЖЕТ TELEGRAM
--
-- Login Widget вимагає зареєструвати домен у BotFather. Домен один,
-- а в нас їх три: прод, дев і localhost. Тобто перевірити вхід можна
-- було б лише зламавши його на бойовому сайті.
--
-- Діплінк у бота (t.me/<bot>?start=login_<token>) такого обмеження не
-- має взагалі: бот один, а прийшли на нього хоч звідки.
--
-- ЩО ТУТ ЗБЕРІГАЄТЬСЯ
--
-- Одноразова спроба входу: випадковий токен, який сайт кладе в
-- посилання, і код із двох цифр, який сайт ПОКАЗУЄ людині.
--
-- НАВІЩО КОД, ЯКЩО Є ТОКЕН
--
-- Токен їде через Telegram — отже, його може надіслати хтось інший.
-- Класична атака: зловмисник відкриває вхід у себе, надсилає жертві
-- своє посилання, жертва тисне «Старт» — і зловмисник заходить у
-- кабінет ЯК ЖЕРТВА.
--
-- Тому бот не входить мовчки: він пише, на який сайт іде вхід, і
-- називає код. Той самий код видно на сайті — але лише тому, хто цей
-- вхід почав. Не збігається — людина бачить, що підтверджує чужий
-- вхід, і не тисне.
--
-- ЧОМУ ЖОДНОЇ ПОЛІТИКИ RLS
--
-- RLS увімкнено, політик немає — це не забутий крок, а «нікому, крім
-- service_role». Чужий рядок звідси = чужий вхід у кабінет.
-- --------------------------------------

create table if not exists public.telegram_logins (
    token        uuid primary key default gen_random_uuid(),
    -- Дві цифри, які показуються і на сайті, і в боті.
    code         text not null,
    created_at   timestamptz not null default now(),
    -- Заповнюються, коли людина підтвердила вхід у боті.
    confirmed_at timestamptz,
    telegram_id  bigint,
    first_name   text,
    last_name    text,
    username     text,
    -- Ставиться, коли за цією спробою вже видали сесію. Друга спроба
    -- за тим самим токеном нічого не дає.
    used_at      timestamptz
);


create index if not exists telegram_logins_created_idx
    on public.telegram_logins (created_at desc);


alter table public.telegram_logins enable row level security;


comment on table public.telegram_logins is
    'Одноразові спроби входу через Telegram. Читає й пише лише Edge Function (service_role).';

comment on column public.telegram_logins.code is
    'Дві цифри, які сайт показує людині, а бот називає в повідомленні. Захист від підсунутого чужого посилання.';
