-- --------------------------------------
-- НАВІЩО
--
-- На оформленні замовлення спосіб «Інша пошта» був давно, а в
-- кабінеті його не було: збережені адреси знали лише три способи
-- Нової пошти. Тобто покупець з Укрпоштою не міг зберегти свою
-- адресу взагалі й вписував її щоразу руками.
--
-- ЧОМУ ОКРЕМИЙ СТОВПЕЦЬ, А НЕ courier_address
--
-- Спокуса очевидна: там теж вільний рядок з адресою. Але це різні
-- речі. courier_address — вулиця й будинок, куди приїде кур'єр
-- Нової пошти; тут — назва чужого перевізника разом із його
-- відділенням. Злити їх в одне поле означає, що жоден код більше не
-- може сказати, кому саме везти: у картці адреси, в листі й у
-- повідомленні в Telegram вийшов би «Кур'єр» замість «Укрпошта».
--
-- ЧОМУ NULL — ЦЕ НОРМАЛЬНО
--
-- Порожньо в усіх адрес, збережених раніше: вони всі Новою поштою.
-- Сайт це враховує — assets/js/account.js читає поле через
-- ?? "" і не вимагає його наявності, тож порядок «спершу код, потім
-- міграція» нічого не ламає.
-- --------------------------------------

alter table public.addresses
    add column if not exists other_carrier text;


comment on column public.addresses.other_carrier is
    'Перевізник і відділення для способу «Інша пошта» (Укрпошта, Meest) одним рядком. NULL — адреса Нової пошти.';
