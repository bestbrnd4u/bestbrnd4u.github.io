-- --------------------------------------
-- НАВІЩО ЦЕ
--
-- У панелі накопичуються замовлення, яких там бути не повинно:
-- тестові (кожна перевірка оплати на проді лишає одне), дублі, коли
-- людина натиснула «Оформити» двічі, і відверте сміття від ботів.
-- Скасувати їх мало: скасоване замовлення — це теж подія, воно
-- лишається у вкладці «Скасовані» й далі плутається під ногами.
--
-- Видаляти одразу теж не діло: рядок замовлення — це запис про
-- продаж. Помилковий клік знищив би його разом із заявками на
-- відмову (order_refusals посилається сюди з on delete cascade), і
-- повернути можна було б хіба з резервної копії.
--
-- Тому два кроки. Спершу замовлення йде в архів — зникає з панелі,
-- але лишається в базі. І вже з архіву його можна або повернути, або
-- видалити назавжди.
--
-- ЩО АРХІВ НЕ ЧІПАЄ
--
-- Кабінет клієнта. Він читає свої замовлення сам, за власною
-- політикою RLS, і про цю колонку не знає: прибране з панелі
-- замовлення клієнт бачить, як бачив. Це навмисно — архів наводить
-- лад у власника, а не переписує історію покупця.
-- --------------------------------------

alter table public.orders
    add column if not exists archived_at timestamptz;


-- Вкладка «Архів» — єдине місце, яке шукає рядки з датою. Усі решта
-- вкладок питають протилежне (archived_at is null), і там індекс не
-- потрібен: таких рядків переважна більшість, і планувальник усе
-- одно піде послідовно.
create index if not exists orders_archived_idx
    on public.orders (archived_at desc)
    where archived_at is not null;


