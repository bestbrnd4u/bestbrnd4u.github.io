-- --------------------------------------
-- НАВІЩО
--
-- Питання вирішили — і розмова просто обривається. Для людини це
-- виглядає як «мене перестали читати»: останнє повідомлення висить,
-- поле вводу відкрите, і незрозуміло, чекати ще чи ні.
--
-- Тепер власник пише в Telegram /chatdone реплаєм, і в людини на
-- сайті розмова закривається по-доброму: «раді, що допомогли», а
-- замість поля вводу — кнопка «Почати нову розмову».
--
-- ЧОМУ ЗАКРИТТЯ, А НЕ ВИДАЛЕННЯ
--
-- Переписка лишається: власнику вона потрібна, щоб згадати, про що
-- домовлялись, а людині — щоб перечитати відповідь. Закриття лише
-- каже «цю розмову завершено», і наступне питання почне нову.
--
-- ЧОМУ ЦЕ НЕ ТЕ САМЕ, ЩО /chatblock
--
-- Блокування — проти настирливих: розмова мовчки перестає приймати
-- повідомлення, і людина про це не дізнається. Завершення —
-- навпаки, подія, яку ВИДНО, і після неї писати можна далі, просто
-- в новій розмові.
-- --------------------------------------

-- Коли завершили. NULL — розмова триває.
--
-- Саме час, а не boolean: інколи потрібно знати, коли це сталось —
-- наприклад, щоб не закривати повторно те, що закрили хвилину тому.
alter table public.chat_threads
    add column if not exists closed_at timestamptz;


comment on column public.chat_threads.closed_at is
    'Коли розмову завершили командою /chatdone. NULL — триває. Нове питання створює нову нитку, ця лишається для історії.';


-- --------------------------------------
-- ТРЕТІЙ АВТОР ПОВІДОМЛЕННЯ: system
--
-- Колонка author — text без обмежень, тож міграція тут нічого не
-- змінює; рядок лишається для того, хто читатиме схему й питатиме,
-- звідки взялось третє значення.
--
--   visitor — покупець
--   owner   — власник
--   system  — сам магазин: підсумок завершеної розмови
--
-- Окремий автор, а не owner, бо виглядати це має інакше: не
-- бульбашкою в листуванні, а підсумком під ним.
-- --------------------------------------

comment on column public.chat_messages.author is
    'visitor, owner або system. system — підсумок завершеної розмови, малюється не бульбашкою.';


