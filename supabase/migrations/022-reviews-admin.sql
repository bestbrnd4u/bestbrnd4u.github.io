-- --------------------------------------
-- 1. Яке повідомлення в Telegram показує цей відгук
--
-- ЩО БЕЗ ЦЬОГО НЕ ТАК
--
-- Відгуками тепер керують із двох місць: кнопками під карткою в
-- Telegram і панеллю в адмінці. Картка в чаті — звичайне
-- повідомлення: саме воно не оновлюється.
--
-- Тобто відхиливши відгук у панелі, власник лишив би в чаті картку з
-- живими кнопками «Показати на сайті» / «Відхилити». Натиснувши
-- котрусь через тиждень, він МОВЧКИ скасував би своє ж рішення — і в
-- чаті все виглядало б правильно.
--
-- Це рівно та сама пастка, яку для замовлень закрила міграція
-- 009-admin-orders.sql (колонка bot_message_id). Тут — те саме для
-- відгуків.
--
-- Колонки заповнюються самі, коли бот надсилає картку нового
-- відгуку. Відгукам, що вже лежать у базі, вони лишаться порожніми —
-- для них панель просто не перемалює картку, все інше працює.
-- --------------------------------------

alter table public.reviews
    add column if not exists owner_chat_id    bigint;

alter table public.reviews
    add column if not exists owner_message_id bigint;


-- --------------------------------------
-- 2. Хто й коли відмодерував
--
-- НАВІЩО. Модерація тепер із двох місць, і за місяць «чому цей відгук
-- відхилений» — питання без відповіді. Дата рішення відповідає на
-- половину таких питань, а джерело («telegram» / «admin») — на другу.
--
-- Це не аудит і не журнал: одне поле й одна дата, які видно в панелі
-- поруч із відгуком.
-- --------------------------------------

alter table public.reviews
    add column if not exists moderated_at timestamptz;

alter table public.reviews
    add column if not exists moderated_by text;


-- --------------------------------------
-- 3. Швидкий список для панелі
--
-- Панель гортає відгуки сторінками, від найновіших, і рахує, скільки
-- їх у кожній вкладці (нові / опубліковані / відхилені). Обидва
-- запити впираються в ті самі дві колонки.
--
-- Наявний reviews_product_idx для цього не годиться: у ньому першим
-- іде product_id, тож для вибірки «всі відгуки за датою» він не
-- працює.
-- --------------------------------------

create index if not exists reviews_created_at_idx
    on public.reviews (created_at desc);

create index if not exists reviews_status_created_idx
    on public.reviews (status, created_at desc);


-- --------------------------------------
-- 4. Перевірка
--
-- Має повернути чотири колонки й два індекси.
-- --------------------------------------

select 'колонка' as що, column_name as назва
from information_schema.columns
where table_schema = 'public'
  and table_name = 'reviews'
  and column_name in ('owner_chat_id', 'owner_message_id', 'moderated_at', 'moderated_by')

union all

select 'індекс' as що, indexname as назва
from pg_indexes
where schemaname = 'public'
  and indexname in ('reviews_created_at_idx', 'reviews_status_created_idx')

order by 1, 2;
