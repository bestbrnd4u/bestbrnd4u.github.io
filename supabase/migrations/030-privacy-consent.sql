-- --------------------------------------
-- НАВІЩО
--
-- У кабінеті з'явилась галочка «Я згоден на обробку персональних
-- даних» із посиланням на політику конфіденційності. Сама галочка без
-- запису нічого не варта: питання, на яке треба вміти відповісти, —
-- не «чи згоден», а «коли саме погодився».
--
-- Тому зберігаємо МОМЕНТ, а не прапорець. «Так» без дати не доводить
-- нічого: людина могла погодитись до того, як політику змінили.
--
-- ЧОМУ NULL — ЦЕ НОРМАЛЬНО
--
-- Порожньо = згоди ще не давали. Так і буде в усіх, хто зареєструвався
-- раніше: питати заднім числом нема як, а вигадувати їм дату — це
-- рівно те, від чого й захищає цей стовпець.
--
-- Сайт це враховує: якщо стовпця ще немає (міграцію не застосували),
-- assets/js/account.js просто не пише його — див. loadProfile(), де
-- наявність ключа в рядку і є перевіркою. Тому порядок «спершу код,
-- потім міграція» нічого не ламає.
-- --------------------------------------

alter table public.profiles
    add column if not exists privacy_consent_at timestamptz;


comment on column public.profiles.privacy_consent_at is
    'Коли користувач підтвердив згоду на обробку персональних даних у кабінеті. NULL — згоди ще не давали.';
