-- --------------------------------------
-- Чи вже враховане це замовлення в залишках
--
-- НАВІЩО
--
-- Залишки лежать не в базі, а в репозиторії (data/products/*.json) —
-- там їх редагує адмінка, звідти їх бере збірка сайту. Списує їх
-- окремий крок (scripts/apply-order-stock.js), який запускається за
-- розкладом: бере замовлення, яких ще не врахував, і зменшує залишки.
--
-- Цей прапорець — уся його памʼять. Без нього крок або списував би
-- одне й те саме замовлення щоразу, або мусив би тримати «останній
-- оброблений номер», а такий лічильник ламається від будь-якого
-- замовлення, що приїхало із запізненням.
--
-- ЩО ЦЕ ДАЄ ЩЕ
--
-- Скасування. Клієнт передумав — товар повертається на полицю: крок
-- бачить «замовлення скасоване, але залишок списаний» і повертає його
-- назад, знімаючи прапорець. Якщо скасування скасують (у панелі
-- адмінки таке можна), товар спишеться знову.
--
-- Тобто прапорець відповідає не на «чи оброблено», а на «чи зайняті
-- зараз ці одиниці товару цим замовленням».
-- --------------------------------------

alter table public.orders
    add column if not exists stock_applied boolean not null default false;


-- Крок питає базу так: «дай замовлення, де прапорець не збігається з
-- очікуваним». Індекс маленький і робить цю вибірку миттєвою навіть
-- тоді, коли замовлень стане тисячі.
create index if not exists orders_stock_applied_idx
    on public.orders (stock_applied);


-- --------------------------------------
-- Перевірка
--
-- Має повернути один рядок: stock_applied | boolean | false
-- --------------------------------------

select column_name as колонка, data_type as тип, column_default as за_замовчуванням
from information_schema.columns
where table_schema = 'public'
  and table_name = 'orders'
  and column_name = 'stock_applied';
