-- --------------------------------------
-- ЩО БУЛО НЕ ТАК
--
-- У панелі «Люди» є «Видалити покупця». У коді функції поруч стоїть
-- коментар «ЗАМОВЛЕННЯ НЕ ЧІПАЄМО — і це навмисно»: видаляються
-- профіль, адреси, обране й сам обліковий запис.
--
-- Насправді замовлення зникали разом з акаунтом, і робила це база, а
-- не функція. У orders-schema.sql стоїть:
--
--     user_id uuid references auth.users(id) ON DELETE CASCADE
--
-- Тобто видалення рядка з auth.users зносило всі замовлення цієї
-- людини. Мовчки: функція відповідала «готово», у панелі все
-- виглядало правильно, а замовлень більше не існувало. Разом із ними
-- зникали й заявки на відмову (order_refusals посилається на orders
-- теж із cascade).
--
-- Помітили це аж тоді, коли людина зареєструвалась наново й побачила
-- порожню історію — але порожньою вона була вже давно.
--
-- ЩО МІНЯЄМО
--
-- ON DELETE CASCADE → ON DELETE SET NULL. Видалення акаунта тепер
-- лишає замовлення на місці, просто без власника: рівно те саме, що
-- гостьове замовлення. Ім'я, телефон, пошта, склад і суми в рядку
-- свої, тож замовлення лишається повноцінним — і його можна знайти,
-- показати в панелі й повернути людині, коли вона зареєструється
-- знову (маршрут claim-orders).
--
-- ЧОМУ ТІЛЬКИ ЗАМОВЛЕННЯ
--
-- profiles, addresses, favorites і cart теж каскадні — і хай такими
-- лишаються. Це дані САМОГО акаунта: без акаунта вони не значать
-- нічого й нікому не потрібні. Замовлення інше: це запис про продаж.
-- Він потрібен для обліку, для гарантії й для самої людини — за
-- номером замовлення її знайдуть, навіть коли кабінету вже немає.
--
-- ⚠️ ЩО ЦЯ МІГРАЦІЯ НЕ ПОВЕРТАЄ
--
-- Замовлення, знищені раніше. Їх немає в базі, і відновити їх можна
-- лише з резервної копії. Міграція припиняє втрату, а не відкочує її.
-- --------------------------------------

do $$
declare
    fk_name text;
begin

    -- Ім'я обмеження за замовчуванням — orders_user_id_fkey, але
    -- покладатись на це не варто: таблицю могли створити інакше.
    -- Тому шукаємо саме зовнішній ключ по колонці user_id.
    select con.conname
      into fk_name
      from pg_constraint con
      join pg_attribute att
        on att.attrelid = con.conrelid
       and att.attnum = con.conkey[1]
     where con.conrelid = 'public.orders'::regclass
       and con.contype = 'f'
       and array_length(con.conkey, 1) = 1
       and att.attname = 'user_id';

    if fk_name is not null then
        execute format('alter table public.orders drop constraint %I', fk_name);
    end if;

end $$;


alter table public.orders
    add constraint orders_user_id_fkey
    foreign key (user_id) references auth.users(id)
    on delete set null;


-- --------------------------------------
-- ПОШУК ЗАМОВЛЕНЬ БЕЗ ВЛАСНИКА
--
-- Коли людина реєструється, функція шукає гостьові замовлення з її
-- поштою, щоб повернути їх у кабінет. Без індексу це щоразу повний
-- перебір таблиці — на кожну реєстрацію.
--
-- Індекс частковий: рядки з власником у цьому пошуку не беруть
-- участі взагалі, і тримати їх в індексі нема сенсу. Пошта
-- порівнюється без урахування регістру — «Ilya@» і «ilya@» це та
-- сама скринька.
-- --------------------------------------

create index if not exists orders_guest_email_idx
    on public.orders (lower(email))
    where user_id is null and email is not null;


-- --------------------------------------
-- ТЕЛЕФОН: КЛЮЧ ПОРІВНЯННЯ ОКРЕМОЮ КОЛОНКОЮ
--
-- У базі лежить те, що людина набрала в оформленні: place-order.js
-- лише обрізає рядок до 40 символів, не чіпаючи вмісту. Той самий
-- номер тому трапляється щонайменше в чотирьох виглядах:
--
--     +380 73 728 82 91    0737288291    380737288291    73 728 82 91
--
-- Шукати за таким полем «схоже на 737288291» безглуздо: у першому
-- варіанті між цифрами стоять пробіли, і жоден ilike його не знайде.
--
-- Тому ключ рахує сама база — останні дев'ять цифр, тобто номер
-- абонента без коду країни й міжміського нуля. Це рівно те саме
-- правило, що в order-lookup.js (phoneKey) на сторінці «Де моє
-- замовлення»: коротше брати не можна, бо 6-7 цифр почали б
-- випадково збігатися в різних людей.
--
-- Колонка ГЕНЕРОВАНА: її не можна записати ззовні й вона не може
-- розійтися з phone. Індекс частковий — шукаємо лише серед
-- замовлень без власника.
-- --------------------------------------

alter table public.orders
    add column if not exists phone_key text
    generated always as (
        right(regexp_replace(coalesce(phone, ''), '\D', '', 'g'), 9)
    ) stored;


create index if not exists orders_guest_phone_idx
    on public.orders (phone_key)
    where user_id is null;
