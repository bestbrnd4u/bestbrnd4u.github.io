-- --------------------------------------
-- ЩО ЦЕ ДАЄ
--
-- Наявність на сайті бралась із зібраного каталогу, а він
-- перезбирається раз на десять хвилин. Тобто картка могла обіцяти
-- «в наявності» товар, якого вже немає: захист від подвійного продажу
-- (011) не давав продати його двічі, але покупець дізнавався про це
-- вже від власника.
--
-- Тепер сайт питає базу — і бачить те саме, що бачить перевірка при
-- створенні замовлення.
--
-- ЧОМУ ФУНКЦІЯ, А НЕ ДОСТУП ДО ТАБЛИЦІ
--
-- Таблиця залишків закрита від клієнта (у неї немає політик), і
-- відкривати її не варто: у ній лежать ЧИСЛА. Скільки саме одиниць
-- кожного товару на полиці — це відомості про оберти магазину, і
-- сайт їх ніде не показує.
--
-- Тому функція віддає лише «так/ні». Це рівно те, що сайт і малює:
-- «в наявності» або «під замовлення». Більше знати браузеру ні до
-- чого.
--
-- ЧОМУ БЕЗ ПАРАМЕТРІВ
--
-- Рядків усього десятки — весь перелік важить кілька кілобайт. Список
-- id у запиті означав би або окремий запит на кожну картку, або
-- адресу на кілометр, і при цьому нічого не економив би.
-- --------------------------------------

create or replace function public.stock_live()
returns table (
    product_id bigint,
    color      text,
    size       text,
    available  boolean
)
language sql
-- security definer: таблиця залишків і замовлення закриті від
-- клієнта, а відповісти на «чи є в наявності» треба саме йому.
-- Функція не приймає параметрів, тож підставити в неї щось чуже
-- неможливо за побудовою.
security definer
-- Пін search_path обов'язковий для security definer: без нього
-- виклик можна збити підміною схеми.
set search_path = public
stable
as $$
    select s.product_id,
           s.color,
           s.size,
           (s.qty - public.stock_reserved(s.product_id, s.color, s.size)) > 0
    from public.stock s;
$$;

-- Читати може будь-хто, включно з неавторизованим відвідувачем: це
-- та сама наявність, яку він бачить на картці.
grant execute on function public.stock_live() to anon, authenticated;


