-- Компактний діалог: редагуємо одне повідомлення замість
-- надсилання нового на кожному кроці
--
-- Виконати один раз у Supabase → SQL Editor.
-- Повторний запуск безпечний.
-- ======================================

-- Щоб редагувати повідомлення, треба знати його id. Без цього бот
-- на кожен крок надсилає НОВЕ повідомлення: чат швидко росте, а
-- клієнту доводиться прокручувати його вручну, щоб побачити
-- наступне питання.
alter table public.bot_sessions
    add column if not exists message_id bigint;
