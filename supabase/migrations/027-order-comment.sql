-- --------------------------------------
-- НАВІЩО
--
-- У формі оформлення було десять полів і жодного, куди покупець міг
-- би написати те, що не влазить у поля:
--
--   «подзвоніть перед відправкою»
--   «це подарунок — не кладіть чек у коробку»
--   «мене не буде до п'ятниці, відправте в понеділок»
--   «якщо цього кольору немає — беру чорний»
--
-- Усе це зараз іде в Instagram чи Telegram окремим повідомленням, і
-- магазин звіряє його із замовленням руками. Тобто найризикованіша
-- частина замовлення — та, де є прохання, — живе не в замовленні.
--
-- ЧОМУ ПРОСТО ТЕКСТ, А НЕ ПЕРЕЛІК ГАЛОЧОК
--
-- Галочки («подарункова упаковка», «подзвонити перед доставкою»)
-- вгадують лише те, про що вже здогадались. Поле для тексту приймає
-- і те, чого ніхто не передбачив, — а таких прохань більшість.
-- --------------------------------------

alter table public.orders
    add column if not exists comment text;


-- --------------------------------------
-- ПЕРЕВІРКА
--
-- Має повернути 1.
-- --------------------------------------

select count(*) as колонка
  from information_schema.columns
 where table_schema = 'public'
   and table_name = 'orders'
   and column_name = 'comment';
