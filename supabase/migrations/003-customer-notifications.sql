-- ======================================
-- Сповіщення клієнту про статус + номер ТТН
--
-- Виконати один раз у Supabase → SQL Editor.
-- Повторний запуск безпечний.
-- ======================================


-- --------------------------------------
-- 1. Куди писати клієнту
--
-- Замовлення з бота знають чат клієнта — саме туди підуть сповіщення
-- про зміну статусу. Замовлення з сайту цього поля не мають (там
-- Telegram не задіяний), і для них сповіщення просто не надсилаються.
-- --------------------------------------

alter table public.orders
    add column if not exists telegram_chat_id bigint;


-- --------------------------------------
-- 2. Номер накладної
--
-- Ви вводите його в Telegram після натискання «Відправлено», і клієнт
-- одразу отримує його разом із посиланням на відстеження.
-- --------------------------------------

alter table public.orders
    add column if not exists tracking_number text;


-- --------------------------------------
-- 3. Стан «чекаю на ТТН»
--
-- Коли ви тиснете «Відправлено», бот питає номер накладної. Треба
-- пам'ятати, до якого саме замовлення стосується ваша наступна
-- відповідь — інакше номер прив'яжеться навмання.
--
-- Використовуємо ту саму таблицю чернеток: окрема таблиця заради
-- одного поля була б зайвою.
-- --------------------------------------

-- bigint, а НЕ uuid: тут лежить id замовлення, а public.orders.id —
-- bigint (див. supabase/orders-schema.sql).
--
-- У першій версії цієї міграції стояв uuid. Якщо ви вже її виконали,
-- колонка створилась з неправильним типом і кнопка «Додати ТТН» не
-- працювала б: збереження id замовлення падало б на невідповідності
-- типів. Тому спершу прибираємо стару колонку — у ній лежить лише
-- тимчасовий стан діалогу, втрачати нічого.
alter table public.bot_sessions
    drop column if exists awaiting_ttn_for;

alter table public.bot_sessions
    add column if not exists awaiting_ttn_for bigint;


