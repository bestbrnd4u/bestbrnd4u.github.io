-- --------------------------------------
-- НАВІЩО
--
-- Надіслати код на довільний номер безкоштовно не можна ні в кого:
-- платне саме телеком-плече — і SMS, і flash-дзвінок, і Viber через
-- партнера, і Telegram Gateway ($0.01 за код).
--
-- Тому напрямок перевернуто. Не ми стукаємо на номер, а людина сама
-- віддає його з Telegram кнопкою «Поділитися номером». Номер
-- надсилає клієнт Telegram, а не рука на клавіатурі, — і це
-- безкоштовно й без лімітів.
--
-- ОДНА ДЕТАЛЬ, БЕЗ ЯКОЇ ЦЕ НЕ ПЕРЕВІРКА
--
-- Боту можна переслати ЧУЖИЙ контакт. Тому перевіряємо, що
-- contact.user_id збігається з from.id того, хто натиснув: інакше в
-- базу ліг би номер друга й виглядав би підтвердженим.
-- Перевірка живе в telegram-login.js, sharedPhone().
--
-- ЩО ДОДАЄТЬСЯ ТУТ
--
-- phone   — номер, поки він ще не доїхав у профіль;
-- user_id — кому саме його записати.
--
-- ЧОМУ ДВА СТОВПЦІ, А НЕ ОДИН
--
-- Порядок дій людини непередбачуваний. Вона може поділитися номером
-- ДО того, як сайт устиг відкрити сесію, — тоді записувати нема
-- кому, і номер чекає в phone. А може після — тоді в рядку вже
-- лежить user_id, і бот пише в профіль одразу.
--
-- Обидва шляхи сходяться в одному місці й не залежать від того, хто
-- був перший.
-- --------------------------------------

alter table public.telegram_logins
    add column if not exists phone text;

alter table public.telegram_logins
    add column if not exists user_id uuid;


comment on column public.telegram_logins.phone is
    'Номер, надісланий кнопкою «Поділитися номером» у боті. Перевірено, що контакт належить самому відправнику.';

comment on column public.telegram_logins.user_id is
    'Користувач Supabase, якому належить ця спроба входу. Ставиться, коли сайт відкрив сесію.';
