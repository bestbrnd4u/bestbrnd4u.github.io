-- --------------------------------------
-- НАВІЩО
--
-- stock_live() — ЄДИНИЙ запит до бази, який робить кожен відвідувач
-- сайту. Він питається на сторінці товару, у каталозі, у «схожих» —
-- скрізь, де показано наявність (158 сторінок), і повторюється раз на
-- хвилину перегляду (CACHE_MS у assets/js/live-stock.js).
--
-- Тобто це найгарячіший запит магазину. А написаний він був так:
--
--     select s.product_id, s.color, s.size,
--            (s.qty - public.stock_reserved(s.product_id, s.color, s.size)) > 0
--     from public.stock s;
--
-- stock_reserved() для КОЖНОГО рядка залишку заново перебирає всі
-- незакриті замовлення й розкладає їхній JSON-масив items. Сьогодні в
-- таблиці stock 91 рядок — отже, 91 перебір замовлень на один виклик.
--
-- Заміряно на проді 19.10.2026: 96 / 136 / 725 мс (мін / медіана /
-- макс) при 91 рядку й кількох відкритих замовленнях. Для запиту, що
-- читає 91 рядок, це на два порядки більше, ніж треба.
--
-- ЯК ЦЕ РОСТЕ
--
-- Вартість = (рядків у stock) × (позицій у незакритих замовленнях).
-- Обидва множники ростуть разом із магазином:
--
--     103 товари,  91 рядок, 10 позицій у роботі  →      910 порівнянь
--     500 товарів, ~450 рядків, 50 позицій        →   22 500
--    1000 товарів, ~900 рядків, 100 позицій       →   90 000
--
-- І все це — на кожного відвідувача щохвилини. Тобто першим від
-- зростання асортименту й трафіку ламається не хостинг і не канал, а
-- саме цей запит.
--
-- ЩО ЗМІНЮЄТЬСЯ
--
-- Замовлення розкладаються ОДИН раз, згортаються в «скільки зайнято
-- по кожній комірці», і цей невеликий набір приєднується до залишку.
-- Вартість стає (рядків у stock) + (позицій у замовленнях) замість
-- їхнього добутку.
--
-- Частковий індекс orders_stock_pending_idx (міграція 011) тепер
-- використовується один раз на виклик, а не 91.
--
-- ЩО НЕ ЗМІНЮЄТЬСЯ
--
-- Відповідь. Ті самі колонки, ті самі рядки, те саме значення
-- available. Набір правил рахунку теж той самий, слово в слово:
-- не списані (stock_applied = false), не скасовані, не раніше дати
-- відліку. Дата мусить збігатися зі STOCK_SINCE у
-- scripts/apply-order-stock.js — за цим стежить tests/test-oversell.js,
-- і тепер він звіряє ВСІ міграції, де ця дата згадана, а не одну.
--
-- stock_reserved() лишається як була: її викликає тригер
-- orders_flag_stock_shortfall на кожне замовлення, і там вона
-- рахує одну комірку, а не всі — тобто саме те, для чого годиться.
-- --------------------------------------

create or replace function public.stock_live()
returns table (
    product_id bigint,
    color      text,
    size       text,
    available  boolean
)
language sql
-- security definer: таблиця залишків і замовлення закриті від
-- клієнта, а відповісти на «чи є в наявності» треба саме йому.
-- Функція не приймає параметрів, тож підставити в неї щось чуже
-- неможливо за побудовою.
security definer
-- Пін search_path обов'язковий для security definer: без нього
-- виклик можна збити підміною схеми.
set search_path = public
stable
as $$
    with reserved as (
        select
            -- id лишається ТЕКСТОМ, без приведення до bigint.
            --
            -- Так само, як робила stock_reserved: вона порівнювала
            -- (i->>'id') = p_id::text. Приведення JSON-значення до
            -- числа впало б на першому ж замовленні, де в items
            -- опинився нечисловий id, — і живий залишок зник би
            -- одразу з усього сайту, бо запит той самий для всіх.
            (i->>'id')                     as product_key,
            coalesce(i->>'color', '')      as color,
            coalesce(i->>'size',  '')      as size,

            -- Кількість: щонайменше одиниця.
            --
            -- CASE перед приведенням — з тієї ж причини. У старому
            -- вигляді (i->>'qty')::int рахувався лише для комірки, що
            -- збіглася, тож зіпсоване значення в чужій позиції могло
            -- лежати роками непоміченим. Тут один прохід по ВСІХ
            -- позиціях, і таке значення поклало б функцію цілком.
            -- Нечислове читаємо як одиницю — рівно те, що й так
            -- робив coalesce(..., 1).
            sum(greatest(coalesce(
                case when (i->>'qty') ~ '^[0-9]+$' then (i->>'qty')::int end,
                1), 1))::int               as qty

        from public.orders o
        cross join lateral jsonb_array_elements(
            case jsonb_typeof(o.items) when 'array' then o.items else '[]'::jsonb end
        ) as i
        where o.stock_applied = false
          and coalesce(o.status, 'new') <> 'cancelled'
          -- ⚠ МУСИТЬ ЗБІГАТИСЯ зі STOCK_SINCE у scripts/apply-order-stock.js
          and o.created_at >= timestamptz '2026-09-05T17:35:47Z'
        group by 1, 2, 3
    )
    select s.product_id,
           s.color,
           s.size,
           (s.qty - coalesce(r.qty, 0)) > 0
    from public.stock s
    -- Звичайна рівність, без coalesce на боці залишку: color і size в
    -- public.stock оголошені not null default '', тож NULL там узятись
    -- нема звідки, а зайвий coalesce лише заважав би планувальнику
    -- скористатись первинним ключем.
    left join reserved r
           on r.product_key = s.product_id::text
          and r.color       = s.color
          and r.size        = s.size;
$$;

-- Читати може будь-хто, включно з неавторизованим відвідувачем: це
-- та сама наявність, яку він бачить на картці. (create or replace
-- права не скидає, але повторюємо явно — щоб файл був самодостатнім
-- і його можна було накотити на чисту базу.)
grant execute on function public.stock_live() to anon, authenticated;


