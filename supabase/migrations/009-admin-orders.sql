-- ======================================
-- Панель «Замовлення» в адмінці
--
-- Виконати ОДИН раз у Supabase → SQL Editor → New query: вставити
-- весь файл і натиснути Run. Повторний запуск безпечний.
--
-- Плейсхолдерів тут немає — нічого замінювати не треба.
-- ======================================


-- --------------------------------------
-- 1. Яке повідомлення в Telegram показує це замовлення
--
-- ЩО БЕЗ ЦЬОГО НЕ ТАК
--
-- Замовленнями тепер керують із двох місць: кнопками під карткою в
-- Telegram і панеллю в адмінці. Картка в чаті — це звичайне
-- повідомлення: воно не оновлюється саме.
--
-- Тобто після зміни статусу з панелі в чаті лишався б попередній
-- статус. І це не лише про красу: кнопки під карткою теж лишились би
-- від старого статусу. Натиснувши «В обробці» під уже відправленим
-- замовленням, власник МОВЧКИ відкотив би зміну назад — і в чаті все
-- виглядало б правильно.
--
-- Тому бот запам'ятовує номер повідомлення з карткою, а панель
-- перемальовує саме його — так само, як це робить натискання кнопки.
--
-- Колонка заповнюється сама: при новому замовленні й щоразу, коли
-- картку відкривають зі списку /orders або тиснуть під нею кнопку.
-- Старим замовленням вона лишиться порожньою — для них панель просто
-- не перемалює картку, все інше працює.
-- --------------------------------------

alter table public.orders
    add column if not exists bot_message_id bigint;


-- --------------------------------------
-- 2. Швидкий список
--
-- Панель гортає замовлення сторінками по 25, від найновіших, і
-- рахує, скільки їх у кожній вкладці. Обидва запити впираються в ті
-- самі дві колонки.
--
-- Індекс за user_id уже є (orders_user_id_created_at_idx з
-- orders-schema.sql), але він для кабінету клієнта: у ньому першим
-- іде user_id, тож для вибірки «всі замовлення за датою» він не
-- годиться.
-- --------------------------------------

create index if not exists orders_created_at_idx
    on public.orders (created_at desc);

create index if not exists orders_status_idx
    on public.orders (status);


-- --------------------------------------
-- 3. Перевірка
--
-- Має повернути три рядки: bot_message_id і два індекси.
-- --------------------------------------

select 'колонка' as що, column_name as назва
from information_schema.columns
where table_schema = 'public'
  and table_name = 'orders'
  and column_name = 'bot_message_id'

union all

select 'індекс', indexname
from pg_indexes
where schemaname = 'public'
  and tablename = 'orders'
  and indexname in ('orders_created_at_idx', 'orders_status_idx');
