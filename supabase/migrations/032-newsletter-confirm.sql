-- --------------------------------------
-- НАВІЩО
--
-- Лист підтвердження підписки надсилав MailerLite. Він приходив
-- АНГЛІЙСЬКОЮ — «Confirm your email address» — і відредагувати його
-- на безкоштовному тарифі не можна: у панелі кнопка «Редагувати»
-- закрита підказкою «доступно лише в платних тарифах».
--
-- Людина щойно залишила пошту українському магазину, а отримує лист
-- чужою мовою від назви, яку бачила вперше. Такі не відкривають.
-- А без відкриття підписка лишається в стані «unconfirmed» назавжди:
-- у списку є, листів не отримує.
--
-- Решта листів магазину — про замовлення, про статус, прохання про
-- відгук, подяка з промокодом — збираються в mail.js і йдуть через
-- Resend або Brevo. Лист підтвердження був єдиним, який із цього
-- правила випав. Тепер не випадає.
--
-- ЩО ТУТ ЗБЕРІГАЄТЬСЯ
--
-- Одноразове посилання: випадковий токен, пошта, коли створено й
-- коли підтверджено. Токен у посиланні — єдине, що доводить доступ
-- до скриньки; саме тому він і мусить бути непередбачуваним, а не
-- порядковим номером.
--
-- ЧОМУ ЗБЕРІГАЄТЬСЯ САМЕ МОМЕНТ ПІДТВЕРДЖЕННЯ
--
-- Та сама причина, що й у privacy_consent_at (міграція 030):
-- питання, на яке треба вміти відповісти, — не «чи погодився», а
-- «коли саме». Згода на рекламну розсилку без дати не доводить
-- нічого, а саме її й вимагають, коли приходить скарга на спам.
--
-- ЧОМУ ЖОДНОЇ ПОЛІТИКИ RLS
--
-- RLS увімкнено, політик немає — це НЕ забутий крок. Означає воно
-- «нікому, крім service_role», а service_role є тільки у функції.
-- Тобто з браузера цю таблицю не прочитати взагалі: список чужих
-- токенів — це список чужих підписок, які можна підтвердити за
-- людину.
-- --------------------------------------

create table if not exists public.newsletter_confirmations (
    token        uuid primary key default gen_random_uuid(),
    email        text not null,
    created_at   timestamptz not null default now(),
    confirmed_at timestamptz
);


-- Пошук іде за поштою: перед надсиланням нового листа функція
-- дивиться, чи не надсилала вона його щойно.
create index if not exists newsletter_confirmations_email_idx
    on public.newsletter_confirmations (email, created_at desc);


alter table public.newsletter_confirmations enable row level security;


comment on table public.newsletter_confirmations is
    'Одноразові посилання для підтвердження підписки на розсилку. Читає й пише лише Edge Function (service_role).';

comment on column public.newsletter_confirmations.confirmed_at is
    'Коли людина перейшла за посиланням із листа. NULL — ще не підтверджено.';
