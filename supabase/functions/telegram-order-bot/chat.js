// Чат на сайті: покупець пише в панелі, власник відповідає з Telegram.
//
// ЧОГО ТУТ НЕМА
// --------------
// Мережі й бази. Лише чисті функції — щоб перевірялись тестами в Node.

// Скільки знаків беремо. Не обмеження для людини, а стеля здорового
// глузду: Telegram усе одно ріже повідомлення на 4096, а все, що
// довше за тисячу, — це не питання до магазину.
export const CHAT_LIMITS = {
    body: 1000,
    page: 200,
    agent: 300,
    // Скільки повідомлень віддаємо сайту за раз. Довша розмова
    // догортається запитом зі since.
    batch: 50
};

// Хто написав.
//
//   visitor — покупець
//   owner   — власник
//   system  — сам магазин: підсумок завершеної розмови
//
// system окремо від owner навмисно: виглядати це має не бульбашкою в
// листуванні, а підсумком під ним.
export const CHAT_AUTHORS = ["visitor", "owner", "system"];

// ПІДСУМОК ЗАВЕРШЕНОЇ РОЗМОВИ.
//
// Текст тут, а не в коді функції, бо його читатимуть люди і міняти
// його буде власник, а не програміст.
//
// Чого в ньому немає навмисно: «дякуємо за звернення» і «ваша думка
// важлива». Це мова кол-центру, а тут розмова двох людей.
export const CHAT_DONE_TEXT =
    "Раді, що змогли допомогти. Якщо виникне нове питання — "
    + "почніть нову розмову, ми на звʼязку.";

// Те, що бачить власник у Telegram після /chatdone.
//
// Кого саме завершили — у першому ж рядку: у переписці з десятком
// розмов «розмову завершено» не каже нічого.
export function chatDoneReceipt(text, who) {

    const кого = String(who ?? "").trim();

    // ОКРЕМИМ РЯДКОМ, А НЕ ВСЕРЕДИНІ РЕЧЕННЯ.
    //
    // «Розмову з Гість #7 завершено» — не українською: потрібен
    // орудний відмінок, «з гостем сьомим». А для імені з профілю це
    // взагалі нерозв'язно: «з Олена Коваль» неправильно, а відміняти
    // чуже ім'я програмно не можна — вийде «з Олегом Кучма».
    //
    // Тому підпис стоїть окремим рядком, тим самим, що в картці.
    return [
        "✅ Розмову завершено.",
        кого ? `👤 ${кого}` : "",
        "",
        "Людина побачила на сайті:",
        `«${String(text ?? "")}»`,
        "",
        "Переписка нікуди не зникла. Нове питання почне нову розмову.",
    ].filter((рядок, i) => рядок !== "" || i > 1).join("\n");

}

// Те, що бачить власник у Telegram після /chatclear.
//
// ЧОМУ ЦЕ ОКРЕМА КОМАНДА, А НЕ ЧАСТИНА /chatdone.
//
// Завершення — подія для ЛЮДИНИ: вона бачить підсумок і може почати
// нову розмову. Очищення — дія з ДАНИМИ: переписки більше немає
// ніде. Злити їх в одну команду означало б, що власник не може
// завершити розмову, не стерши її, — а підсумок якраз і має
// лишитись перед очима.
//
// Скільки саме стерто — у квитанції навмисно: «очищено» без числа не
// відрізняє «стерло двадцять повідомлень» від «не знайшло нічого».
export function chatClearReceipt(who, count) {

    const кого = String(who ?? "").trim();

    const скільки = Number(count) || 0;

    return [
        "🧹 Переписку стерто.",
        кого ? `👤 ${кого}` : "",
        "",
        `Прибрано повідомлень: ${скільки}.`,
        "У людини чат став порожній — так, ніби вона щойно зайшла.",
        "",
        "Відновити нічим: ні в боті, ні в базі цієї розмови більше немає.",
    ].filter((рядок, i) => рядок !== "" || i > 1).join("\n");

}

// Текст повідомлення від відвідувача.
//
// Порожнє (і «самі пробіли») відкидаємо: такі надсилає не людина, а
// випадковий Enter, і в Telegram вони виглядають як збій бота.
export function cleanChatBody(raw) {

    const value = String(raw ?? "")
        // Невидимі керівні символи прибираємо всі, крім переносу
        // рядка: вставлене з месенджера часто тягне їх за собою, а в
        // Telegram вони ламають розмітку.
        .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "")
        .replace(/\r\n?/g, "\n")
        .trim();

    if (!value) return null;

    return value.slice(0, CHAT_LIMITS.body);

}

// Токен нитки. Приймаємо тільки те, що справді схоже на uuid: усе
// інше пішло б у запит до бази як є.
export function cleanThreadId(raw) {

    const value = String(raw ?? "").trim().toLowerCase();

    return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(value)
        ? value
        : null;

}

// Сторінка, з якої написали. Те саме правило, що в зворотному
// дзвінку: тільки свій відносний шлях, бо це поле приходить від
// клієнта, а потрапляє в повідомлення власнику.
export function cleanChatPage(raw) {

    const value = String(raw ?? "");

    if (!value.startsWith("/")) return "";

    if (value.startsWith("//")) return "";

    if (value.length > CHAT_LIMITS.page) return "";

    return /^\/[\w\-./?&=%+]*$/.test(value) ? value : "";

}

// ХТО ПИШЕ.
//
// Імʼя з метаданих користувача. Ключі різні в різних провайдерів, і
// перебір тут ТОЙ САМИЙ, що в namesFromMetadata() у assets/js/account.js:
// given_name/family_name дає Google, first_name/last_name — вхід через
// Telegram, full_name і name трапляються в обох.
//
// Копія свідома: ця функція живе в боті, той файл — у браузері, і
// спільного модуля між ними немає. Тест звіряє, що переліки ключів не
// розійшлись.
export function chatUserName(user) {

    const meta = (user && user.user_metadata) || {};

    const first = String(meta.given_name || meta.first_name || "").trim();
    const last = String(meta.family_name || meta.last_name || "").trim();

    if (first || last) return [first, last].filter(Boolean).join(" ");

    return String(meta.full_name || meta.name || "").trim();

}

// Рядок, яким картка підписана в Telegram.
//
// Гість — номер: короткий, його можна вимовити («відповідаю гостю
// сім») і видно, хто прийшов раніше. Шматок uuid цього не дає.
//
// Той, хто увійшов, — імʼя й пошта. Якщо імені в профілі немає,
// лишається сама пошта: вона є завжди й розрізняє людей не гірше.
export function chatWho(thread) {

    const t = thread || {};

    const name = String(t.user_name || "").trim();
    const email = String(t.user_email || "").trim();

    if (name && email) return `${name} · ${email}`;
    if (email) return email;
    if (name) return name;

    return t.thread_no ? `Гість #${t.thread_no}` : "Гість";

}

// Картка для власника в Telegram.
//
// escape — функція екранування, яку передає викликач (у зібраному
// файлі це escapeHtml). Тягнути її сюди імпортом означало б другу
// копію того самого.
export function formatChatMessage(message, thread, escape) {

    const esc = typeof escape === "function" ? escape : (v) => String(v ?? "");

    const перше = thread && thread.first === true;

    // ПОРОЖНІ РЯДКИ ТУТ СПРАВЖНІ, А НЕ ПРИКРАСА.
    //
    // Раніше весь список проганявся через .filter(Boolean) — він
    // потрібен, щоб прибрати рядок «Сторінка», коли сторінки немає.
    // Але заразом він викидав і порожні рядки-роздільники, тож
    // картка злипалась в суцільний стовпчик: заголовок, підпис, текст
    // питання й службова примітка однаково щільно.
    //
    // Тепер фільтр діє лише на хвіст, де він і потрібен.
    const шапка = [
        перше ? "💬 <b>Нове питання з сайту</b>" : "💬 <b>Питання з сайту</b>",
        // ХТО ПИШЕ — ДРУГИМ РЯДКОМ, НА КОЖНІЙ КАРТЦІ.
        //
        // Не лише на першій: власник гортає переписку й має бачити
        // біля кожної репліки, чия вона. Коли пишуть двоє одночасно,
        // без цього рядка відповідь летить не тому.
        `👤 <b>${esc(chatWho(thread))}</b>`,
    ];

    const хвіст = [
        thread && thread.page ? `Сторінка: ${esc(thread.page)}` : "",
        "↩️ Відповідайте <b>реплаєм на це повідомлення</b> — відповідь зʼявиться в людини на сайті."
    ].filter(Boolean);

    return шапка.join("\n") + "\n\n" + esc(message) + "\n\n" + хвіст.join("\n");

}

// ЧИ ЗАРАЗ РОБОЧИЙ ЧАС.
//
// Потрібно не боту, а сайту: панель має сказати правду одразу.
// «Відповімо за хвилину» о другій ночі — це обіцянка, якої ніхто не
// виконає, і людина піде ображеною замість того, щоб спокійно
// дочекатись ранку.
//
// Години ті самі, що на сторінці контактів: Пн–Нд 09:00–20:00.
export const CHAT_HOURS = { from: 9, to: 20 };

// kyivHour — година за Києвом (0..23). Передається ззовні, бо
// рахується вона по-різному: у браузері через Intl, на сервері
// через timestamptz. Тут — лише саме правило.
export function withinWorkingHours(kyivHour) {

    const h = Number(kyivHour);

    if (!Number.isFinite(h)) return true;

    return h >= CHAT_HOURS.from && h < CHAT_HOURS.to;

}

// Що сайт показує під полем вводу.
export function chatGreeting(kyivHour) {

    return withinWorkingHours(kyivHour)
        ? "Зазвичай відповідаємо за кілька хвилин."
        : "Зараз неробочий час — відповімо зранку, з 9:00.";

}
