                g.gain.exponentialRampToValueAtTime(0.07, t + 0.02);
                g.gain.exponentialRampToValueAtTime(0.0001, t + 0.18);

                o.connect(g);
                g.connect(звук.destination);

                o.start(t);
                o.stop(t + 0.2);

